import { route } from "preact-router";

/**
 * Глубина текущей записи истории внутри нашей сессии: сколько НАШИХ записей
 * осталось позади. 0 — мы на той записи, с которой человек вошёл на сайт.
 *
 * Считать переходы, как здесь было раньше, нельзя: `onChange` роутера срабатывает
 * и на «Назад» тоже, а счётчик только рос. Пройдя раздел → карточку → «Назад»,
 * человек оказывался на записи, позади которой уже ничего нашего нет, но счётчик
 * показывал три перехода, и следующее «Назад» уводило на предыдущий ДОКУМЕНТ
 * вкладки. Для пришедших из RSS это буквально `/rss.xml` — сырой XML вместо
 * сайта.
 */
let depth = 0;

/** Был ли уже начальный рендер: он не переход и глубину не увеличивает. */
let started = false;

/** Ключ метки в `history.state`. Чужие поля состояния сохраняем как есть. */
const DEPTH_KEY = "__delabsNavDepth";

interface HistoryLike {
  state: unknown;
  replaceState(state: unknown, unused: string): void;
  back(): void;
  length: number;
}

function defaultHistory(): HistoryLike | null {
  return typeof window === "undefined" ? null : (window.history as HistoryLike);
}

function readDepth(h: HistoryLike | null): number | null {
  const s = h?.state as Record<string, unknown> | null | undefined;
  const d = s?.[DEPTH_KEY];
  return typeof d === "number" && Number.isFinite(d) && d >= 0 ? d : null;
}

/**
 * Куда мы поехали. `initial` — первый рендер вкладки (в том числе после F5),
 * `forward` — новая запись истории, `returning` — «Назад»/«Вперёд» на запись,
 * где уже были.
 *
 * Направление нужно не только глубине: браузер сам восстанавливает положение
 * прокрутки при возврате и после перезагрузки, и тому, кто листает список,
 * нельзя это восстановление затирать (см. App.tsx).
 */
export type NavDirection = "initial" | "forward" | "returning";

/**
 * Вызывается из `onChange` роутера — единственного места, где адрес меняется.
 *
 * Направление перехода роутер не сообщает, но его можно прочитать из самой
 * истории. Свою глубину мы штампуем в `history.state` каждой созданной записи;
 * `pushState` роутера состояние не переносит, поэтому отсутствие метки — это
 * ровно «запись новая, мы ушли вперёд», а наличие — «вернулись (или прошли
 * вперёд) на запись, где уже были», и там глубина записана точная.
 *
 * Побочно это чинит перезагрузку: `history.state` переживает F5, поэтому после
 * обновления страницы на третьем шаге «Назад» по-прежнему знает, что позади две
 * наши записи, — раньше счётчик обнулялся и кнопка деградировала до перехода на
 * раздел.
 */
export function markNavigation(h: HistoryLike | null = defaultHistory()): NavDirection {
  const stamped = readDepth(h);
  const first = !started;
  let direction: NavDirection;
  if (stamped !== null) {
    depth = stamped;
    direction = first ? "initial" : "returning";
  } else {
    if (started) depth += 1;
    const prev = (h?.state as Record<string, unknown> | null) ?? {};
    try {
      h?.replaceState({ ...prev, [DEPTH_KEY]: depth }, "");
    } catch {
      // replaceState умеет бросать на «about:», в песочнице iframe и при
      // превышении лимита вызовов. Глубина в модуле уже посчитана — в пределах
      // этой вкладки навигация продолжит работать, потеряется только устойчивость
      // к перезагрузке. Ронять из-за этого рендер незачем.
    }
    direction = first ? "initial" : "forward";
  }
  started = true;
  return direction;
}

/**
 * Увести страницу наверх — но только там, где это наше дело.
 *
 * Решение живёт здесь, а не в обработчике роутера, ровно чтобы быть под тестом:
 * в `App.tsx` это одна строка без условия, и забыть условие там больше негде.
 *
 * `forward` — новая запись истории, положения для неё не существует, наверх
 * уводим мы. `returning` и `initial` — положение уже восстановил браузер
 * (`history.scrollRestoration` по умолчанию `'auto'`), и трогать его нельзя:
 * именно это затирание возвращало в начало ленты того, кто отмотал её до
 * середины и открыл карточку.
 */
export function scrollForNavigation(
  direction: NavDirection,
  scrollTop: () => void = () => window.scrollTo({ top: 0 }),
): void {
  if (direction === "forward") scrollTop();
}

/** Только для тестов: сбросить состояние между сценариями. */
export function resetNavigations(): void {
  depth = 0;
  started = false;
}

/** Сколько наших записей истории позади текущей. */
export function navigationDepth(): number {
  return depth;
}

/**
 * Решение «Назад»: уходим по истории браузера или ведём на запасной адрес.
 *
 * Признаком «пришли изнутри» когда-то был `document.referrer`. Он отвечает на
 * другой вопрос — как был загружен ДОКУМЕНТ, — и при pushState не обновляется,
 * то есть в SPA остаётся тем же самым до конца жизни вкладки. Заменивший его
 * счётчик переходов ошибался в другую сторону (см. `depth` выше). Глубина
 * отвечает ровно на нужный вопрос: есть ли позади наша собственная запись.
 */
export function shouldGoBack(navDepth: number): boolean {
  return navDepth > 0;
}

/**
 * Возврат «Назад» для детальных страниц. При прямом заходе по ссылке ведём на
 * `fallback`, чтобы не выкинуть человека со страницы наружу.
 */
export function goBackOr(fallback: string, h: HistoryLike | null = defaultHistory()): void {
  if (h && shouldGoBack(depth)) h.back();
  else route(fallback);
}

/** Клик, после которого текущая страница остаётся на месте. */
export interface ModifiedClick {
  metaKey?: boolean;
  ctrlKey?: boolean;
  shiftKey?: boolean;
  altKey?: boolean;
  button?: number;
}

/**
 * Откроет ли этот клик ссылку где-то ещё, оставив текущую страницу как есть.
 *
 * Пункты меню закрывали ящик по любому клику. Но cmd-клик (ctrl в Windows),
 * shift и средняя кнопка открывают ссылку в новой вкладке или окне: человек
 * остаётся на той же странице, с тем же меню, — а меню под ним схлопывалось.
 * Открыть три раздела в фоновых вкладках, что и есть обычный способ читать
 * такой сайт, становилось невозможно: после первого же cmd-клика ящик исчезал.
 */
export function opensElsewhere(e: ModifiedClick): boolean {
  return Boolean(
    e.metaKey || e.ctrlKey || e.shiftKey || e.altKey || (e.button ?? 0) !== 0,
  );
}

/**
 * Путь без query и хэша — для сравнения «в каком мы разделе».
 *
 * `url` от роутера это pathname + search, поэтому подсветка раздела вместе с
 * `aria-current` пропадала на любом адресе с параметрами: ровно на тех ссылках,
 * ради которых редизайн и вынес фильтры в адрес, и на всём, что приходит с
 * utm-хвостом.
 */
export function sectionPath(url: string): string {
  return url.split(/[?#]/)[0];
}

/**
 * Гасить ли клик по пункту меню: мы уже в этом разделе.
 *
 * Роутер адрес с текущим не сравнивает — `route()` кладёт запись в историю
 * всегда. А `onChange`, из которого зовётся `markNavigation`, срабатывает
 * только когда адрес изменился. Клик по своему же разделу попадает ровно в
 * зазор между этими двумя правилами и ломает обе стороны:
 *
 * - с параметрами в адресе (`/drops?status=live` → `/drops`) фильтр из адреса
 *   исчезает, а список остаётся прежним: секция не перемонтируется, читать
 *   адрес заново некому. Дальше адрес врёт — скопированная ссылка и F5
 *   покажут другое;
 * - без параметров адрес не меняется вовсе, поэтому запись в истории остаётся
 *   без метки глубины. Позже «Назад» на неё читается как «ушли вперёд» — с
 *   прокруткой наверх поверх той, что браузер только что восстановил.
 *
 * Модифицированный клик не гасим: он открывает вкладку, а не переходит, и
 * отняв его, мы отняли бы единственный способ открыть текущий раздел рядом.
 *
 * Решение живёт здесь, а не в обработчике шапки, чтобы быть под тестом.
 */
export function swallowsNavClick(
  e: ModifiedClick,
  currentUrl: string,
  href: string,
): boolean {
  if (opensElsewhere(e)) return false;
  return sectionPath(currentUrl) === href;
}
