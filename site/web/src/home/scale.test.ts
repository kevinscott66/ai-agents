/**
 * Главная перестраивается с четырёх одинаковых сеток карточек на четыре разные
 * формы (T-742). Разблокировки при этом перестают быть таблицей и становятся
 * временно́й осью: «через сколько» + полоса, длина которой пропорциональна
 * сумме. Обе величины считаются здесь, и обе легко испортить незаметно.
 *
 * Что проверяем:
 *
 *  • «через сколько» считается по КАЛЕНДАРНЫМ суткам, а не по 24-часовым
 *    окнам. Разблокировка сегодня в 23:50 и завтра в 00:10 разнесены на 20
 *    минут, но это «сегодня» и «завтра» — для читателя это разные дни.
 *    Деление разницы миллисекунд на 86400000 обе назвало бы «сегодня».
 *  • переход через смену времени (в РФ её нет, но пояс задаёт браузер
 *    читателя) не сдвигает счёт на сутки — 23- и 25-часовые сутки округляются
 *    к ближайшему целому, а не режутся вниз.
 *  • длина полосы нормируется по максимуму видимого окна, а не по абсолютной
 *    шкале: в списке из пяти событий важно соотношение между ними.
 *  • сумма может быть null (DefiLlama не отдаёт её для части событий) — тогда
 *    полосы нет вовсе, а не полосы нулевой/NaN-длины, из-за которой строка
 *    молча уезжает в 0 или на всю ширину.
 *  • ненулевая, но крошечная на фоне максимума сумма всё равно получает
 *    видимый минимум: иначе «$3 млн против $2 млрд» рисуется как пустота и
 *    выглядит как отсутствие данных.
 */
import { describe, expect, test } from "bun:test";
import { axisTone, daysUntil, magnitudes, relativeDay } from "./scale";

const at = (s: string) => new Date(s);

describe("daysUntil — календарные сутки, не 24-часовые окна", () => {
  test("сегодня поздно вечером и завтра сразу после полуночи — разные дни", () => {
    const now = at("2026-08-12T23:50:00Z");
    expect(daysUntil("2026-08-12T23:59:00Z", now)).toBe(0);
    expect(daysUntil("2026-08-13T00:10:00Z", now)).toBe(1);
  });

  test("тот же день, но раньше по времени — это ноль, а не минус один", () => {
    expect(daysUntil("2026-08-12T02:00:00Z", at("2026-08-12T22:00:00Z"))).toBe(0);
  });

  test("прошедшая дата даёт отрицательное число", () => {
    expect(daysUntil("2026-08-10T12:00:00Z", at("2026-08-12T12:00:00Z"))).toBe(-2);
  });

  test("невалидная дата — null, а не NaN", () => {
    expect(daysUntil("не дата", at("2026-08-12T12:00:00Z"))).toBeNull();
  });

  test("счёт через месяц и через год не сбивается", () => {
    expect(daysUntil("2026-09-01T00:00:00Z", at("2026-08-12T00:00:00Z"))).toBe(20);
    expect(daysUntil("2027-08-12T00:00:00Z", at("2026-08-12T00:00:00Z"))).toBe(365);
  });
});

describe("relativeDay — подпись на оси", () => {
  const now = at("2026-08-12T09:00:00Z");

  test("нулевой и первый день названы словами", () => {
    expect(relativeDay("2026-08-12T20:00:00Z", now)).toBe("сегодня");
    expect(relativeDay("2026-08-13T06:00:00Z", now)).toBe("завтра");
  });

  test("русская плюрализация дней", () => {
    expect(relativeDay("2026-08-14T00:00:00Z", now)).toBe("через 2 дня");
    expect(relativeDay("2026-08-17T00:00:00Z", now)).toBe("через 5 дней");
    expect(relativeDay("2026-08-23T00:00:00Z", now)).toBe("через 11 дней");
  });

  test("дальше двух недель подпись пустая — там дата говорит сама за себя", () => {
    expect(relativeDay("2026-09-30T00:00:00Z", now)).toBe("");
  });

  test("прошедшее и мусор не притворяются будущим", () => {
    expect(relativeDay("2026-08-01T00:00:00Z", now)).toBe("");
    expect(relativeDay("", now)).toBe("");
  });
});

/**
 * Аудит 2026-08-13: комментарий в `.axis-row::before` описывал раскраску узла
 * по близости события, а правил под него не было — все пять узлов на оси
 * рисовались одинаково серыми. Цвет узла ставится тем же правилом, что и
 * словесная подпись слева: цвет дублирует текст, а не заменяет его.
 */
describe("axisTone — цвет узла на оси", () => {
  const now = new Date("2026-08-13T10:00:00.000Z");

  test("сегодня — акцент", () => {
    expect(axisTone("2026-08-13T00:00:00.000Z", now)).toBe("is-today");
  });

  test("ближайшие две недели — янтарь", () => {
    expect(axisTone("2026-08-14T00:00:00.000Z", now)).toBe("is-soon");
    expect(axisTone("2026-08-26T00:00:00.000Z", now)).toBe("is-soon");
  });

  test("дальше двух недель, прошедшее и мусор — без класса", () => {
    expect(axisTone("2026-08-27T00:00:00.000Z", now)).toBe("");
    expect(axisTone("2026-08-12T00:00:00.000Z", now)).toBe("");
    expect(axisTone("не дата", now)).toBe("");
  });

  test("цвет есть ровно тогда, когда есть подпись", () => {
    for (const iso of [
      "2026-08-13T00:00:00.000Z",
      "2026-08-14T00:00:00.000Z",
      "2026-08-26T00:00:00.000Z",
      "2026-08-27T00:00:00.000Z",
      "2026-08-01T00:00:00.000Z",
      "не дата",
    ]) {
      expect(axisTone(iso, now) !== "").toBe(relativeDay(iso, now) !== "");
    }
  });
});

describe("magnitudes — длина полосы", () => {
  test("нормировка по максимуму окна", () => {
    expect(magnitudes([100, 50, 25])).toEqual([1, 0.5, 0.25]);
  });

  test("null и не-числа не рисуют полосу вовсе", () => {
    expect(magnitudes([100, null, undefined, NaN, -5])).toEqual([1, 0, 0, 0, 0]);
  });

  test("окно без сумм не даёт NaN и не растягивает всё на всю ширину", () => {
    expect(magnitudes([null, null])).toEqual([0, 0]);
    expect(magnitudes([])).toEqual([]);
  });

  test("крошечная на фоне максимума сумма остаётся видимой", () => {
    const [big, tiny] = magnitudes([2_000_000_000, 3_000_000]);
    expect(big).toBe(1);
    // 0.0015 от максимума — на 600 пикселях это меньше пикселя, то есть
    // «данных нет» на вид. Пол в 6% читается как «мало», а не как «пусто».
    expect(tiny).toBeGreaterThanOrEqual(0.06);
    expect(tiny).toBeLessThan(0.1);
  });

  test("единственное событие занимает полосу целиком", () => {
    expect(magnitudes([42])).toEqual([1]);
  });
});

/**
 * Пояс читателя не должен двигать сутки. Даты разблокировок привязаны к
 * полуночи UTC, и до фикса читатель в Нью-Йорке видел «сегодня» и «5 февр.»
 * там, где источник (и читатель в Москве) говорит «завтра, 6 февр.».
 *
 * Проверяется в подпроцессе: Intl-форматтеры создаются на импорте модуля, и
 * подменить TZ внутри уже запущенного процесса нельзя.
 */
describe("пояс читателя не сдвигает календарные сутки", () => {
  const snippet = `
    const { relativeDay } = await import(${JSON.stringify(`${import.meta.dir}/scale.ts`)});
    const { formatDateShort } = await import(${JSON.stringify(`${import.meta.dir}/../format.ts`)});
    const now = new Date("2026-02-05T12:00:00.000Z");
    const when = "2026-02-06T00:00:00.000Z";
    console.log(JSON.stringify([relativeDay(when, now), formatDateShort(when, now)]));
  `;

  const inZone = (tz: string): string[] => {
    const p = Bun.spawnSync(["bun", "-e", snippet], {
      env: { ...process.env, TZ: tz },
    });
    if (p.exitCode !== 0) throw new Error(p.stderr.toString());
    return JSON.parse(p.stdout.toString().trim());
  };

  test("Москва (UTC+3) и Нью-Йорк (UTC-5) читают одно и то же", () => {
    const msk = inZone("Europe/Moscow");
    const nyc = inZone("America/New_York");
    expect(msk[0]).toBe("завтра");
    expect(msk[1]).toContain("6");
    expect(nyc).toEqual(msk);
  });
});
