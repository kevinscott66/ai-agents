/**
 * Адрес, который не уронит роутер.
 *
 * preact-router при сопоставлении маршрута декодирует и параметры пути
 * (`decodeURIComponent` по сегменту), и КАЖДУЮ пару из query-строки — всё без
 * try/catch. Любой битый percent-escape в адресе поэтому кидает URIError прямо
 * из render, а границы ошибок в приложении не было: страница оставалась
 * пустой, белой.
 *
 * Задевает это не только статьи: query-строка разбирается на любом маршруте,
 * то есть `/?utm=%` роняет и главную. Хвост `%` в ссылке — обычное дело:
 * обрезанный при пересылке адрес, кривой трекер, ручная правка.
 *
 * Чинить внутри библиотеки нечего, поэтому чиним вход: если адрес не
 * декодируется, считаем все `%` в нём литеральными и экранируем их. Тогда
 * `/digest/%` — просто статья с id «%», её нет, и пользователь видит обычное
 * «такого дайджеста нет» вместо белого экрана. Сервер с 2026-08-12 отвечает
 * на такой id ровно так же (site/server/index.ts, decodeIdSegment).
 *
 * Проверка одним decodeURIComponent по всей строке эквивалентна проверке по
 * кускам: разделители (`/`, `&`, `=`) — литеральные ASCII, многобайтовая
 * последовательность через них не переносится.
 */
export function safeRouterUrl(url: string): string {
  try {
    decodeURIComponent(url);
    return url;
  } catch {
    return url.replace(/%/g, "%25");
  }
}

/** Текущий адрес для роутера: путь + query, уже безопасный. */
export function currentSafeUrl(): string | undefined {
  if (typeof window === "undefined") return undefined;
  return safeRouterUrl(window.location.pathname + window.location.search);
}
