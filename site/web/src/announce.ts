import { plural } from "./format";
import type { PagedStatus } from "./usePagedList";

export interface AnnounceInput {
  status: PagedStatus;
  /** Запрос, по которому реально загружено (не то, что сейчас набрано в поле). */
  query: string;
  /** Сколько карточек на экране. */
  shown: number;
  /** Сколько всего насчитал сервер. */
  total: number;
  /** Есть ли что догружать — тот же признак, по которому рисуется кнопка. */
  hasMore: boolean;
  /** Трогал ли человек поиск или «Показать ещё» с момента открытия страницы. */
  interacted: boolean;
}

/**
 * Текст живой области (`role="status"`) раздела «Дайджесты».
 *
 * Аудит 2026-08-13 нашёл здесь три отдельных дефекта, и все они видны только
 * тому, кто слушает страницу, а не смотрит на неё:
 *
 * 1. Число найденного бралось из `shown` — длины загруженной страницы. При 40
 *    совпадениях и странице в 6 объявлялось «найдено дайджестов: 6», то есть
 *    прямая неправда о размере выдачи, и ровно в тот момент, когда человек
 *    решает, уточнять запрос или нет.
 *
 * 2. Область заполнялась сразу при монтировании: первая же смена «Загрузка
 *    дайджестов» → «Показано дайджестов: 6 из 6» объявлялась вслух, хотя
 *    человек только открыл страницу и ничего не просил. Живая область должна
 *    сообщать об изменениях, а не зачитывать исходное состояние — его
 *    скринридер прочитает сам при обходе.
 *
 * 3. `shown из total` печаталось без всяких условий, а величины эти разной
 *    природы: `shown` копится на клиенте, `total` приходит с каждым ответом
 *    заново. Стоит удалить запись между двумя страницами — и на экране
 *    появляется «Показано дайджестов: 6 из 4». Здесь «из total» пишется только
 *    когда есть что догружать, а в этом случае `shown < total` выполняется по
 *    построению `hasMore`.
 */
export function digestsAnnouncement(a: AnnounceInput): string {
  if (!a.interacted) return "";
  if (a.status === "loading") return "Загрузка дайджестов";
  if (a.status === "error") return "Не удалось загрузить дайджесты";

  const noun = (n: number) => plural(n, "дайджест", "дайджеста", "дайджестов");

  if (a.query) {
    // Найдено не может быть меньше показанного, чем бы ни разошлись счётчики.
    const found = Math.max(a.total, a.shown);
    if (found === 0) return `По запросу «${a.query}» ничего не найдено`;
    return `По запросу «${a.query}» найдено: ${found} ${noun(found)}`;
  }

  if (a.shown === 0) return "";
  if (a.hasMore) return `Показано ${a.shown} из ${a.total} ${noun(a.total)}`;
  return `Показано ${a.shown} ${noun(a.shown)} — это все`;
}
