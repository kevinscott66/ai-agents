/**
 * Аудит 2026-08-13: кнопка сортировки размонтировалась от собственного клика.
 *
 * Вся таблица разблокировок лежала под `items.length > 0`, а `usePagedList`
 * чистит список СИНХРОННО при перезагрузке с нулевого смещения (`setItems([])`
 * в `load`) — специально, чтобы «Показать ещё» не просила offset от чужой
 * выборки. Значит на каждый клик по «Дате» и на каждую смену чипа `<thead>`
 * исчезал вместе с кнопкой, по которой только что кликнули: фокус улетал на
 * `body`, второй Enter подряд не делал ничего, порядок с клавиатуры туда-обратно
 * не переключался, шапка моргала.
 *
 * Инвариант: пока в разделе уже были строки, рамка таблицы с шапкой остаётся на
 * месте (`reloading`), а скелет едет внутрь `<tbody>`. Первой загрузки это не
 * касается — сохранять там нечего, и полноразмерный скелет честнее пустой рамки.
 *
 * Тест — на чистой функции, а не на DOM: рендерера в проекте нет (см. шапку
 * `paged-list.test.ts`), тот же приём, что в `about-claims.test.ts`.
 */
import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { unlocksView } from "./UnlocksSection";

const SRC = readFileSync(join(import.meta.dir, "UnlocksSection.tsx"), "utf8");

describe("unlocksView: что рисовать в теле раздела", () => {
  test("первая загрузка — полноразмерный скелет", () => {
    expect(unlocksView("loading", 0, false)).toBe("skeleton");
  });

  test("перезагрузка после строк — таблица остаётся, скелет внутри", () => {
    // Ровно тот кадр, что ломался: клик по сортировке уже очистил items,
    // ответ ещё не пришёл. `hadRows` — память о том, что шапку есть что беречь.
    expect(unlocksView("loading", 0, true)).toBe("reloading");
  });

  test("пришли строки — обычная таблица", () => {
    expect(unlocksView("success", 12, true)).toBe("rows");
    expect(unlocksView("success", 12, false)).toBe("rows");
  });

  test("догрузка следующей страницы не гасит уже показанное", () => {
    // status="more" при непустом списке — «Показать ещё» в работе. Ветка
    // reloading сюда попасть не должна: строки на экране, чистить нечего.
    expect(unlocksView("more", 30, true)).toBe("rows");
  });

  test("пусто в окне фильтра — пустое состояние, а не рамка таблицы", () => {
    // Даже когда строки были: пустая рамка со шапкой и без единой строки
    // читается как поломка, а выйти из окна нужно чипом — он остаётся.
    expect(unlocksView("success", 0, true)).toBe("empty");
    expect(unlocksView("success", 0, false)).toBe("empty");
  });

  test("ошибка сильнее всего остального", () => {
    expect(unlocksView("error", 0, true)).toBe("error");
    expect(unlocksView("error", 0, false)).toBe("error");
  });

  test("сбой догрузки не сносит уже показанный календарь", () => {
    // `usePagedList` ставит `error` и на провал первой страницы, и на провал
    // `loadMore`; различает их только наличие строк. Со строками на экране
    // блок `ErrorState` с «загрузить заново» — не то лекарство: перезагружать
    // нечего, нужна строка «дальше не подгрузилось» под таблицей.
    expect(unlocksView("error", 12, true)).toBe("rows");
  });
});

describe("UnlocksSection: ветка reloading доехала до разметки", () => {
  test("шапка и кнопка сортировки живут в обеих ветках", () => {
    // Проверка формы источника: без неё функция может остаться правильной, а
    // JSX — вернуться к `items.length > 0`, и дефект тихо воскреснет.
    expect(SRC).toMatch(/\{\(view === "rows" \|\| view === "reloading"\)/);
    expect(SRC).not.toMatch(/\{items\.length > 0 && \(/);
  });

  test("чипы не исчезают на перезагрузке", () => {
    // Чип — второй орган управления той же выборкой; спрятать его на
    // полсекунды означает ту же потерю фокуса, что и с кнопкой сортировки.
    // В main этот же инвариант доведён дальше: `loadedOnce` из `usePagedList`
    // не сбрасывается на `load(0)`, поэтому чипы, показавшись однажды, не
    // исчезают уже никогда. Ветка `view === "reloading"` покрывала только
    // случай, когда строки хоть раз приходили; окно фильтра, пустое с самого
    // начала, оставалось без единого органа управления — выйти из него нечем.
    expect(SRC).toMatch(/const showFilters = loadedOnce;/);
  });

  test("перезагрузка объявлена вслух", () => {
    // Фокус мы теперь специально не уводим — значит о смене выборки
    // скринридеру сообщает только aria-busy.
    expect(SRC).toMatch(/aria-busy=\{view === "reloading"\}/);
  });
});
