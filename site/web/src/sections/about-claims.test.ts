/**
 * Аудит 2026-08-12: страница «О проекте» обещала читателю ручную работу,
 * которой нет.
 *
 * Два места говорили одно и то же:
 *
 *   about-card «Откуда данные»: «Дайджесты — кураторские: читаем
 *   первоисточники сами и оставляем ссылку на каждый»
 *   FAQ «Откуда берутся данные?»: «Дайджесты собираем вручную»
 *
 * Дайджесты собирает команда агентов: роль ищет источники через web_search,
 * copy пишет текст, публикация уходит в канал и на сайт через ингест. Человек
 * в цепочке один раз — на аппруве черновика перед публикацией. «Читаем
 * первоисточники сами» — не преувеличение формулировки, а неверное
 * утверждение о том, кто и что делает, причём ровно там, где сайт просит
 * доверия («чтобы ты мог проверить, а не верить на слово»).
 *
 * Инвариант: страница не заявляет ручную/кураторскую сборку дайджестов, и при
 * этом сохраняет то, что правда, — ссылку на первоисточник у каждого пункта.
 */
import { describe, expect, test } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";

const SRC = readFileSync(join(import.meta.dir, "AboutSection.tsx"), "utf8");

describe("AboutSection: обещания страницы «О проекте»", () => {
  test("нет заявки на ручную сборку дайджестов", () => {
    for (const claim of [
      /собираем вручную/,
      /кураторск/i,
      /читаем первоисточники сами/,
    ]) {
      expect({ claim: String(claim), found: claim.test(SRC) }).toEqual({
        claim: String(claim),
        found: false,
      });
    }
  });

  test("сказано, что дайджесты собирают агенты", () => {
    expect(SRC).toMatch(/агент/i);
  });

  test("обещание ссылки на первоисточник осталось — оно правдиво", () => {
    expect(SRC).toMatch(/первоисточник/);
  });

  test("человек в цепочке назван честно: аппрув перед публикацией", () => {
    expect(SRC).toMatch(/публикаци/i);
  });
});
