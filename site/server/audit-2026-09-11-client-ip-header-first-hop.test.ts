/**
 * Аудит 2026-09-11, круг 51: заголовок, заданный владельцем, читался с ЛЕВОГО
 * конца — с того самого, который в соседней ветке той же функции объявлен
 * подконтрольным клиенту.
 *
 * Две ветки `clientIpKey` разбирают одну и ту же форму данных (список адресов
 * через запятую) прямо противоположным образом:
 *
 *   - XFF: `hops[hops.length - trustedHops]` — отсчёт с конца, потому что
 *     `proxy_add_x_forwarded_for` ДОПИСЫВАЕТ remote_addr справа, а всё левее
 *     прислал клиент (это утверждает и тест proxy-header-trust.test.ts);
 *   - заголовок владельца: `direct.split(",")[0]` — первый элемент, то есть
 *     ровно тот, который в первой ветке считается поддельным.
 *
 * Оправдание стояло в комментарии: «заданный владельцем заголовок содержит
 * ровно один адрес». Для `cf-connecting-ip` это правда, и там обе трактовки
 * совпадают. Но значение переменной — это строка в .env, а не тип, и докблок
 * `clientIpKey` сам подсказывает читателю худший вариант: «пустое значение
 * сохраняет прежнее поведение — последний элемент X-Forwarded-For». Владелец,
 * который выпишет то же самое явно (`SITE_CLIENT_IP_HEADER=x-forwarded-for`),
 * ждёт неизменности, а получает разворот доверия на 180°.
 *
 * Замер до правки, пир петлевой, XFF `1.1.1.1, 198.51.100.7`:
 *   без переменной                     → ip:198.51.100.7  (адрес от nginx)
 *   SITE_CLIENT_IP_HEADER=x-forwarded-for → ip:1.1.1.1     (адрес от клиента)
 * Второй ключ клиент выбирает сам и меняет на каждый запрос: 300 запросов —
 * 300 вёдер, лимитера нет вовсе.
 *
 * Тот же разворот получается и без ошибки в .env: если vhost заголовок не
 * перезаписывает, а дописывает (или клиент пришлёт его дважды — Headers.get
 * склеит значения через запятую), первым элементом окажется присланное
 * клиентом. Об этой второй линии обороны говорит докблок `claimedIpKey`, но
 * держалась она только на «ровно один адрес».
 *
 * Правка: обе ветки берут адрес одним и тем же способом — с правого конца, с
 * учётом SITE_TRUSTED_PROXY_HOPS. Для однозначного заголовка (один адрес)
 * левый и правый конец совпадают, поэтому рабочая конфигурация с
 * `cf-connecting-ip` не меняется ничем.
 */
import { describe, expect, test, beforeEach, afterEach } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import {
  clientIpKey,
  CLAIMED_LOOPBACK_KEY,
  _rateLimitOk,
  _resetRateLimiter,
} from "./index.ts";

const SRC = readFileSync(join(import.meta.dir, "index.ts"), "utf8");
const LOOPBACK = "127.0.0.1";

beforeEach(_resetRateLimiter);
afterEach(_resetRateLimiter);

describe("заголовок владельца читается с того же конца, что и XFF", () => {
  test("список в заголовке — берётся правый элемент, а не левый", () => {
    // Когда падает: не менять ожидание на "1.1.1.1". Левый элемент в списке
    // адресов прислал клиент — это утверждает соседняя ветка той же функции.
    expect(clientIpKey(null, LOOPBACK, "1.1.1.1, 198.51.100.7")).toBe(
      "ip:198.51.100.7",
    );
  });

  test("SITE_CLIENT_IP_HEADER=x-forwarded-for — действительно то же самое", () => {
    // Именно это обещает докблок про «прежнее поведение». Оба вызова
    // изображают один запрос: слева переменная не задана, справа задана
    // именем того же заголовка, значение одно и то же.
    const xff = "1.1.1.1, 2.2.2.2, 198.51.100.7";
    expect(clientIpKey(xff, LOOPBACK, xff)).toBe(clientIpKey(xff, LOOPBACK));
  });

  test("дубль заголовка от клиента не перебивает значение прокси", () => {
    // Headers.get склеивает одноимённые заголовки через ", ": клиент прислал
    // свой CF-Connecting-IP, CF/nginx дописал настоящий.
    expect(clientIpKey(null, LOOPBACK, "9.9.9.9, 198.51.100.7")).toBe(
      "ip:198.51.100.7",
    );
  });

  test("SITE_TRUSTED_PROXY_HOPS действует и на заголовок владельца", () => {
    // Два своих слоя (CDN → nginx → сюда): берётся предпоследний.
    expect(clientIpKey(null, LOOPBACK, "1.1.1.1, 198.51.100.7, 10.0.0.2", 2)).toBe(
      "ip:198.51.100.7",
    );
  });

  test("рабочая конфигурация с одним адресом не изменилась", () => {
    // Ради чего переменная и заводилась: у cf-connecting-ip элемент один,
    // левый конец совпадает с правым.
    expect(clientIpKey(null, LOOPBACK, "198.51.100.7")).toBe("ip:198.51.100.7");
    expect(clientIpKey(null, LOOPBACK, "  198.51.100.7  ")).toBe("ip:198.51.100.7");
  });

  test("граница доверия не сдвинулась: посторонний пир — заголовков нет", () => {
    expect(clientIpKey(null, "203.0.113.9", "1.1.1.1, 198.51.100.7")).toBe(
      "ip:203.0.113.9",
    );
  });

  test("пустой заголовок по-прежнему уступает XFF", () => {
    // `direct` пустой строкой — это «заголовка не было», а не «адрес пуст».
    expect(clientIpKey("1.1.1.1, 198.51.100.7", LOOPBACK, "   ")).toBe(
      "ip:198.51.100.7",
    );
  });

  test("«я — петля» в заголовке сводится в отдельное ведро", () => {
    // Вторая линия из докблока claimedIpKey: теперь она смотрит на тот же
    // элемент, который действительно станет ключом.
    expect(clientIpKey(null, LOOPBACK, "9.9.9.9, 127.0.0.1")).toBe(
      CLAIMED_LOOPBACK_KEY,
    );
    expect(clientIpKey(null, LOOPBACK, "127.0.0.1, 198.51.100.7")).toBe(
      "ip:198.51.100.7",
    );
  });
});

describe("замер: лимитер остаётся лимитером", () => {
  test("300 запросов с крутящимся левым элементом упираются в лимит", () => {
    // Атакующий меняет ровно то, что может менять, — свою часть списка.
    // Правый элемент дописал прокси, он один и тот же, значит и ведро одно.
    let passed = 0;
    for (let i = 0; i < 300; i++) {
      const forged = `10.${i >> 8}.${i & 255}.1`;
      if (_rateLimitOk(clientIpKey(null, LOOPBACK, `${forged}, 198.51.100.7`))) {
        passed++;
      }
    }
    // Ёмкость ведра — 60 токенов в минуту; точное число зависит от того,
    // сколько миллисекунд заняли 300 итераций, поэтому меряем порядок.
    expect(passed).toBeGreaterThan(0);
    expect(passed).toBeLessThan(100);
  });

  test("настоящие разные адреса по-прежнему получают свои вёдра", () => {
    // Обратная сторона: правка не должна слепить всех в одно ведро.
    let passed = 0;
    for (let i = 0; i < 100; i++) {
      if (_rateLimitOk(clientIpKey(null, LOOPBACK, `203.0.113.${i}`))) passed++;
    }
    expect(passed).toBe(100);
  });
});

describe("текст больше не обещает «ровно один адрес»", () => {
  test("оправдания левого конца в исходнике не осталось", () => {
    const flat = SRC.replace(/^\s*\*/gm, "").replace(/\s+/g, " ");
    // Когда падает: фраза вернулась вместе с разбором по первому элементу.
    // Значение переменной — строка в .env, гарантировать её форму нечем.
    expect(flat).not.toContain("содержит ровно один адрес");
  });

  test("докблок называет разворот доверия своим именем", () => {
    const flat = SRC.replace(/^\s*\*/gm, "").replace(/\s+/g, " ");
    expect(flat).toContain("с правого конца");
  });
});
