/**
 * Разделы сайта, на которые ссылается канальный пост.
 *
 * Зачем список, а не ссылка на страницу выпуска. До 21.09.2026 каждый пункт
 * дайджеста вёл на `${base}/digest/${siteId}`, а id выдавал прежний backend
 * сайта: approve-poll создавал страницу ингестом ДО публикации и получал в
 * ответ её адрес. Того backend'а больше нет — хост из `SITE_INGEST_URL` не
 * резолвится, — а живой сайт устроен наоборот: страницы `/digest/[slug]`
 * строятся из корпуса, который догоняется из снапшота канала уже ПОСЛЕ поста.
 * То есть адрес страницы выпуска в момент публикации не существует нигде, и
 * «Подробнее →» обещало бы читателю то, чего нет.
 *
 * Поэтому пост ведёт на СПИСКИ — они существуют всегда и не зависят от того,
 * успел ли редакторский таймер пересобрать корпус.
 *
 * ## Откуда взяты адреса и подписи
 *
 * Это зеркало `src/components/navigation/nav.ts` из репозитория сайта — там
 * сказано «единственный источник правды по навигации», и шапка, меню и подвал
 * берут разделы оттуда. Здесь копия, потому что репозитории разные и импорта
 * между ними нет.
 *
 * Копия обязана быть заметной при расхождении: список закрыт тестом
 * (`tests/delabs-sections.test.ts`), так что переименование раздела на сайте
 * не «тихо ломает ссылки в канале», а требует правки здесь и видно в ревью.
 * Сверено 21.09.2026 — все шесть адресов отвечали 200 на живом сайте.
 *
 * Проверены и отвергнуты в тот же день: `/partners` и `/airdrop` дают 404.
 * Раздачи живут на `/drops`, а у партнёров есть только одна страница
 * (`/partners/the-trends-vi`), списка нет — ставить их в пост нельзя.
 */
export interface DelabsSection {
  href: string;
  label: string;
}

/** Порядок — как в шапке сайта. */
export const DELABS_SECTIONS: readonly DelabsSection[] = [
  { href: "/digest", label: "Дайджест" },
  { href: "/drops", label: "Дропы" },
  { href: "/activities", label: "Активности" },
  { href: "/unlocks", label: "Анлоки" },
  { href: "/projects", label: "Проекты" },
  { href: "/ai", label: "AI" },
];

/**
 * Строка разделов для поста: `Разделы: [Дайджест](…) · [Дропы](…) · …`.
 *
 * Отдельной функцией, а не константой: база берётся из `DELABS_SITE_BASE`,
 * и в тестах она другая.
 */
export function sectionsLine(base: string): string {
  const links = DELABS_SECTIONS.map((s) => `[${s.label}](${base}${s.href})`);
  return `Разделы: ${links.join(" · ")}`;
}
