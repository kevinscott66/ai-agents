/**
 * Обрезка строки, не разваливающая суррогатную пару.
 *
 * `slice` считает единицы UTF-16. Астральный символ — эмодзи, иероглиф из
 * SIP — занимает две, и граница среза проходит между ними в одном случае из
 * двух: в хвосте остаётся одинокий ВЫСОКИЙ суррогат (U+D800..U+DBFF). Дальше
 * он не безобиден. В Telegram человек видит ромб вместо символа; в SQLite
 * такой хвост склеивается со следующей записью (разбор — `svg-render.ts`); в
 * `JSON.stringify` уезжает в мост (`mac-bridge.ts`); Resvg отвергает документ
 * как невалидный XML (`cover-banner.ts`).
 *
 * Аудит 2026-09-11, круг 26: правило в репозитории не новое, новым было
 * только то, что оно жило копиями. Три места держали одну и ту же пару строк
 * (`cutBlock` здесь рядом, `sliceOneEnd` в telegram-chunking.ts, разбор
 * потолка в message-handler.ts), и ровно поэтому два других места —
 * подтверждение расшифровки голоса человеку и срез текстового вложения в
 * контекст модели — правила не унаследовали: наследовать было нечего, его
 * неоткуда было импортировать. Довод дословно тот же, которым `cutBlock`
 * объясняет собственный переезд: «Копия правила — это правило, действующее
 * на N−1 из N мест».
 *
 * Здесь только высокий суррогат в хвосте. Одинокий НИЗКИЙ в начале среза
 * обрезкой не порождается (он может прийти только из уже битого входа), и
 * чинить чужую битость — отдельное решение, принятое в `delabs-text.ts`.
 */

/** Убрать одинокий высокий суррогат, если срез оставил его последним. */
export function dropLoneHighSurrogate(s: string): string {
  const last = s.charCodeAt(s.length - 1);
  return last >= 0xd800 && last <= 0xdbff ? s.slice(0, -1) : s;
}

/**
 * `s.slice(0, max)`, но без половины символа на конце.
 *
 * Результат не длиннее `max`: пара либо входит целиком, либо не входит вовсе.
 */
export function cutToCodeUnits(s: string, max: number): string {
  return max >= s.length ? s : dropLoneHighSurrogate(s.slice(0, max));
}
