/**
 * Граница периодических задач.
 *
 * Аудит 2026-08-20, к паре с фиксом uncaughtException. Пока глобальный
 * обработчик глушил всё подряд, исключение из колбэка `setInterval` стоило
 * одной строки в логе и следующий тик приходил как ни в чём не бывало. Как
 * только необработанное исключение начинает валить процесс (а оно должно —
 * состояние после него неизвестно), каждый голый колбэк таймера превращается
 * в потенциальный рестарт сервиса от рядового SQLITE_BUSY.
 *
 * Разница принципиальная: для планировщика сбой одного тика — ожидаемое
 * событие, а не неизвестное состояние. Работа инкрементальная, следующий тик
 * догонит. Поэтому такие места обязаны ловить сами, а не полагаться на
 * глобальный обработчик, который про них ничего не знает и знать не может.
 *
 * Здесь нет ретраев и нет подавления: тик, который упал, просто не состоялся,
 * и об этом говорит log.error с ИМЕНЕМ таймера — без имени в journalctl
 * остаётся строка без модуля и без стека, по которой не понять, что сломалось
 * (ровно эта жалоба записана в комментарии к `[unhandledRejection]` в
 * lib/self-diag.ts — искать по тексту «без модуля и без стека»).
 *
 * Аудит 2026-08-27: ссылка была на `lib/self-diag.ts:694`, где сейчас другой
 * код — комментарий уехал на ~:855 вместе с правками файла. Номер строки в
 * ссылке протухает с первой же вставкой выше по файлу и молча уводит читателя
 * не туда, поэтому ссылаемся на текст, а не на позицию.
 */
import { getErrorMessage } from "./errors.ts";
import { log, scrubSecretString } from "./log.ts";

/** Потолок на стек в логе — как у соседей (telegraf-patch, role-runtime-worker). */
const MAX_STACK = 1000;

/**
 * Стек упавшего тика: обрезанный и без секретов.
 *
 * Аудит 2026-08-28: в логе оставалось только `getErrorMessage(e)`, то есть
 * ровно та «строка без стека», против которой написан докблок выше. Имя
 * таймера отвечает на вопрос «что сломалось», но не на «где»: у всех шести
 * рабочих тиков (db-maint.gc/daily/alerting/storm, watchdog, mac-bridge.ping)
 * под колбэком лежит длинная цепочка, и сообщения вида `database is locked`
 * или `no such column` одинаковы для десятка разных запросов внутри неё.
 *
 * Чистим тем же скраббером, что и `getErrorMessage`: в стек попадают кадры с
 * URL, а telegraf ходит по `https://api.telegram.org/bot<ТОКЕН>/...`.
 */
function stackOf(e: unknown): string | undefined {
  if (!(e instanceof Error) || typeof e.stack !== "string") return undefined;
  return scrubSecretString(e.stack).slice(0, MAX_STACK);
}

/**
 * Обернуть колбэк таймера так, чтобы его исключение осталось внутри.
 *
 * Возвращает функцию для передачи в `setInterval`/`setTimeout`. Асинхронные
 * колбэки тоже поддержаны: reject промиса ловится тем же логом, иначе он ушёл
 * бы в `unhandledRejection` — то есть в анонимную строку без имени таймера.
 */
export function safeTick(
  label: string,
  fn: () => void | Promise<unknown>,
): () => void {
  const fail = (e: unknown): void => {
    log.error("[timer] тик упал", {
      timer: label,
      error: getErrorMessage(e),
      stack: stackOf(e),
    });
  };
  return () => {
    try {
      const r = fn();
      if (r && typeof (r as Promise<unknown>).catch === "function") {
        void (r as Promise<unknown>).catch(fail);
      }
    } catch (e) {
      fail(e);
    }
  };
}
