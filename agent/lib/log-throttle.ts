/**
 * Сколько одинаковых строк в лог пускать, когда их вдруг стало очень много.
 *
 * Аудит 2026-09-11, круг 30. Отбой анонимного ведра в Mini App возвращался из
 * `fetch()` раньше обеих точек access-лога, так что 429 от `preAuth` не
 * оставлял в журнале НИЧЕГО. Владелец при флуде видел бы тормозящий Mini App,
 * флапающий /readyz — и тишину в логе: сигнал «по нам идут и ведро держит»
 * существовал только внутри процесса. Ровно тот случай, когда лог нужен
 * больше всего.
 *
 * Просто «дописать log.info» мало. ANON_LIMIT — 300 в ведре и 20 в секунду,
 * то есть при потоке в 2000 запросов/с отбоев будет ~1980 в секунду, и честная
 * строка на каждый превращает журнал в средство исчерпания диска, любезно
 * предоставленное атакующему. Поэтому строка одна на ключ за окно, а
 * проглоченные считаются и приезжают следующей строкой: и факт, и масштаб
 * сохранены, а объём — нет.
 *
 * Карта ключей ограничена сверху по тому же уроку, что и вёдра лимитера
 * (см. `HARD_MAX_BUCKETS` в lib/http-utils.ts): число анонимных ключей задаёт
 * тот, кто шлёт запросы, и «карта, которую чистят по возрасту» потолка не
 * имеет — при потоке РАЗНЫХ адресов протухших записей просто нет. Переполнение
 * здесь давит на молчание, а не на рост: лишний ключ не заводится, его строки
 * не печатаются. Это безопасная сторона — к этому моменту по другим ключам уже
 * напечатано более чем достаточно, чтобы шторм было видно.
 */

/** Что делать с очередным событием. */
export type ThrottleDecision =
  /** Печатать. `suppressed` — сколько проглочено с прошлой печати по этому ключу. */
  | { emit: true; suppressed: number }
  /** Молчать: по этому ключу уже печатали в текущем окне. */
  | { emit: false };

export type LogThrottle = {
  take: (key: string, now: number) => ThrottleDecision;
  /** Для тестов и диагностики: сколько ключей сейчас в карте. */
  size: () => number;
};

/** Предел карты ключей. Порядок тот же, что у вёдер лимитера. */
export const THROTTLE_MAX_KEYS = 10_000;

export function createLogThrottle(windowMs: number, maxKeys = THROTTLE_MAX_KEYS): LogThrottle {
  /** ключ → { когда печатали последний раз, сколько проглотили с тех пор } */
  const seen = new Map<string, { at: number; suppressed: number }>();

  const sweep = (now: number): void => {
    for (const [k, v] of seen) {
      if (now - v.at >= windowMs && v.suppressed === 0) seen.delete(k);
    }
  };

  return {
    size: () => seen.size,
    take(key: string, now: number): ThrottleDecision {
      const prev = seen.get(key);
      if (!prev) {
        if (seen.size >= maxKeys) {
          // Сначала попробовать освободить место: запись, по которой окно
          // истекло и глотать нечего, больше ничего не хранит.
          sweep(now);
          // Всё ещё полно — молчим. Рост карты от потока новых ключей и есть
          // тот дефект, ради которого здесь потолок.
          if (seen.size >= maxKeys) return { emit: false };
        }
        seen.set(key, { at: now, suppressed: 0 });
        return { emit: true, suppressed: 0 };
      }
      if (now - prev.at < windowMs) {
        prev.suppressed += 1;
        return { emit: false };
      }
      const suppressed = prev.suppressed;
      prev.at = now;
      prev.suppressed = 0;
      return { emit: true, suppressed };
    },
  };
}
