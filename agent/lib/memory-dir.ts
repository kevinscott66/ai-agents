/**
 * Разбор `MEMORY_DIR` — отдельным модулем, без побочных эффектов.
 *
 * Ровно та же роль, что у `lib/db-path.ts` для `MEMORY_DB_PATH`: чистая
 * функция, которую могут звать и писатель вики (`lib/memory.ts`, открывает
 * `db.ts` и трогает ФС), и бэкап (`lib/backup.ts`, которому нужен путь, а не
 * инициализированный модуль памяти). Одно место — чтобы читатель и писатель
 * не разъехались.
 */

/** Каталог, в котором вики лежит на проде и в разработке (относительно cwd). */
export const DEFAULT_MEMORY_DIR = "memory";

/**
 * Каталог вики из сырого значения переменной окружения.
 *
 * `process.env.MEMORY_DIR ?? "memory"` спасает только от ОТСУТСТВУЮЩЕЙ
 * переменной. Строка `MEMORY_DIR=` переменную задаёт — пустой, и это не
 * экзотика: в `agent/.env.example` строка `MEMORY_DIR=` написана ровно так, а
 * соседняя `MEMORY_DB_PATH=` уже стоила проекта одного разбора (аудит 2026-08-27,
 * `db-path.ts`) — правку тогда применили к одной переменной из двух.
 *
 * Пустая строка ломала читателя и писателя ПО-РАЗНОМУ, и оба тихо:
 *
 * - `lib/memory.ts`, сборка пути страницы — `join("", scope)` даёт `"_team"`,
 *   то есть вики уезжает в cwd-относительные `./_team/`, `./pm/` вместо
 *   `memory/…`;
 * - `lib/backup.ts`, шаг архива вики — `fs.existsSync("") === false`, он
 *   пропускается КАЖДУЮ ночь, оставляя одну строку `wiki dir not found: ` с
 *   пустым путём в логе. `errors` при этом пуст, то есть `backup_failed` не
 *   поднимается: единственный сигнал — вечный `backup_retention_held`.
 *
 * Пустое (и пробельное) значение считаем не заданным. Это не смена поведения,
 * а его восстановление: и докстрока `.env.example`, и комментарий про
 * `MEMORY_DIR` в `deploy/deploy.sh` описывают переменную как «override for memory/wiki
 * directory» с умолчанием `memory` — каталога `""` не подразумевал никто.
 */
export function resolveMemoryDir(
  raw: string | undefined,
  fallback: string = DEFAULT_MEMORY_DIR,
): string {
  if (raw === undefined) return fallback;
  const dir = raw.trim();
  if (dir !== "") return dir;
  console.warn(
    `[memory] MEMORY_DIR пуст — использую ${fallback}. ` +
      "Пустой путь развёл бы писателя вики и её бэкап: первый писал бы в " +
      "cwd, второй не нашёл бы каталога и молча пропускал архив.",
  );
  return fallback;
}
