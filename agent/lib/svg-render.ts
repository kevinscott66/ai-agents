/**
 * C8: SVG → PNG рендер через @resvg/resvg-js.
 *
 * Используется action'ом GENERATE_SVG_IMAGE: агент пишет валидный SVG-код,
 * бэкенд рендерит его в PNG-буфер и отправляет в чат как фото.
 *
 * Ограничения:
 *  - размер SVG ≤ 200KB;
 *  - ширина рендера ≤ 2048px;
 *  - каждая сторона ИТОГОВОГО растра ≤ 4096px (см. MAX_RENDER_SIDE).
 */
