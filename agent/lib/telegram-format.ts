/**
 * Render the agents' standard Markdown into Telegram HTML so `**bold**`,
 * `*italic*`, inline code, code fences, links and headings display formatted
 * instead of showing raw asterisks. HTML (not MarkdownV2) is used because it
 * only needs `& < >` escaped — far more forgiving than MarkdownV2's huge escape
 * set. Anything the converter can't render cleanly is caught by the send-time
 * fallback (sendWithHtml), so a formatting glitch never blocks delivery.
 */

import { log } from "./log.ts";
import { dropLoneHighSurrogate } from "./text-cut.ts";
import { withTelegramRateLimitRetry, type RetryOptions } from "./telegram-retry.ts";

function escapeHtml(s: string): string {
  return s.replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;");
}

/**
 * Свернуть Markdown-цитаты в Telegram <blockquote>. На входе текст уже escape-нут,
 * поэтому маркер строки — `&gt;` (бывший `>`). Подряд идущие строки-цитаты
 * объединяются в один блок. `&gt;!` в первой строке → раскрывающаяся цитата
 * (<blockquote expandable>). Telegram не разрешает вложенные цитаты — не вкладываем.
 */
function collapseBlockquotes(text: string): string {
  const lines = text.split("\n");
  const out: string[] = [];
  let buf: string[] | null = null;
  let expandable = false;
  const flush = () => {
    if (buf) {
      const tag = expandable ? "<blockquote expandable>" : "<blockquote>";
      out.push(`${tag}${buf.join("\n")}</blockquote>`);
      buf = null;
      expandable = false;
    }
  };
  for (const line of lines) {
    const m = line.match(/^&gt;(!?)\s?(.*)$/);
    if (m) {
      if (!buf) {
        buf = [];
        if (m[1] === "!") expandable = true;
      }
      buf.push(m[2]);
    } else {
      flush();
      out.push(line);
    }
  }
  flush();
  return out.join("\n");
}

// NUL-wrapped placeholders can't collide with real message text.
//
// \u0000, а не сам байт: тут стояли восемь литеральных NUL'ов (здесь и в
// восстановлении ниже), из-за чего `file` видит здесь `data`, а GNU/BSD grep считает
// файл бинарным и молча пропускает («Binary file matches» вместо строк, а под
// `-l`/`-r` и вовсе ничего). Аудит 2026-08-13 дважды сделал ложный вывод «такого
// кода нет» именно поэтому. Для JS записи равнозначны.
const B = (i: number) => `\u0000B${i}\u0000`;
const I = (i: number) => `\u0000I${i}\u0000`;
/**
 * Аудит 2026-08-14: URL защищаются так же, как код.
 *
 * Ссылки подставлялись шагом 4, а выделение шло шагами 5-10 — то есть
 * регулярки курсива и жирного правили `_`, `*` и `~` ВНУТРИ уже готового URL.
 * `[док](https://delabs.space/tag/_defi_)` давало
 * `<a href="https://delabs.space/tag/<i>defi</i>">` — 400 и откат на сырой
 * markdown. Хуже голая ссылка: `https://t.me/c/_test_` превращалась в
 * `https://t.me/c/<i>test</i>`, а это ВАЛИДНЫЙ HTML — ни ошибки, ни фолбэка,
 * читателю молча уходит ссылка не туда. Единственный тест на ссылки в
 * tfmt-telegram-format брал `https://x.com`, где нет ни одного такого символа.
 */
const U = (i: number) => `\u0000U${i}\u0000`;

/**
 * Отделить от голой ссылки ЗАКРЫВАЮЩИЙ markdown-разделитель, прилипший к её
 * концу.
 *
 * Аудит 2026-08-20: класс `[^\s<>"]` шага 4b включает `*`, `~` и `|`, поэтому
 * из `||спойлер https://delabs.space/a||` в плейсхолдер уезжало
 * `https://delabs.space/a||`. Открывающие `||` оставались без пары, шаг 10
 * спойлер не собирал — и текст, помеченный автором как скрытый, уходил в канал
 * ВИДИМЫМ. Молча: ни 400, ни фолбэка, отправка успешна. Ровно то последствие,
 * которое этот файл уже чинил 2026-08-13, только причина другая. На двух
 * спойлерах подряд было хуже: палки слипались крест-накрест и под спойлер
 * попадал чужой кусок текста. `**жирный …**` и `~~…~~` теряли разметку
 * косметически.
 *
 * Режем ТОЛЬКО парные двухсимвольные разделители (`**`, `~~`, `||`) — реальный
 * URL ими не заканчивается. Одиночные `*`, `~`, `|` и любые `_` оставляем в
 * адресе: `/tag/_defi_` и `/__init__` — живые пути, а срезанный хвост потом
 * съест курсив шага 9, и читатель получит ссылку на 404. Обменивать редкую
 * потерянную разметку на редкую битую ссылку нельзя, разметку чинит фолбэк.
 *
 * Хвостовая пунктуация уезжает вместе с разделителем — и та, что стоит после
 * него (`||…||.`), и та, что перед (`**… ссылка.**`): склейка
 * `плейсхолдер + хвост` посимвольно равна исходному совпадению, так что для
 * ссылки это не меняет ничего, а до разделителя добраться позволяет. Отсюда
 * lookahead: срезаем хвост, только если внутри него ЕСТЬ парный разделитель,
 * иначе обычная точка в конце предложения уезжала бы из адреса просто так.
 */
const URL_TRAILING_MARKUP =
  /^(https?:\/\/[^\s<>"]*?[^\s<>"*~|.,!?;:])((?=[*~|.,!?;:]*(?:\*\*|~~|\|\|))[*~|.,!?;:]+)$/;

export function mdToTelegramHtml(input: string): string {
  if (!input) return input;
  const blocks: string[] = [];
  const inlines: string[] = [];
  const urls: string[] = [];

  // 0) Вычистить U+0000 из ВХОДА до того, как мы сами начнём им размечать.
  //
  //    Аудит 2026-08-19: этим символом обёрнуты наши внутренние плейсхолдеры
  //    (\u0000U0\u0000 и т.п.), а во входе он не служит ничему — Telegram его
  //    всё равно не отображает. Вход при этом недоверенный: тела текстовых
  //    вложений READ_FILE и выдача web_search попадают в текст как есть.
  //    Строка `"\u0000U0\u0000 [док](https://ok.tld/real)"` на шаге
  //    восстановления забирала href НАСТОЯЩЕЙ ссылки (индекс 0 занят, `?? _m`
  //    не помогает — промах индекса тут не при чём), и читателю уходили две
  //    ссылки на один адрес: одна подписана автором, вторая — тем, кто прислал
  //    файл. Убираем источник, а не следствие.
  input = input.replace(/\u0000/g, "");

  // 1) Fenced code blocks → <pre> (content escaped, protected from formatting)
  //
  //    Аудит 2026-08-28: метка языка была `[a-zA-Z0-9_+-]*` с необязательным
  //    `\n` после — то есть ни к чему не привязана. У забора, открытого и
  //    закрытого на ОДНОЙ строке, она забирала первый латинский токен самого
  //    кода: `"Запусти ```npm install```"` теряло `npm`, а `"```code```"`
  //    выдавало пустой `<pre></pre>` — код исчезал целиком. HTML при этом
  //    валиден, поэтому ни 400 от Telegram, ни плейн-фолбэка: сообщение
  //    уходило успешно и без куска. Путь общий для чата и канала —
  //    mdToUserbotHtml зовёт этот же конвертер.
  //
  //    Теперь метка засчитывается, только если за ней (с точностью до
  //    пробелов) идёт перевод строки. Ровно так её и определяет CommonMark:
  //    info string живёт на строке открывающего забора. Хвостовые пробелы
  //    добавлены заодно — раньше `"```js \ncode```"` уносил в <pre> сам
  //    перевод строки.
  let text = input.replace(/```(?:[a-zA-Z0-9_+-]*[ \t]*\n)?([\s\S]*?)```/g, (_m, code: string) =>
    B(blocks.push(`<pre>${escapeHtml(code.replace(/\n+$/, ""))}</pre>`) - 1),
  );
  // 2) Inline `code` → <code>
  text = text.replace(/`([^`\n]+)`/g, (_m, code: string) =>
    I(inlines.push(`<code>${escapeHtml(code)}</code>`) - 1),
  );
  // 3) Escape the rest
  text = escapeHtml(text);
  // 4) Links [text](url) — URL прячется за плейсхолдер до конца конвертации.
  //
  //    Аудит 2026-08-29: класс URL был `[^\s)]+`, а шаги 1-2 к этому моменту
  //    уже подменили код на `\u0000B<n>\u0000` / `\u0000I<n>\u0000`. `\u0000`
  //    — не пробел и не `)`, поэтому плейсхолдер уезжал ВНУТРЬ href, а шаг
  //    восстановления (после balanceHtmlTags) разворачивал его там в тег:
  //    `` See [doc](https://x.tld/a`v1`/b) `` давало
  //    `<a href="https://x.tld/a<code>v1</code>/b">doc</a>`. На пути юзербота
  //    gramjs делает из этого MessageEntityTextUrl с мусорным URL — в канале
  //    висит ссылка в никуда, без ошибки и без плейн-фолбэка, уже ПОСЛЕ
  //    апрува владельца. На пути Bot API Telegram отвечает 400, и
  //    `sendWithHtml` роняет форматирование поста целиком.
  //
  //    Исключаем `\u0000` из обоих классов. Ссылка тогда просто не собирается
  //    (нет `)` сразу за URL) и уходит читателю сырым markdown — видимая
  //    поломка вместо тихо подменённого адреса.
  text = text.replace(
    /\[([^\]\n]+)\]\((https?:\/\/[^\s)\u0000]+)\)/g,
    (_m, t: string, u: string) =>
      `<a href="${U(urls.push(u.replace(/"/g, "%22")) - 1)}">${t}</a>`,
  );
  // 4b) Голые ссылки. Telegram линкует их сам, наше дело — не дать шагам 5-10
  //     переписать в них `_`, `*` и `~`. Восстанавливаем дословно, поэтому
  //     захваченная хвостовая пунктуация выйдет ровно такой, какой пришла.
  //     `\u0000` исключён по той же причине, что и на шаге 4.
  text = text.replace(/https?:\/\/[^\s<>"\u0000]+/g, (m) => {
    const split = URL_TRAILING_MARKUP.exec(m);
    return split ? U(urls.push(split[1]!) - 1) + split[2]! : U(urls.push(m) - 1);
  });
  // 5) Bold **x** / __x__  (before single-char italic)
  //     Аудит 2026-08-27: было `[^\n*]+?` — запрет на `*` внутри. Из-за него
  //     `**жирный с *курсивом* внутри**` не матчился шагом 5, шаг 9 съедал
  //     внутренние `*`, и в канал уходило `**жирный с <i>курсивом</i>
  //     внутри**` — сырые звёздочки открытым текстом, жирность потеряна. Молча:
  //     HTML валиден, 400 от Telegram нет, отката нет. Запрет на перенос строки
  //     оставлен, ленивый квантор по-прежнему берёт ближайшую пару (`**a** и
  //     **b**` не слипаются), а `(?=[^\s*])` не даёт схлопнуть `** **` и
  //     сохраняет прежний разбор `***жирный курсив***` (внешняя пара остаётся
  //     курсиву шага 9).
  text = text.replace(/\*\*(?=[^\s*])([^\n]+?)\*\*/g, "<b>$1</b>");
  text = text.replace(/__([^\n_]+?)__/g, "<b>$1</b>");
  // 6) Strikethrough ~~x~~
  text = text.replace(/~~([^\n~]+?)~~/g, "<s>$1</s>");
  // 7) Headings (#…######) → bold line
  text = text.replace(/^#{1,6}\s+(.+)$/gm, "<b>$1</b>");
  // 7b) Standalone horizontal rules (---, ***, ___, ≥3) — выкинуть строку целиком.
  //     В постах канала они не нужны (по правке владельца) и засоряют вид.
  text = text.replace(/^[ \t]*([-*_])(?:[ \t]*\1){2,}[ \t]*$/gm, "");
  // 8) Bullet list markers at line start → •
  text = text.replace(/^(\s*)[-*+]\s+/gm, "$1• ");
  // 9) Italic *x* / _x_ (single, not part of ** / __)
  //     Аудит 2026-08-27: границей слова служил `\w`, а он в JS — только ASCII.
  //     Любая кириллическая буква считалась «не словом» и ОТКРЫВАЛА курсив:
  //     `отчёт_за_неделю.md` уходил в канал как `отчёт<i>за</i>неделю.md`, имя
  //     файла без подчёркиваний и с паразитным курсивом. HTML при этом валиден,
  //     значит ни 400, ни плейн-фолбэка — читатель получает изменённый текст.
  //     `\p{L}\p{N}` под флагом `u` закрывают все алфавиты сразу.
  //     Аудит 2026-08-28: символ перед открывающей звёздочкой проверялся, а
  //     вокруг самой пары — нет. Жирный такую охрану получил ещё 2026-08-27
  //     (`(?=[^\s*])`), курсив остался без неё с обеих сторон, и на пробеле
  //     открывался и закрывался: `"Цена 5 * 3 рублей и ещё 2 * 8"` уходило как
  //     `"Цена 5 <i> 3 рублей и ещё 2 </i> 8"` — обе звёздочки стёрты, читатель
  //     видит «5  3 … 2  8». Так же пропадали глоб-маски: `*.log и *.txt`
  //     превращались в `.log` и `.txt`. HTML валиден, значит ни 400, ни
  //     плейн-фолбэка. CommonMark обе стороны запрещает: за открывающей
  //     звёздочкой не должно быть пробела, перед закрывающей — тоже.
  text = text.replace(
    /(^|[^*\p{L}\p{N}_])\*(?=[^\s*])([^\n*]*?[^\s*])\*(?!\*)/gu,
    "$1<i>$2</i>",
  );
  text = text.replace(
    /(^|[^_\p{L}\p{N}])_([^\n_]+?)_(?![_\p{L}\p{N}])/gu,
    "$1<i>$2</i>",
  );
  // 10) Spoiler ||x|| → <tg-spoiler>
  //     Аудит 2026-08-28: правило было без единой охраны, и любые два `||` в
  //     одной строке склеивались в спойлер. `"if (a || b || c) return"` уходило
  //     как `"if (a <tg-spoiler> b </tg-spoiler> c) return"` — кусок текста в
  //     чате и в канале становился СКРЫТЫМ под тап, а сами `||` пропадали.
  //     Зеркало дефекта, который этот файл чинил дважды в обратную сторону
  //     (аудит 2026-08-13 и 2026-08-20: помеченное автором как скрытое уходило
  //     видимым) — здесь непомеченное уходит невидимым. `<tg-spoiler>` —
  //     валидная сущность, поэтому ни 400, ни плейн-фолбэка.
  //     Охраны те же, что у одиночного `_` (аудит 2026-08-27): границы слова с
  //     обеих сторон плюс запрет пробела сразу за открывающей парой и перед
  //     закрывающей.
  text = text.replace(
    /(^|[^|\p{L}\p{N}])\|\|(?=[^\s|])([^\n|]*?[^\s|])\|\|(?![|\p{L}\p{N}])/gu,
    "$1<tg-spoiler>$2</tg-spoiler>",
  );
  // 11) Blockquote: подряд идущие строки «> …» (после escape — «&gt; …») в один
  //     <blockquote>. «>! …» в первой строке делает цитату раскрывающейся.
  text = collapseBlockquotes(text);
  // 12) T-813: снять перекрёстную разметку до восстановления кода и ссылок.
  text = balanceHtmlTags(text);

  // restore protected urls, then code
  //
  // Аудит 2026-09-11: `?? _m` сегодня недостижим, и делать вид, что он что-то
  // ловит, не надо. Подделать плейсхолдер можно было только принеся \u0000 во
  // входе, а шаг 0 вычищает их все ДО того, как мы начнём размечать своими;
  // после него каждый `\u0000U<n>\u0000` в тексте поставлен здесь же, и индекс
  // у него по построению в диапазоне. Аудит 2026-08-19 (вход
  // `"\u0000U0\u0000 [x](https://ok.tld/real)"` уводил href НАСТОЯЩЕЙ ссылки,
  // а у B/I в сообщение уезжал литерал "undefined") починил именно шаг 0 —
  // прежний комментарий приписывал заслугу этой строке и делал из неё вывод
  // «промах индекса — всегда чужая подделка», хотя после шага 0 промаха не
  // бывает вовсе. Шаг 0 про эту строку говорит прямо: «`?? _m` не помогает».
  //
  // Оставляем как деградацию на случай, если шаг 0 уедет или переедет ниже:
  // тогда чужой плейсхолдер уйдёт читателю литералом, а не заберёт URL соседней
  // ссылки. Цена — одно `??`.
  text = text.replace(/\u0000U(\d+)\u0000/g, (_m, i: string) => urls[+i] ?? _m);
  text = text.replace(/\u0000I(\d+)\u0000/g, (_m, i: string) => inlines[+i] ?? _m);
  text = text.replace(/\u0000B(\d+)\u0000/g, (_m, i: string) => blocks[+i] ?? _m);
  return text;
}

/**
 * T-813: чинит перекрёстную разметку в готовом HTML.
 *
 * Шаги 5-10 выше — независимые регулярки без стека вложенности, поэтому
 * `**жирный _кур** сив_` даёт `<b>жирный <i>кур</b> сив</i>`: теги
 * перехлёстываются, а Telegram требует строгой вложенности и отвечает
 * 400 «can't parse entities: Unmatched end tag». Сообщение всё же доходит —
 * `sendWithHtml` откатывается на plain text, — но пост при этом теряет
 * форматирование целиком, а в логах копится ошибка.
 *
 * Чинить сами регулярки означало бы писать полноценный парсер Markdown;
 * дешевле пройтись по результату со стеком тегов. Правило: если закрывающий
 * тег не совпал с вершиной стека, но такой открытый тег есть глубже —
 * снимаем ПАРУ целиком. Текст остаётся весь, разметка теряется только у того
 * куска, который перекрещивался (в примере — жирный), вложенный курсив цел.
 * Непарные хвосты (закрывашка без открывашки и наоборот) тоже снимаются:
 * Telegram ругается и на них.
 *
 * Аудит 2026-08-29: сюда же снятие ВЛОЖЕННОГО тега с тем же именем. Шаги 5 и 9
 * — по две регулярки каждый (`**` и `__` дают один и тот же `<b>`, `*` и `_` —
 * один и тот же `<i>`), поэтому `*это _очень_ важно*` собиралось в
 * `<i>это <i>очень</i> важно</i>`. Вложенность формально корректная, стек её
 * пропускал, а `HTMLToTelegramParser` в gramjs держит `_buildingEntities` по
 * ИМЕНИ тега: внутренний `<i>` затирает запись внешнего, первый `</i>` её
 * закрывает, второй закрывать уже нечего. Проверено: на входе выше в канал
 * уезжает одна `MessageEntityItalic(0, 9)` — курсив обрывается на «это очень»,
 * хвост «важно» идёт обычным текстом. Ни ошибки, ни 400, ни отката: сообщение
 * уходит успешно и с потерянной разметкой. Внутренняя пара ничего не добавляет
 * (жирное внутри жирного — то же жирное), поэтому снимаем её, а не внешнюю:
 * оформление сохраняется целиком, сущность остаётся одна.
 *
 * Вызывается ДО восстановления плейсхолдеров кода — внутри <pre>/<code>
 * содержимое уже экранировано, и балансировщику там делать нечего. Весь
 * `<` в пользовательском тексте к этому моменту тоже экранирован (шаг 3),
 * так что любой тег, который видит эта функция, поставлен нами.
 */
export function balanceHtmlTags(input: string): string {
  if (!input.includes("<")) return input;

  interface Tok {
    start: number;
    end: number;
    name: string;
    closing: boolean;
  }
  const TAG_RE = /<(\/?)([a-z][a-z0-9-]*)(?:\s[^>]*)?>/gi;
  const toks: Tok[] = [];
  for (let m = TAG_RE.exec(input); m !== null; m = TAG_RE.exec(input)) {
    toks.push({
      start: m.index,
      end: m.index + m[0].length,
      name: m[2]!.toLowerCase(),
      closing: m[1] === "/",
    });
  }
  if (toks.length === 0) return input;

  const drop = new Set<number>(); // индексы токенов на выброс
  const open: number[] = []; // стек индексов открытых токенов
  const redundant = new Set<number>(); // открывашки внутри такой же открытой
  for (let i = 0; i < toks.length; i++) {
    const t = toks[i]!;
    if (!t.closing) {
      if (open.some((j) => toks[j]!.name === t.name)) redundant.add(i);
      open.push(i);
      continue;
    }
    if (open.length > 0 && toks[open[open.length - 1]!]!.name === t.name) {
      const from = open.pop()!; // корректная вложенность — самый частый путь
      if (redundant.has(from)) {
        drop.add(from);
        drop.add(i);
      }
      continue;
    }
    let at = -1;
    for (let j = open.length - 1; j >= 0; j--) {
      if (toks[open[j]!]!.name === t.name) {
        at = j;
        break;
      }
    }
    drop.add(i);
    if (at !== -1) {
      drop.add(open[at]!); // перекрёст — снимаем пару целиком
      open.splice(at, 1);
    }
  }
  for (const i of open) drop.add(i); // открывашки без закрывашек

  if (drop.size === 0) return input;
  let out = "";
  let cur = 0;
  for (let i = 0; i < toks.length; i++) {
    if (!drop.has(i)) continue;
    out += input.slice(cur, toks[i]!.start);
    cur = toks[i]!.end;
  }
  return out + input.slice(cur);
}

/**
 * То же, но для юзербота (gramjs), а не Bot API.
 *
 * Аудит 2026-08-13: спойлер публиковался открытым текстом. У Bot API тег
 * называется `<tg-spoiler>` — его и отдаёт `mdToTelegramHtml`. Юзербот же
 * разбирает HTML сам, своим `HTMLParser` из `telegram/extensions/html.js`, а
 * тот знает только `<spoiler>` (см. `MessageEntitySpoiler` там же). Незнакомый
 * тег парсер молча выбрасывает вместе с разметкой — сущности не появляется, и
 * `||текст||`, который автор пометил как скрытый, уходит в канал видимым.
 * Молча: ни ошибки, ни 400 — сообщение уходит успешно.
 *
 * Замена по закрывающему и открывающему тегу целиком, а не по подстроке
 * «tg-spoiler»: внутри `<pre>`/`<code>` содержимое уже экранировано
 * (`&lt;tg-spoiler&gt;`), так что пример разметки в блоке кода не пострадает.
 */
export function mdToUserbotHtml(md: string): string {
  return mdToTelegramHtml(md)
    .replaceAll("<tg-spoiler>", "<spoiler>")
    .replaceAll("</tg-spoiler>", "</spoiler>");
}

/**
 * Длина текста ТАК, как её считает Telegram: по plain-тексту (без Markdown-
 * разметки). `[текст](url)` весит только «текст», `**x**` — только «x», и т.д.
 * Поэтому меряем результат конвертера md→HTML со снятыми тегами, а не сырой
 * Markdown — иначе длинные URL раздувают оценку и мы режем пост зря.
 *
 * Живёт здесь, а не в action-dispatch: тот же счёт нужен и подписям к медиа в
 * lib/telegram-actions.ts, а две копии этого правила разъедутся при первой же
 * правке конвертера.
 */
export function plainTelegramLength(md: string): number {
  const plain = mdToTelegramHtml(md)
    .replace(/<[^>]+>/g, "")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&");
  return plain.length; // UTF-16 code units — как считает Telegram
}

/**
 * Ошибка разметки — и только она. Telegram отвечает 400 с описанием вида
 * «can't parse entities: …», «unsupported start tag», «unclosed start tag».
 * Отличаем её от всего остального: таймаута, 429, 5xx и обрыва сети.
 */
export function isHtmlParseError(e: unknown): boolean {
  const err = e as {
    response?: { error_code?: number; description?: string };
    error_code?: number;
    description?: string;
    message?: string;
  } | null;
  const code = err?.response?.error_code ?? err?.error_code;
  if (code !== undefined && code !== 400) return false;
  const desc = String(
    err?.response?.description ?? err?.description ?? err?.message ?? "",
  );
  return /can't parse entities|unsupported start tag|unclosed start tag|can't find end tag|entities|tag "[^"]*" is unsupported/i.test(
    desc,
  );
}

/**
 * Send `rawText` as Telegram HTML (Markdown-converted); on a MARKUP error
 * (400 «can't parse entities» и родня) retry once as plain text, so a
 * formatting issue never blocks delivery. `send(text, parseMode?)` adapts each
 * transport.
 *
 * Аудит 2026-08-04: `catch` был без разбора и ловил ЛЮБУЮ ошибку — включая
 * таймаут сокета, 429 и 5xx. А таймаут не значит «не доставлено»: запрос мог
 * дойти до Telegram, потерялся только ответ. Тогда второй send доставлял ВТОРОЙ
 * экземпляр сообщения. Идемпотентности здесь нет ни на одном уровне
 * (trigger-anti-dup дедуплицирует входящие триггеры, а не исходящие вызовы), и
 * ретрай на 429 был ещё и мгновенным, без задержки. Задевало SEND_MESSAGE,
 * подписи SEND_PHOTO и Bot-API-ветку PUBLISH_TO_CHANNEL — то есть публикацию
 * подписчикам.
 *
 * `plainFallbackFits` — мерка для ФОЛБЭКА, не для основного пути. Аудит
 * 2026-08-14: решение «резать ли» текст принимают вызывающие, и принимают его
 * по видимой длине — правильно, Telegram считает подпись после разбора
 * сущностей, и дайджест из полутора десятков ссылок обязан остаться одним
 * сообщением (аудит 2026-08-12 это как раз чинил). Но при ошибке разметки сюда
 * возвращается СЫРОЙ markdown, у которого своя длина. Замер на 22 строках
 * `• Новость N [Подробнее →](https://delabs.space/digest/…)` плюс одна строка
 * с перекрёстным `**жирный _курсив** хвост_`: raw 1663 против plain 566 —
 * первый вызов падает на сущностях, второй на «caption is too long», и
 * документ не доезжает вовсе. Двухграничная мерка на ВХОДЕ здесь не подходит:
 * она бы дробила подписи, которые прекрасно уходят одним сообщением, когда
 * разметка валидна (обычный случай). Поэтому граница стоит ровно там, где она
 * нужна, — на редком плейн-пути, и стоит она текста, а не доставки.
 */
export async function sendWithHtml<T>(
  send: (text: string, parseMode?: "HTML") => Promise<T>,
  rawText: string,
  plainFallbackFits?: (text: string) => boolean,
  /** Только для тестов: подмена сна и числа попыток. В проде — дефолты. */
  retryOpts?: RetryOptions,
): Promise<T> {
  // Аудит 2026-08-20: 429 выше назван среди тех ошибок, по которым слепой
  // повтор недопустим, — и это верно ровно потому, что повтор был МГНОВЕННЫМ.
  // Сам по себе 429 как раз повторяемый: это отказ ДО обработки (сообщение не
  // доставлено), и Telegram называет точное число секунд. Не читал его никто:
  // отправка падала, действие репортилось провалившимся, а решение о повторе
  // принимала модель — иногда через секунду, в тот же лимит. Ждём столько,
  // сколько просят; разбор остальных ошибок не меняется. См. telegram-retry.ts.
  //
  // Аудит 2026-08-27: повтор перезапускал функцию С НАЧАЛА, то есть заново слал
  // HTML-запрос, который уже был отвергнут по разметке. Разметка ломается
  // детерминированно (текст тот же — ответ тот же), а 429 в этой связке ловит
  // как раз плейн-фолбэк: он идёт вторым. Получалось шесть запросов вместо
  // четырёх, и три обречённых 400 уходили ВНУТРЬ того флуд-окна, из-за которого
  // мы и ждём. Помечаем отказ разметки на весь вызов; 429 на самой HTML-попытке
  // (форматирование ни при чём, запрос просто не доехал) повторяется как прежде.
  const state = { htmlRejected: false };
  return withTelegramRateLimitRetry(
    () => sendWithHtmlOnce(send, rawText, plainFallbackFits, state),
    { label: "sendWithHtml", ...retryOpts },
  );
}

async function sendWithHtmlOnce<T>(
  send: (text: string, parseMode?: "HTML") => Promise<T>,
  rawText: string,
  plainFallbackFits?: (text: string) => boolean,
  /** Живёт один вызов `sendWithHtml`: разметку отвергли — второй раз не пробуем. */
  state?: { htmlRejected: boolean },
): Promise<T> {
  if (!state?.htmlRejected) {
    try {
      return await send(mdToTelegramHtml(rawText), "HTML");
    } catch (e) {
      if (!isHtmlParseError(e)) throw e;
      if (state) state.htmlRejected = true;
    }
  }
  if (plainFallbackFits && !plainFallbackFits(rawText)) {
    // Фолбэк шлёт СЫРОЙ текст, а он длиннее видимого: `[текст](url)` весит
    // здесь всю ссылку. Без этой обрезки ошибка разметки превращается во
    // вторую 400 — «too long» — и падает уже само действие (см. коммент
    // к параметру).
    const cut = cutBlock(rawText, plainFallbackFits) || "…";
    log.warn("[tg] плейн-фолбэк не влезал в лимит — подпись обрезана", {
      raw: rawText.length,
      cut: cut.length,
    });
    return await send(cut);
  }
  return await send(rawText);
}

/** `]` метки дочитывается в хвосте и сразу переходит в `(url` — то есть обрыв. */
function labelClosesInRest(rest: string): boolean {
  return /^[^\n\]]*\]\(/.test(rest);
}

/**
 * Начало оборванной markdown-ссылки в конце `s`, либо -1.
 *
 * `rest` — то, что в исходном тексте идёт сразу за `s`. Обрезка бывает двух
 * родов, и различает их только он: при усечении (`cutBlock`) хвост
 * выбрасывается совсем, при разбиении на части (`sliceOneEnd`) хвост поедет
 * следующим куском. Поэтому `s`, кончающаяся на `[Подробнее]`, — законченная
 * проза, если дальше ничего нет, и разорванная пополам ссылка, если дальше
 * `(https://…)`. Без `rest` (усечение) считаем прозой.
 *
 * Аудит 2026-08-29: правило было записано как `open > s.lastIndexOf(")")`, то
 * есть сравнивало позицию `[` с позицией ЛЮБОЙ круглой скобки. Текст в
 * квадратных скобках без единой круглой давал `-1` справа, условие
 * выполнялось всегда, и хвост отрезался по `[`: «Дроп подтверждён
 * [ANNOUNCED] — детали ниже» схлопывалось до «Дроп подтверждён…».
 * Квадратные скобки в новостной прозе встречаются заметно чаще, чем обрывы
 * ссылок. Проверяем ровно обрыв: либо `](` без закрывающей скобки после него,
 * либо подпись, чьё `]` осталось в хвосте.
 *
 * Аудит 2026-09-11: тогда правило починили только здесь, а вторая обрезка —
 * `sliceOneEnd` в lib/telegram-chunking.ts — осталась со старым условием и
 * схлопывала куски ещё два аудита. Поэтому правило живёт одной функцией на
 * оба места; проверять его копией больше негде.
 *
 * Круг 32: та же ошибка пережила обе правки в ветке «`]` нет вовсе». Она
 * возвращала `open` безусловно, то есть ЛЮБАЯ непарная `[` — `items[`,
 * «[ANNOUNCED» без пары, скобка в коде — считалась обрывом. В усечении это
 * стоило дороже всего: `cutBlock` меряет двоичным поиском, каждый кандидат
 * схлопывался до символа перед `[`, каждый «влезал», и блок в 2443 символа
 * уезжал в чат семнадцатью. Живой путь — `fitToLimit` в dispatch/publish.ts,
 * а там кусок короче 40 символов ещё и выбрасывается вместе с остатком поста.
 *
 * Метка ссылки без `]` — обрыв только если `]` дочитывается в хвосте и сразу
 * переходит в `(`. Без такого доказательства это проза: лишняя `[` в тексте
 * ничего не ломает (конвертер md→HTML без `](url)` ссылку не собирает), а
 * схлопывание сообщения ломает всё. Поэтому `sliceOneEnd` отдаёт сюда весь
 * остаток строки, а не один символ: на одном символе доказательство
 * непредъявимо, и ветка молча вырождалась в «всегда обрыв».
 */
export function danglingLinkStart(s: string, rest = ""): number {
  const open = s.lastIndexOf("[");
  if (open === -1) return -1;
  const close = s.indexOf("]", open);
  if (close === -1) return labelClosesInRest(rest) ? open : -1;
  if (s.charAt(close + 1) === "(") {
    return s.indexOf(")", close + 2) === -1 ? open : -1; // `](url` без `)`
  }
  // `]` — последний символ куска, а url остался в хвосте: ссылка разорвана.
  if (close === s.length - 1 && rest.startsWith("(")) return open;
  return -1;
}

/**
 * Обрезать блок так, чтобы `fits` вернул true, не оставив мусора на срезе.
 *
 * Срез идёт по СЫРОМУ markdown, а меряется PLAIN-длина, поэтому позиция ищется
 * двоичным поиском с линейной подстраховкой: у частично отрезанной ссылки
 * plain-длина ведёт себя немонотонно, и одного bsearch мало.
 *
 * После среза чистим хвост: половина суррогатной пары (иначе строка невалидна
 * как UTF-16), оборванная `[текст](url` и непарные `**` / `` ` `` — всё это
 * конвертер md→HTML превращает в сломанную разметку, а это 400 «can't parse
 * entities», то есть снова потерянный пост.
 *
 * Жила приватной функцией в `action-dispatch.ts`, пока аудит 2026-08-12 не нашёл
 * второе место с той же задачей — обрезку в `tgEditMessage`, которая резала по
 * сырой длине и по code units. Копия правила — это правило, действующее на N−1
 * из N мест, поэтому обрезка переехала сюда, к остальной мерке.
 */
export function cutBlock(block: string, fits: (candidate: string) => boolean): string {
  const clean = (raw: string): string => {
    let s = dropLoneHighSurrogate(raw);
    // Обрыв внутри ссылки: `](` ещё не закрыт — отрезаем ссылку целиком.
    const open = danglingLinkStart(s);
    if (open !== -1) s = s.slice(0, open);
    // Непарная разметка: убираем последний открывающий маркер.
    if ((s.match(/\*\*/g) ?? []).length % 2 === 1) s = s.slice(0, s.lastIndexOf("**"));
    if ((s.match(/`/g) ?? []).length % 2 === 1) s = s.slice(0, s.lastIndexOf("`"));
    // По границе слова, но не ценой заметного куска текста.
    const sp = s.lastIndexOf(" ");
    if (sp > s.length * 0.8) s = s.slice(0, sp);
    return s.trimEnd();
  };

  let lo = 0;
  let hi = block.length;
  while (lo < hi) {
    const mid = Math.ceil((lo + hi) / 2);
    if (fits(`${clean(block.slice(0, mid))}…`)) lo = mid;
    else hi = mid - 1;
  }
  let out = `${clean(block.slice(0, lo))}…`;
  // Подстраховка на немонотонность: досекаем, пока не влезет.
  while (out.length > 1 && !fits(out)) out = `${clean(out.slice(0, Math.floor(out.length * 0.9)))}…`;
  return fits(out) ? out : "";
}
