// Сначала длинные ключи (с variation selector, напр. 🗓️ = 3 UTF-16 единицы),
// чтобы не сматчить короткий вариант 🗓 раньше.
const EMOJI_KEYS = Object.keys(DELABS_EMOJI).sort((a, b) => b.length - a.length);

/** Селектор варианта: невидимый модификатор, из-за которого «❤» и «❤️» — разные строки. */
const VS16 = "\uFE0F";

/**
 * Тот же словарь, но по ключу БЕЗ селектора варианта.
 *
 * Аудит 2026-08-12: совпадение было точным, а в словаре одни ключи записаны с
 * селектором («⭐️», «✍️»), другие без («❤», «🎖»). Селектор невидим, так что
 * какая форма попала в словарь — вопрос случая, а от неё зависело, оживёт
 * эмодзи в посте или нет: «⭐» не находилось вовсе, хотя «⭐️» находилось.
 *
 * Явная запись сильнее выведенной: у «🗓️» и «🗓» РАЗНЫЕ documentId, то есть
 * разные анимации, и подменять одну другой нельзя.
 */
const BASE_EMOJI: Record<string, string> = (() => {
  const out: Record<string, string> = {};
  for (const [key, id] of Object.entries(DELABS_EMOJI)) {
    const base = key.replaceAll(VS16, "");
    if (base === key || base === "" || base in DELABS_EMOJI) continue;
    out[base] ??= id;
  }
  return out;
})();
const BASE_KEYS = Object.keys(BASE_EMOJI).sort((a, b) => b.length - a.length);

/** Модификаторы тона кожи U+1F3FB…U+1F3FF — каждый ровно две UTF-16 единицы. */
const SKIN_TONES = ["\u{1F3FB}", "\u{1F3FC}", "\u{1F3FD}", "\u{1F3FE}", "\u{1F3FF}"];
/** Zero-width joiner: склеивает эмодзи в одну составную графему («❤️‍🔥»). */
const ZWJ = "‍";

/**
 * Длина графемы, начинающейся ключом словаря в позиции `i`, или null — если
 * оживлять её нельзя.
 *
 * Селектор варианта, тон и ZWJ — часть отображаемого эмодзи, и модификатор
 * обязан попасть ВНУТРЬ границ сущности: она подменяет накрытый текст
 * анимированным стикером, а оставшийся снаружи модификатор относиться к нему
 * уже не может.
 *
 * Аудит 2026-08-12: расширение было только на VS16. «👍🏻 Отлично» давало
 * сущность (0,2), и модификатор U+1F3FB оставался ЗА границей — Telegram
 * подменял стикером две накрытые единицы, а осиротевший модификатор оставался
 * в тексте отдельным квадратом. «❤️‍🔥» (2764 FE0F 200D 1F525) давало ДВЕ
 * сущности, (0,2) и (3,2): одна графема разрезана на два разных анимированных
 * стикера.
 *
 * Тон накрываем: documentId у нас один на эмодзи, и общий анимированный 👍
 * лучше, чем стикер плюс мусорный символ рядом.
 *
 * ZWJ-составные пропускаем совсем. У составного эмодзи своя картинка, и накрыть
 * «❤️‍🔥» стикером «❤️» — это подмена символа, а не оживление; живой настоящий
 * эмодзи лучше неправильного стикера.
 */
function graphemeLength(
  text: string,
  i: number,
  keyLength: number,
  keyEndsWithVs16: boolean,
): number | null {
  // Часть составного эмодзи слева — трогать нельзя.
  if (i > 0 && text[i - 1] === ZWJ) return null;
  let end = i + keyLength;
  if (!keyEndsWithVs16 && text.startsWith(VS16, end)) end += 1;
  if (SKIN_TONES.some((t) => text.startsWith(t, end))) end += 2;
  // Часть составного эмодзи справа — тоже нельзя.
  if (text.startsWith(ZWJ, end)) return null;
  return end - i;
}

/** Ключ словаря, начинающийся в позиции `i`, вместе с реальной длиной в тексте. */
function matchAt(text: string, i: number): { id: string; length: number } | null {
  for (const key of EMOJI_KEYS) {
    if (!text.startsWith(key, i)) continue;
    const length = graphemeLength(text, i, key.length, key.endsWith(VS16));
    return length === null ? null : { id: DELABS_EMOJI[key]!, length };
  }
  for (const key of BASE_KEYS) {
    if (!text.startsWith(key, i)) continue;
    const length = graphemeLength(text, i, key.length, key.endsWith(VS16));
    return length === null ? null : { id: BASE_EMOJI[key]!, length };
  }
  return null;
}

/**
 * Отрезки текста, куда кастом-эмодзи заходить нельзя: `pre` и `code`.
 *
 * Аудит 2026-08-13: словарь сканировал ВЕСЬ плейн-текст, не спрашивая, что это
 * за текст. Две цены:
 *
 *  1. Код перестаёт быть кодом. Блок с `✅` в выводе теста или `🔥` в примере
 *     конфига получал анимированный стикер вместо символа — то есть кусок,
 *     который читатель копирует, чтобы выполнить.
 *  2. Публикация падает целиком. MTProto не принимает сущности внутри
 *     `messageEntityPre`/`messageEntityCode` (там форматирование запрещено
 *     по определению) — весь вызов отвечает MESSAGE_ENTITIES_INVALID. У
 *     юзербот-пути фолбэка нет: `publishPost` не ловит ошибку, а на подходе
 *     к нему пост УЖЕ одобрен владельцем. Апрув сгорает, поста нет.
 *
 * Границы берём из тех самых сущностей, что вернул HTMLParser, — гадать по
 * тексту не нужно и нельзя: после разбора разметки бэктиков в нём уже нет.
 */
/**
 * Потолок на число сущностей в одном сообщении.
 *
 * Аудит 2026-08-29: раньше потолка не было вовсе — сколько эмодзи из словаря
 * нашлось в тексте, столько сущностей и уезжало в Telegram. Это не
 * теоретический перебор: недельный дайджест это два-три десятка позиций, у
 * каждой свой значок, плюс сущности разметки от HTMLParser на тех же
 * строках. Сервер отвечает на перебор отказом (ENTITIES_TOO_LONG), а у
 * юзербот-пути фолбэка нет — `publishPost` ошибку не ловит, и на подходе к
 * нему пост УЖЕ одобрен владельцем: апрув сгорает, поста нет. Ровно тот
 * сценарий, что описан выше для сущностей внутри code-блоков.
 *
 * Обрезать декорацию безопасно: символ эмодзи остаётся в тексте (мы вешаем
 * сущность, а не заменяем его — см. шапку файла). Лишние позиции просто
 * покажутся обычным эмодзи вместо анимированного. Потерять пост дороже.
 *
 * 100 — цифра из документации Bot API. Точное значение серверного лимита
 * MTProto по документации не проверить, поэтому берём известную границу:
 * даже если реальный лимит окажется другим, обрезка только декоративного
 * хвоста не может сделать сообщение хуже, чем оно было без потолка.
 */
const MAX_MESSAGE_ENTITIES = 100;

function protectedRanges(
  entities: readonly Api.TypeMessageEntity[],
): Array<[number, number]> {
  const out: Array<[number, number]> = [];
  for (const e of entities) {
    if (e instanceof Api.MessageEntityPre || e instanceof Api.MessageEntityCode) {
      out.push([e.offset, e.offset + e.length]);
    }
  }
  return out;
}

/**
 * Найти эмодзи из словаря в тексте и вернуть MessageEntityCustomEmoji со
 * смещениями в UTF-16 (как у Telegram и JS-строк). Текст не изменяется.
 *
 * `formatting` — сущности разметки того же текста (результат HTMLParser). Не
 * обязателен: без него поведение прежнее, со сканом всего текста. Оба
 * юзербот-вызова его передают.
 */
export function buildCustomEmojiEntities(
  text: string,
  formatting: readonly Api.TypeMessageEntity[] = [],
): Api.TypeMessageEntity[] {
  const skip = protectedRanges(formatting);
  const inSkip = (from: number, to: number) =>
    skip.some(([s, e]) => from < e && to > s);
  // Бюджет считается от ОБЩЕГО числа сущностей в сообщении: оба боевых
  // вызова шлют `[...fmtEntities, ...buildCustomEmojiEntities(...)]`
  // (`publishPost` в lib/userbot.ts), то есть разметка занимает место в том
  // же лимите.
  // Сущности разметки не выбрасываем никогда — это смысл текста, и именно
  // они несут границы pre/code, ради которых существует protectedRanges.
  // Если одной разметки уже больше потолка, бюджет уходит в ноль: сделать
  // здесь больше нечего, но и усугублять нельзя.
  const budget = Math.max(0, MAX_MESSAGE_ENTITIES - formatting.length);
  const ents: Api.TypeMessageEntity[] = [];
  let i = 0;
  while (i < text.length && ents.length < budget) {
    const m = matchAt(text, i);
    if (!m) {
      i++;
      continue;
    }
    // Пересечение, а не вложенность: сущность, начатая до блока кода и
    // заехавшая в него хвостом, недопустима ровно так же.
    if (inSkip(i, i + m.length)) {
      i += m.length;
      continue;
    }
    ents.push(
      new Api.MessageEntityCustomEmoji({
        offset: i,
        length: m.length,
        documentId: bigInt(m.id) as any,
      }),
    );
    i += m.length;
  }
  return ents;
}
