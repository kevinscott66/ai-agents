/**
 * Футер канала — ОДНО определение на всех.
 *
 * Раньше правило «что считать футером» жило в двух местах: строгое в
 * action-dispatch.ts (там футер и ставится) и своё, разъехавшееся, в
 * site-ingest.ts (там его вырезают перед отправкой карточки на сайт). Вторая
 * копия матчила `delabs` без якоря — то есть любую строку с названием бренда, а
 * канал у нас ровно про DeLabs. Пункты дайджеста и вступление поста молча
 * пропадали с сайта (замер — в шапке tests/site-ingest-footer.test.ts).
 *
 * Держим здесь, а не в action-dispatch: тот тянет за собой пол-рантайма
 * (telegram, юзербот, БД), и импортировать его ради одной регулярки из
 * fire-and-forget-моста нельзя.
 */

/**
 * Канонический футер канала (стиль @delabsru) со ССЫЛКАМИ. Агент часто
 * переписывает футер простым текстом и теряет ссылки — поэтому проставляем его
 * программно, не полагаясь на промпт. Ссылки вытянуты из @delabsru (×25 постов).
 */
export const CHANNEL_FOOTER =
  "💬 [ЧАТ](https://t.me/+TBw7_-wGgxRiZjQy) сообщества | [Активности](https://delabs-team.notion.site/5f1150ddc4584bd294966f2eadea6eae?v=98dc51bfd685415580f5a30554dc42c3&pvs=4) **© Copyright 2023-2026 [DeLabs](https://t.me/+GlWh_q7pcZFkNjc6)**🤑";

/**
 * Строка похожа на футер-блок (его и заменяем — и его же не тащим на сайт).
 *
 * Маркеры намеренно узкие: 💬 и © только в НАЧАЛЕ строки, «copyright» и
 * «DeLabs🤑» — как часть копирайт-строки. Название бренда само по себе
 * маркером быть не может.
 *
 * Аудит 2026-08-12: узкими они были только на словах. В альтернации
 * `/^\s*💬|copyright|DeLabs🤑|^\s*©/iu` якорь `^\s*` относится ТОЛЬКО к 💬 и ©,
 * а `copyright` матчил в любой позиции строки — то есть ровно тот же дефект,
 * что чинили выше для `delabs`. Строка «• Спор про copyright в Zora закрыт»
 * считалась футером: ensureChannelFooter отрывал её от поста и по флагу
 * `removed` приклеивал канонический футер, которого в посте не было, а
 * site-ingest выбрасывал её из items/summary карточки на сайте.
 *
 * Теперь «copyright» считается маркером только рядом с © или годом — там, где
 * это действительно копирайт-строка. Само слово — обычный текст.
 */
export function isChannelFooterLine(line: string): boolean {
  const marker = /^\s*([💬©])/u.exec(line)?.[1];
  return (
    (marker !== undefined && hasFooterSubstance(line, marker)) ||
    /DeLabs🤑/u.test(line) ||
    // Аудит 2026-08-27: якорь стоял только у 💬/© в строке выше, а эта
    // альтернация матчила в ЛЮБОЙ позиции строки — ровно тот же дефект, что
    // чинил аудит 2026-08-12 для голого слова `copyright`, только на форме с
    // годом. «Спор про copyright 2024 закрыт мировым соглашением.» считалось
    // футером: ensureChannelFooter отрывал содержательную строку от поста и
    // приклеивал канонический футер, которого в посте не было, а site-ingest
    // выбрасывал её из title/items/summary карточки на delabs.space.
    // Настоящая копирайт-строка стоит в начале своей строки; внутри
    // канонического однострочного футера её ловит ветка с ведущим 💬.
    // Ведущее оформление (`**`, `__`, `~~`) пропускаем: модель пишет копирайт
    // жирным — `**© Copyright 2023-2026 DeLabs**🤑`.
    //
    // Аудит 2026-08-28: в класс были дописаны ещё и маркеры списка (`•`, `·`,
    // `—`, `-`) — то есть ровно те глифы, с которых начинаются ПУНКТЫ
    // дайджеста. Замер: `isChannelFooterLine("• Copyright 2024 спор в Zora
    // закрыт мировым соглашением.")` → true, и ensureChannelFooter отрывал
    // последний пункт от уже одобренного поста, приклеивая на его место
    // канонический футер. Тот же дефект, что чинили 2026-08-12 и 2026-08-27,
    // заново открытый через класс оформления. Ущерб двойной: строка исчезает
    // из поста в канале И из карточки на delabs.space (site-ingest.ts:124
    // переиспользует эту же функцию как isFooterLine).
    //
    // Маркер списка — признак пункта, а не футера. В классе оставлены только
    // символы выделения.
    /^[\s*_~]*(©\s*copyright|copyright\s*©|copyright\s+\d{4})/iu.test(line)
  );
}

/**
 * Второй признак футера рядом с ведущим 💬 или ©.
 *
 * Аудит 2026-08-19: одного ведущего эмодзи мало. 💬 лежит в собственном словаре
 * бренда (custom-emoji-map.ts) — агенты ставят его в обычных CTA постоянно.
 * Прогон `ensureChannelFooter("Заголовок\n\nТекст поста.\n\n💬 Что думаете?
 * Пишите в комментариях")` вырезал CTA и приклеил на её место канонический
 * футер — при том, что футера в посте не было, а докстрока `ensureChannelFooter`
 * обещает такой пост не трогать. Все вызовы происходят уже ПОСЛЕ одобрения
 * человеком: правится текст, который человек утвердил.
 *
 * Аудит 2026-08-28: здесь было написано «вызов один, в PUBLISH_TO_CHANNEL».
 * Вызовов три: `dispatch/publish.ts:172` и два в `tools/approve-poll.ts`
 * (632 и 654) — это cron-публикатор ежедневного и недельного поста DeLabs.
 * Утверждение про один вызов использовалось, чтобы очертить радиус поражения
 * правок этих регулярок, и увело мимо дефекта, который проявляется ТОЛЬКО на
 * пути approve-poll (см. комментарий про `belowHasChat` в
 * `ensureChannelFooter`).
 *
 * Аудит 2026-08-20: словарная половина этого признака ловила обычный русский
 * текст, а не футер. Замеры на предыдущей версии:
 *   «💬 Обсуждаем в чате сообщества»  → строка вырезана, на её место футер
 *   «💬 **Активности недели в Monad**» → заголовок ПУНКТА принят за футер
 * Второе особенно неприятно: `emoji` пункта — свободное поле черновика, 💬
 * лежит в брендовом словаре, и такой заголовок стоит в ТЕЛЕ поста.
 *
 * Слова «чат», «сообществ», «активности» сами по себе — обычная лексика. От
 * футера отличает не словарь, а ФОРМА: два блока через разделитель `|`. Агент,
 * переписывающий футер простым текстом, форму сохраняет (он теряет ссылки —
 * ради этого ensureChannelFooter и существует), а живая CTA её не имеет.
 *
 * Многострочный футер («💬 ЧАТ сообщества» строкой выше «© Copyright …») этой
 * проверкой не ловится и не должен: за него отвечает `looksLikeFooterTail` —
 * слабые признаки засчитываются только внутри уже найденного блока.
 */
function hasFooterSubstance(line: string, marker: string): boolean {
  // Аудит 2026-08-28: `slice(1)` снимает одну UTF-16 единицу, а 💬 (U+1F4AC) —
  // суррогатная пара, так что в `tail` остаётся её нижний суррогат. Для
  // единственного потребителя (`/©/u.test(tail)`) это безразлично, но резать
  // по code point честнее, чем оставлять «строка без ведущего маркера»,
  // которой она не была.
  const tail = [...line.trimStart()].slice(1).join(""); // без ведущего 💬/©
  // Ссылка, бренд-хвост, копирайт. Ссылка — осознанный размен аудита
  // 2026-08-19: «💬 Чат: https://t.me/delabs_chat» — это футер, написанный
  // агентом от руки, и заменить его каноническим со всеми ссылками нужно.
  // Живая CTA со ссылкой («💬 Вопросы — сюда: …») от него по содержанию
  // неотличима и под этот размен попадает — известная граница, не дефект.
  const common =
    /https?:\/\/|t\.me\/|notion\.site/iu.test(line) ||
    /🤑/u.test(line) ||
    /copyright/iu.test(line) ||
    /©/u.test(tail);
  if (common) return true;
  // Ведущий © — это уже почти копирайт-строка: хватает года или бренда рядом.
  if (marker === "©") return /(19|20)\d{2}/u.test(line) || /delabs/iu.test(line);
  // Ведущий 💬 — только каноническая форма целиком: оба блока через `|`.
  return (
    /\|/u.test(line) &&
    /чат|сообществ/iu.test(line) &&
    /активност/iu.test(line)
  );
}

/**
 * Слабый признак: строка похожа на ПРОДОЛЖЕНИЕ футер-блока, но сама по себе
 * футером не считается.
 *
 * Нужен ровно для многострочного футера, который пишет модель:
 *   «💬 ЧАТ сообщества»
 *   «© Copyright 2023-2026 DeLabs»
 * Вторая строка ловится как футер, первая — уже нет (после правки 2026-08-20),
 * и без этой функции цикл обрывался бы на ней: канонический футер приклеивался
 * ПОВЕРХ уцелевшего приглашения в чат — тот самый дубль, который чинил аудит
 * 2026-08-12.
 *
 * Засчитывается только когда настоящая футерная строка уже найдена НИЖЕ по
 * тексту. Одиночная CTA в конце поста ничего под собой не имеет, поэтому под
 * это правило не попадает.
 */
function looksLikeFooterTail(line: string): boolean {
  if (!/^\s*[💬©]/u.test(line)) return false;
  return (
    /чат|сообществ|активност/iu.test(line) ||
    /https?:\/\/|t\.me\/|notion\.site/iu.test(line)
  );
}

/**
 * Гарантировать правильный футер со ссылками: если в конце текста есть футер-блок
 * (агент его написал, обычно без ссылок) — заменить на канонический; если футера
 * нет — НЕ навязывать (не каждый пост — дайджест). Возвращает текст с футером.
 */
export function ensureChannelFooter(text: string): string {
  const lines = text.split("\n");
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  // Аудит 2026-08-12: цикл срезания останавливался на первой не-футерной
  // строке, а пустая строка между «💬 ЧАТ …» и «© Copyright …» — обычная
  // разметка от модели. Цикл обрывался после первой итерации, но `removed`
  // уже стоял, и канонический футер приклеивался ПОВЕРХ уцелевшей строки
  // «💬 ЧАТ»: в публичный канал уходило два приглашения в чат. Видно это
  // только на опубликованном посте — вызов один, в PUBLISH_TO_CHANNEL, уже
  // после одобрения человеком.
  //
  // Пустые строки внутри блока пропускаем, но НЕ засчитываем: `end` двигает
  // только настоящая футерная строка. Иначе «пропускать пустые» превратилось
  // бы в «идти сквозь них до любого 💬 где-то выше по тексту» и съедало бы
  // тело поста.
  //
  // Аудит 2026-08-27: подъём по слабому признаку не имел потолка. Канонический
  // футер — ОДНА строка, и 💬 в ней уже есть; следующая строка вверх с 💬 — это
  // не продолжение футера, а живая CTA («💬 Что думаете? Пишем в чате
  // сообщества»), и она молча исчезала из уже одобренного поста. Слабый признак
  // нужен ровно для многострочного футера модели, где 💬-строка стоит НАД
  // «© Copyright …».
  //
  // Аудит 2026-08-28: потолок был поставлен флагом «в блоке уже встречался 💬»,
  // и он ломался ровно там, где чаще всего и работает. `approve-poll.ts:632`
  // зовёт `ensureChannelFooter(text + "\n\n" + FOOTER)`, то есть канонический
  // футер приклеен ЗАРАНЕЕ. Он снимается первой же итерацией и поднимает флаг,
  // после чего рукописный многострочный футер над ним замораживается. Замер на
  // «Итоги недели.\n\n💬 ЧАТ сообщества\n© Copyright 2023-2026 DeLabs» плюс
  // приклеенный футер: в выходе ДВА 💬 — осиротевшее приглашение в чат и
  // канонический футер. Тот же вход без предварительной склейки обрабатывался
  // верно, поэтому tests/audit-2026-08-20-footer-eats-cta.test.ts этого не
  // видел.
  //
  // Правильный потолок — не «встречался ли 💬 в блоке», а «есть ли 💬 в строке
  // НЕПОСРЕДСТВЕННО под текущей». Многострочный футер модели это «💬 ЧАТ» над
  // «© Copyright …»: под слабой строкой стоит копирайт, 💬 в нём нет. Живая CTA
  // стоит под канонической однострочной, и 💬 в ней есть. Различие точное, и
  // оно не зависит от того, что успели снять ниже.
  let removed = false;
  let belowHasChat = false;
  let end = lines.length;
  for (let k = lines.length; k > 0; k--) {
    const line = lines[k - 1]!;
    if (
      isChannelFooterLine(line) ||
      (removed && !belowHasChat && looksLikeFooterTail(line))
    ) {
      end = k - 1;
      removed = true;
      belowHasChat = /💬/u.test(line);
      continue;
    }
    if (!line.trim()) continue; // пустая — только если выше есть футер
    break;
  }
  if (!removed) return text; // футера не было — оставляем как есть
  lines.length = end;
  while (lines.length && !lines[lines.length - 1].trim()) lines.pop();
  // Аудит 2026-08-28: шаблон `${lines.join()}\n\n${FOOTER}` безусловно ставил
  // два перевода строки, в том числе когда от поста не осталось ничего.
  // `ensureChannelFooter(CHANNEL_FOOTER)` возвращал «\n\n💬 …» — пустая строка
  // в начале сообщения канала.
  return lines.length ? `${lines.join("\n")}\n\n${CHANNEL_FOOTER}` : CHANNEL_FOOTER;
}
