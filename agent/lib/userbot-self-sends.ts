/**
 * Реестр собственных отправок userbot'а — чтобы отличить «это мы сами послали»
 * от «это владелец написал руками».
 *
 * Аудит 2026-08-20. `makeHandler` слушает `new NewMessage({})` — без фильтра
 * `outgoing`, то есть MTProto отдаёт и ИСХОДЯЩИЕ сообщения аккаунта тоже. Всё,
 * что userbot отправил сам (SEND_MESSAGE от роли, эскалация реакции,
 * публикация), через секунду возвращалось в тот же ингест и записывалось
 * `makeUserbotRecorder`'ом как сообщение ПОЛЬЗОВАТЕЛЯ: `isBot:false`,
 * `agentKey:null`, от id владельца. Фильтр `ownBotIds` тут не помогает — он
 * знает id наших ботов, а исходящее уходит от личного аккаунта владельца,
 * которого в этом списке нет и быть не должно. Длинный ответ уходит частями
 * (`sendChunked`), так что строк в истории столько же, сколько кусков, и все
 * они приезжают в промпт следующего хода как реплики владельца — то есть как
 * указания.
 *
 * Почему не `if (msg.out) return`, как в обработчике NewMessage у
 * orchestrator-userbot.ts: там путь
 * командный (владелец пишет боту в личку), а здесь ингест групп — и для
 * набранных руками сообщений владельца в группе userbot ЕДИНСТВЕННЫЙ источник,
 * потому что роль-боты работают с включённым privacy mode и своих апдейтов на
 * чужие реплики не получают. Глухой дроп по `out` стёр бы владельца из истории
 * команды целиком — это не починка, а вторая регрессия.
 *
 * Поэтому пара (chatId, text) регистрируется ДО вызова API и снимается первым
 * совпадением на входящем эхе. Гонка закрыта по построению: эхо физически не
 * может прийти раньше, чем отправка началась.
 *
 * Аудит 2026-08-27, две правки этого абзаца.
 *
 * (а) Здесь стояло «пропуск этой строки безвреден: дубликат того, что уже
 * записано». Записано ничего не было: отправка через userbot уходит по MTProto
 * и в `messages` не попадает никаким путём — `recordMessage` зовут только
 * Bot API-путь (message-handler.ts), voice-handler.ts и handoff.ts. Настоящая
 * причина безвредности другая: при совпадении текст и атрибуция у обоих
 * сообщений одинаковы, потому что оба идут с аккаунта владельца.
 *
 * (б) А вот НЕудачная отправка была не безвредна. Регистрация ставилась до
 * запроса и не снималась, если запрос упал, — и висела две минуты, съедая
 * первое же совпадающее сообщение владельца, набранное руками. Вот у него
 * второго источника нет. Отсюда `unmarkSelfSend`: регистрируем до запроса
 * (гонку с эхом иначе не закрыть), снимаем на отказе.
 *
 * Аудит 2026-08-28, продолжение (а): «в `messages` не попадает никаким путём»
 * было не только неверным объяснением, но и живым дефектом. Отправка агента
 * через userbot глушилась здесь и больше нигде не записывалась — то есть
 * собственные слова роли отсутствовали в краткосрочной памяти следующего хода.
 * Спросил агент от лица владельца «сносим прод?», человек ответил «да» — а
 * вопроса в истории нет. Поэтому регистрация теперь носит `agentKey`, и
 * `userbot-ingest.ts` на совпадении ПИШЕТ строку с правильной атрибуцией
 * вместо дропа. Дропаем только то, у чего роли нет (публикация в канал).
 *
 * Листовой модуль без импортов: `userbot.ts` сознательно не тянет ничего, что
 * поднимает БД на уровне модуля (см. шапку про userbot-flood.ts), а
 * `userbot-ingest.ts` через memory.ts как раз её и поднимает. Общее место для
 * двух сторон может быть только здесь.
 */

/** Живёт 2 минуты: эхо приходит за секунды, запас — на flood-wait ретрай. */
const SELF_SEND_TTL_MS = 120_000;
/** Потолок на случай, если эхо перестало приходить вовсе (мьют, дисконнект). */
const MAX_ENTRIES = 200;

/**
 * Одна ждущая эха отправка.
 *
 * Аудит 2026-08-28: раньше здесь лежал голый срок годности. Роль, от имени
 * которой ушло сообщение, была известна только на диспатче и терялась — а
 * дальше по течению `userbot-ingest.ts` именно из-за её отсутствия не мог
 * записать нашу отправку в `messages` с правильной атрибуцией и просто дропал
 * эхо. Носим ключ роли вместе со сроком.
 */
interface SelfSend {
  exp: number;
  /** Роль-отправитель, если известна; null — публикация в канал и т.п. */
  agentKey: string | null;
}

/** key -> ждущие эха отправки, по возрастанию срока (одинаковый текст ×N). */
const pending = new Map<string, SelfSend[]>();

/**
 * `-100123` из allowlist и `123` из апдейта — один и тот же чат. Единственное
 * определение на проект: `canonicalChatId` в userbot.ts импортирует отсюда же.
 */
export function normalizeChatId(id: string | number): string {
  return String(id).replace(/^-100/, "").replace(/^-/, "");
}

function keyOf(chatId: string | number, text: string): string {
  return `${normalizeChatId(chatId)}\n${text}`;
}

function prune(now: number): void {
  for (const [key, exp] of pending) {
    const live = exp.filter((e) => e.exp > now);
    if (live.length) pending.set(key, live);
    else pending.delete(key);
  }
  // Ключей всё ещё больше потолка — значит эхо не приходит; выкидываем самые
  // старые. Map хранит порядок вставки, так что первый ключ и есть старейший.
  while (pending.size > MAX_ENTRIES) {
    const oldest = pending.keys().next();
    if (oldest.done) break;
    pending.delete(oldest.value);
  }
}

/**
 * Зовётся ДО ухода запроса в MTProto. Пустой текст не регистрируем.
 *
 * `agentKey` — роль, от имени которой уходит сообщение. Необязателен: у
 * публикации в канал роли-автора в этом смысле нет, и такая отправка
 * по-прежнему только глушится, а не пишется в историю чата.
 */
export function markSelfSend(
  chatId: string | number,
  text: string,
  agentKey?: string | null,
): void {
  if (!text) return;
  const now = Date.now();
  const key = keyOf(chatId, text);
  const entry: SelfSend = { exp: now + SELF_SEND_TTL_MS, agentKey: agentKey ?? null };
  const arr = pending.get(key);
  if (arr) arr.push(entry);
  else pending.set(key, [entry]);
  // Чистка ПОСЛЕ вставки: иначе потолок перешагивается ровно на новый ключ.
  prune(now);
}

/**
 * Откат регистрации: отправка не состоялась, эха не будет.
 *
 * Снимаем запись СВОЕЙ роли, а не просто последнюю. Прежний докблок объяснял
 * `pop()` тем, что «записи внутри ключа взаимозаменяемы (это просто сроки
 * годности)» — и это перестало быть правдой в этом же файле 2026-08-28, когда
 * к сроку добавился `agentKey`. Снималось при этом с конца, а эхо потребляет
 * с начала (`consumeSelfSendMeta` → `shift`), то есть при двух живых
 * регистрациях одного текста откат уносил ЧУЖУЮ запись, а выжившее эхо
 * забирало атрибуцию упавшей отправки. `userbot-ingest.ts` пишет строку в
 * `messages` — и роль в истории чата оказывалась не та. Путь узкий (две роли
 * шлют байт-в-байт одинаковый короткий текст — «готово», «ок» — в один чат
 * одновременно, и одна отправка падает), но история чата кормит следующий ход.
 *
 * Среди записей одной роли берём последнюю: они и правда взаимозаменяемы, а у
 * последней срок дальше всех — соседней живой отправке достаётся более ранний,
 * то есть меньше шансов пережить своё эхо.
 *
 * Записи своей роли нет вовсе — не снимаем ничего. Значит её уже забрало эхо;
 * унести вместо неё чужую было бы ровно тем дефектом, который здесь чинится.
 */
export function unmarkSelfSend(
  chatId: string | number,
  text: string,
  agentKey?: string | null,
): void {
  if (!text) return;
  const key = keyOf(chatId, text);
  const arr = pending.get(key);
  if (!arr?.length) return;
  const want = agentKey ?? null;
  for (let i = arr.length - 1; i >= 0; i--) {
    if (arr[i]!.agentKey !== want) continue;
    arr.splice(i, 1);
    if (!arr.length) pending.delete(key);
    return;
  }
}

/**
 * Снимает одну регистрацию и отдаёт то, что о ней известно. `null` — совпадения
 * нет. Пустой текст (сервисные сообщения) не совпадает ни с чем никогда.
 */
export function consumeSelfSendMeta(
  chatId: string | number,
  text: string,
): { agentKey: string | null } | null {
  if (!text) return null;
  const now = Date.now();
  prune(now);
  const key = keyOf(chatId, text);
  const arr = pending.get(key);
  if (!arr?.length) return null;
  const entry = arr.shift() as SelfSend;
  if (!arr.length) pending.delete(key);
  return { agentKey: entry.agentKey };
}

/**
 * Снимает одну регистрацию. `true` — это эхо нашей собственной отправки.
 *
 * Тонкая обёртка над `consumeSelfSendMeta`: вызывающим, которым нужен только
 * факт совпадения, знать про атрибуцию незачем.
 */
export function consumeSelfSend(chatId: string | number, text: string): boolean {
  return consumeSelfSendMeta(chatId, text) !== null;
}

/** Только для тестов: реестр — модульный синглтон. */
export function _resetSelfSends(): void {
  pending.clear();
}

/** Только для тестов: сколько отправок ждут своего эха. */
export function _pendingSelfSends(): number {
  let n = 0;
  for (const arr of pending.values()) n += arr.length;
  return n;
}

/**
 * Реестр аккаунтов, от имени которых МЫ сами ходим в MTProto.
 *
 * Аудит 2026-08-28. Гашение эха выше опирается на `isOutgoing`, а этот флаг
 * верен только для той сессии, которая отправила. Как только рядом с
 * синглтоном поднимается вторая сессия (per-character роутинг, T-401 —
 * `orchestrator/services.ts` отдаёт обеим ОДИН рекордер), одно и то же
 * сообщение приезжает в ингест дважды: отправителю как исходящее, соседней
 * сессии — как обычное ВХОДЯЩЕЕ от чужого аккаунта. Регистрация в `pending`
 * при этом одна, гасится первым пришедшим, и вторая копия записывается как
 * реплика человека: `isBot:false`, `agentKey:null`. То есть ровно та дыра,
 * которую закрывал аудит 2026-08-20, воскресает от одного включения роутера —
 * слова агента снова уезжают в промпт следующего хода как указания владельца.
 *
 * Отличить «входящая копия НАШЕЙ отправки» от «человек написал тот же текст»
 * по одному тексту нельзя, и подменять это допущением нельзя тем более:
 * `userbot-ingest.ts` намеренно НЕ тратит регистрацию на входящие (см. тест
 * «входящее чужое сообщение с тем же текстом не тратит регистрацию»). Нужен
 * третий признак — id аккаунта-отправителя. Его и держим здесь: `startUserbot`
 * спрашивает `getMe()` при подключении и кладёт id сюда, ингест сверяется.
 *
 * Строго дополнение к текстовой проверке, а не замена: аккаунт владельца
 * пишет в те же группы руками, и по одному лишь id глушить нельзя — это была
 * бы вторая регрессия, описанная в шапке модуля.
 */
const selfAccounts = new Set<string>();

/** Зовётся из `startUserbot` после подключения. Пустой id игнорируем. */
export function markSelfAccount(id: string | number | null | undefined): void {
  const s = String(id ?? "").trim();
  if (!s || s === "0") return;
  selfAccounts.add(s);
}

/** `true` — сообщение прислал один из наших же MTProto-аккаунтов. */
export function isSelfAccount(id: string | number | null | undefined): boolean {
  const s = String(id ?? "").trim();
  return s !== "" && selfAccounts.has(s);
}

/** Только для тестов: реестр — модульный синглтон. */
export function _resetSelfAccounts(): void {
  selfAccounts.clear();
}
