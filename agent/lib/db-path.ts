/**
 * Разбор `MEMORY_DB_PATH` — отдельным модулем, без побочных эффектов.
 *
 * Логика жила в `lib/db.ts`, но импортировать её оттуда могут не все: top-level
 * `db.ts` открывает `new Database()` и прогоняет миграции. Для `lib/backup.ts`
 * и `orchestrator/services.ts` это неприемлемо — им нужен путь, а не открытая
 * база. Поэтому чистая функция вынесена сюда, а `db.ts` её переэкспортирует
 * (старые импорты `from "./db.ts"` продолжают работать).
 */

/** Путь, по которому база лежит на проде и в разработке. */
export const DEFAULT_DB_PATH = "data/memory.db";

/**
 * Путь к файлу БД из сырого значения переменной окружения.
 *
 * `process.env.MEMORY_DB_PATH ?? "data/memory.db"` спасает только от
 * ОТСУТСТВУЮЩЕЙ переменной. Строка `MEMORY_DB_PATH=` переменную задаёт —
 * пустой, а пустой путь SQLite понимает не как ошибку, а как «заведи приватную
 * временную базу»: `PRAGMA database_list` показывает `file: ""`, запись
 * проходит, и всё исчезает вместе с процессом. Путь из одних пробелов даёт
 * ровно то же самое.
 *
 * Достижимо штатной установкой, а не экзотикой: `.env.example` строка 55 —
 * `MEMORY_DB_PATH=` без значения, и весь файл написан в этом стиле.
 *
 * Поэтому пустое (и пробельное) значение считаем не заданным и падаем на
 * `fallback`. Предупреждаем, потому что деградировать тут некуда: с базой либо
 * работают, либо нет. `:memory:` не трогаем — это осознанный выбор вызывающего.
 *
 * @param fallback чем заменить незаданное значение. По умолчанию
 *   {@link DEFAULT_DB_PATH}; `lib/backup.ts` передаёт путь, собранный из своего
 *   `dataDir`, чтобы не потерять переданный ему каталог.
 */
export function resolveDbPath(
  raw: string | undefined,
  fallback: string = DEFAULT_DB_PATH,
): string {
  if (raw === undefined) return fallback;
  const path = raw.trim();
  if (path !== "") return path;
  console.warn(
    `[db] MEMORY_DB_PATH пуст — использую ${fallback}. ` +
      "Пустой путь SQLite понимает как приватную временную БД: " +
      "данные исчезли бы при остановке процесса.",
  );
  return fallback;
}
