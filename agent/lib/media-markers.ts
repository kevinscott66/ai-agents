/**
 * Словарь пометок носителя для истории чата.
 *
 * Ход без текста должен оставлять в истории строку: иначе агент читает
 * разговор с дырой и отвечает «ты ничего не присылал» на присланное. Картинка
 * и текстовый документ такую пометку имели с самого начала (`[image]`,
 * `[файл: имя]`, `orchestrator/message-handler.ts`), остальные носители — нет:
 * видео, кружок, гифка, стикер и аудио без подписи отсекались раньше записи
 * в короткую память и не оставляли следа вовсе.
 *
 * Пометки живут здесь, а не в обработчике, потому что у них два читателя.
 * Второй — `defuseSpeakerLabels` (lib/agent-prompts.ts): он переводит скобки
 * в начале строки в круглые, чтобы участник чата не мог подделать чужую
 * реплику, и обязан знать, какие скобки поставил обработчик, а какие пришли
 * из чата. Подделать пометку нечем: она называет НОСИТЕЛЬ, а не автора.
 */

/** Пометка, которую обработчик ставит вместо пустого текста. */
export function mediaNote(msg: Record<string, unknown>): string | null {
  // Порядок значим: кружок и гифка в Telegram приходят вместе с
  // `video`/`document`, поэтому узкое проверяется раньше широкого.
  if (msg.video_note) return "[кружок]";
  if (msg.animation) return "[гифка]";
  if (msg.sticker) return "[стикер]";
  if (msg.video) return "[видео]";
  if (msg.audio) return "[аудио]";
  if (msg.document) {
    const d = msg.document as { file_name?: unknown };
    const name = typeof d.file_name === "string" ? d.file_name : "document";
    return `[файл: ${name}]`;
  }
  // Всё прочее (опрос, геометка, контакт, служебные апдейты о входе в чат)
  // носителем разговора не является — и раньше не записывалось, и сейчас не
  // записывается. Список закрытый намеренно: «записывать всё» означало бы
  // строку истории на каждое системное событие.
  return null;
}

/**
 * Те же пометки как предикат для `defuseSpeakerLabels`.
 *
 * Сверяется с ВНУТРЕННОСТЬЮ скобок (без самих скобок) и целиком — `[images]`
 * или `[image ]` под исключение не попадают, иначе список превратился бы в
 * лазейку.
 */
export const MEDIA_MARKER_INNER =
  /^(?:image|кружок|гифка|стикер|видео|аудио|файл: .*)$/;
