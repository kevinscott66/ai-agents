/**
 * Разбиение длинного текста на сообщения Telegram (4096 символов на сообщение)
 * и последовательная отправка через произвольный sender.
 */

import { plainTelegramLength as plainLength, danglingLinkStart } from "./telegram-format.ts";

const TG_LIMIT = 4000; // запас под markdown-обёртки

/**
 * Жёсткий лимит сообщения у самого Telegram; `TG_LIMIT = 4000` выше — наш запас
 * под markdown-обёртки. Пара лимитов ПОДПИСИ (1000/1024) живёт не здесь, а в
 * telegram-actions.ts — заводить ей вторую копию рядом не надо.
 */
export const TELEGRAM_MESSAGE_HARD_LIMIT = 4096;

/**
 * Мерка ПЛЕЙН-фолбэка для сообщения: только сырая длина, под жёсткий лимит.
 *
 * Видимую длину здесь мерить нельзя: на плейн-пути Telegram считает символы как
 * есть, а `[текст](url)` весит всю ссылку. Живёт рядом с самим лимитом, потому
 * что правило разъезжалось: `handoff.ts` пытался обойтись без предиката и
 * передавал в `sendWithHtml` третьим аргументом сам ЧИСЛОВОЙ лимит — см. фикс
 * там же.
 *
 * Приватный `CAPTION_PLAIN_FITS` в telegram-actions.ts сюда сводить НЕ надо и
 * копией этого правила он не является: тот меряет подпись под жёсткий лимит
 * подписи (1024), этот — сообщение под жёсткий лимит сообщения (4096). Числа
 * разные, пути разные; общее у них только имя формы.
 */
export const messagePlainFits = (t: string): boolean =>
  t.length <= TELEGRAM_MESSAGE_HARD_LIMIT;

/**
 * Предикат для отправки с `parse_mode`: видимая длина под мягкий лимит, сырая —
 * под жёсткий.
 *
 * Аудит 2026-08-12: решение «резать ли» принималось по `plainTelegramLength`
 * (у подписи к фото и документу), а сама резка шла по сырой длине. Замер на 18
 * строках `• Пункт N [Подробнее →](https://delabs.space/digest/…)`: raw 1295
 * против plain 404 — по сырой длине это два куска, по видимой всё влезало в
 * один. Пост дробился сильнее, чем нужно, ровно там, где его просили оставить
 * одним сообщением.
 *
 * Сырая граница необязательна. Она нужна там, где плейн-фолбэк `sendWithHtml`
 * шлёт СЫРОЙ текст и не имеет своей мерки: часть, влезающая по видимой длине и
 * не влезающая по сырой, превратила бы ошибку разметки в потерянное сообщение.
 * Но если фолбэку передали собственную мерку (третий аргумент `sendWithHtml`),
 * вторая граница здесь только дробит сообщение сильнее нужного — см. разбор у
 * `CAPTION_FITS` в telegram-actions.ts, аудит 2026-08-19.
 */
export function htmlPartFits(
  limit: number,
  hardLimit?: number,
): (part: string) => boolean {
  return (part) =>
    plainLength(part) <= limit &&
    (hardLimit === undefined || part.length <= hardLimit);
}

/**
 * Мерка части для отправителей с `parse_mode: "HTML"` — одна на всех.
 *
 * Аудит 2026-08-21: `sendChunked` резал по СЫРОЙ длине, а `[текст](url)` весит
 * в сыром markdown весь URL. Замер на отчёте из 45 строк
 * `- [ai-agents#NNN](https://github.com/…/NNN) — …`: raw 4916 / plain 2486,
 * то есть ТРИ сообщения с префиксами «(1/3) » вместо одного.
 *
 * Сырой границы здесь нет намеренно — тот же выбор, что у `CAPTION_FITS`
 * (telegram-actions.ts, аудит 2026-08-19). Она стояла ради плейн-фолбэка
 * `sendWithHtml`, который шлёт СЫРОЙ текст, но фолбэк прикрыт отдельно:
 * `messagePlainFits` третьим аргументом `sendWithHtml` обрежет с записью в
 * лог. Дробление видит каждый читатель, обрезка живёт в ветке, куда попадают
 * только после невалидного HTML от нашего же конвертера.
 *
 * НЕ для сырых отправителей: `admin-commands.ts` шлёт без parse_mode, юзербот
 * (`buildHandle().sendMessage` в `userbot.ts`) зовёт gramjs
 * `sendMessage(peer, {message})` — там сырая
 * длина и есть та, что считает Telegram.
 */
export const HTML_MESSAGE_FITS = htmlPartFits(TG_LIMIT);

/**
 * Жёсткая резка строки без переносов — по границам символов, а не code units.
 *
 * `slice(i, i + limit)` считает UTF-16 code units и разваливает суррогатную
 * пару: часть заканчивается «половиной» эмодзи, строка становится невалидной
 * UTF-16, и Telegram отказывается её принимать — сообщение не уходит целиком.
 * Ветка достижима на обычном тексте: абзац без переносов длиннее лимита (для
 * подписи лимит всего 1000), а эмодзи в постах канала — норма.
 *
 * Отодвигаем границу на одну позицию назад, если она попала внутрь пары.
 * Вырожденный случай (limit=1 и пара) — берём пару целиком: лучше на символ
 * длиннее, чем битая строка. Составные эмодзи (ZWJ, модификаторы тона) по-
 * прежнему могут разъехаться по частям — это уже косметика, а не отказ API.
 *
 * Аудит 2026-08-12: про суррогат знали, а про ссылку — нет. Замер (абзац raw
 * 1032 / plain 991, лимит 1000) давал `…[Подробнее →](https://dela` +
 * `bs.space/digest/9f3c2a1b7) конец`: обе половины парсятся без ошибок, значит
 * плейн-фолбэк не сработает, и читатель просто видит разорванный посреди URL
 * пост. Отодвигаем границу к началу незакрытой ссылки — но только если после
 * этого часть не выродится, иначе цикл перестал бы двигаться.
 */
function sliceOneEnd(
  line: string,
  i: number,
  limit: number,
  fits: (s: string) => boolean,
): number {
  {
    let end = Math.min(i + limit, line.length);
    // Мерка может быть не сырой длиной (см. htmlPartFits) — досекаем, пока
    // часть не влезет. Шаг в 10% сходится быстро и не зависит от монотонности.
    while (end > i + 1 && !fits(line.slice(i, end))) {
      end = i + Math.max(1, Math.floor((end - i) * 0.9));
    }
    // Аудит 2026-08-20: окно ставилось по СЫРОЙ длине (`i + limit`) и умело
    // только ужиматься — раздвинуть его до того, что реально влезает по мерке,
    // было нечем. Та же ошибка «решаем по одной длине, режем по другой», что
    // аудит 2026-08-12 нашёл этажом выше у htmlPartFits, только с обратным
    // знаком: там пост дробился зря, здесь — куски выходили втрое короче
    // разрешённого. Замер на одном абзаце с markdown-ссылками (лимит подписи
    // 1000 по видимой длине): части plain 376/382/384/384/384 — пять сообщений
    // вместо двух, потому что raw-окно 1000 символов вмещает ~380 видимых.
    // Растём только вверх и только с проверкой каждого кандидата: мерка не
    // обязана быть монотонной (видимая длина падает, когда ссылка дописалась
    // до конца), поэтому шаг делится пополам на отказе, а не поиск по границе.
    // Растущий кусок не принимается без fits — немонотонность может стоить
    // только лишней части, но не превышения лимита. Исключение ровно одно и
    // оно вынужденное: вырожденный низ (ужимание останавливается на одном
    // символе, и `end <= i` добирает до двух) отдаётся НЕ меряя — иначе
    // цикл-вызывающий перестал бы двигаться по строке. То есть гарантия
    // звучит как «либо кусок прошёл мерку, либо он длиной в символ-два».
    if (end < line.length && fits(line.slice(i, end))) {
      let step = Math.max(1, Math.floor((end - i) * 0.25));
      for (let guard = 0; guard < 64 && end < line.length; guard++) {
        const cand = Math.min(end + step, line.length);
        if (fits(line.slice(i, cand))) {
          end = cand;
        } else if (step > 1) {
          step = Math.floor(step / 2);
        } else break;
      }
    }
    if (end < line.length) {
      const c = line.charCodeAt(end - 1);
      if (c >= 0xd800 && c <= 0xdbff) end--; // граница попала внутрь пары
      const chunk = line.slice(i, end);
      // Незакрытая `[текст](url` — отводим границу к её началу.
      //
      // Аудит 2026-09-11: условие было `open > chunk.lastIndexOf(")")`, то
      // есть сравнивало позицию `[` с позицией ЛЮБОЙ круглой скобки. Кусок
      // без единой круглой скобки давал справа `-1`, и граница отводилась к
      // каждой `[` в прозе: «Статус дропа [ANNOUNCED] …» на длинной строке
      // выдавало первой частью 13 символов и лишнее сообщение в чате. Тот же
      // дефект аудит 2026-08-29 уже чинил в `cutBlock` — сюда правило тогда
      // не перенесли, поэтому теперь оно одно на оба места.
      const open = danglingLinkStart(chunk, line.slice(end, end + 1));
      if (open > 0) end = i + open;
    }
    if (end <= i) end = Math.min(i + 2, line.length);
    return end;
  }
}

/*
 * Аудит 2026-08-29: здесь жила `hardSlice` — жадная обёртка над `sliceOneEnd`,
 * которая резала строку целиком и возвращала массив. Единственный её
 * вызывающий переехал на инкрементальный цикл 2026-08-28 (см. комментарий в
 * `splitForTelegram`, ветка «длинная строка без переносов»): жадная резка
 * меряла все куски, кроме первого, с чужой чётностью фенсов. С тех пор функция
 * не звалась ниоткуда. Оставлять её — оставлять готовую ловушку: сигнатура
 * приглашает «просто нарезать строку», а собственный докблок предупреждал, что
 * чётность фенсов она не двигает, то есть годится ровно там, где мерка от неё
 * не зависит — условие, которое следующий вызывающий проверить забудет. Удалена;
 * `sliceOneEnd` остаётся, по нему и надо ходить.
 */

/**
 * Разметка блоков кода — ровно та, что у `mdToTelegramHtml`.
 *
 * Там фенсы разбирает `/```[a-zA-Z0-9_+-]*\n?([\s\S]*?)```/g`: маркеры парятся
 * по порядку появления, первый с вторым, третий с четвёртым. Значит и здесь
 * достаточно идти по вхождениям ``` слева направо и переключать состояние.
 * Держим одну семантику на двоих: разъедься эти два разбора — и мы бы
 * «чинили» блок, которого форматтер не видит.
 */
const FENCE_RE = () => /```([a-zA-Z0-9_+-]*)/g;

/**
 * Открывашка, которую перенесут в следующую часть.
 *
 * Lang-токен обрезаем. `mdToTelegramHtml` его всё равно выбрасывает (в
 * `<pre>` уходит только тело блока), так что обрезка не меняет того, что
 * увидит читатель, — зато снимает две беды разом. Первая: `balanceFences`
 * дописывает эту открывашку В НАЧАЛО следующей части, то есть длинный
 * «язык» физически дублировался бы из части в часть. Вторая: он же входит в
 * мерку кандидата (см. withFenceMarkers), и «язык» под размер лимита не
 * оставлял места вообще ни под что — резчик выдавал бы сотни частей по два
 * символа. Достижимо: `FENCE_RE` считает языком любой прогон
 * `[a-zA-Z0-9_+-]` сразу после ```, то есть строку вида "```" + base64-блоб
 * без перевода строки. Настоящие языки короче шестнадцати символов.
 */
const MAX_FENCE_LANG = 16;

function openMarker(lang: string): string {
  return "```" + lang.slice(0, MAX_FENCE_LANG);
}

/**
 * Какая открывашка останется незакрытой после текста `s`, если до него уже была
 * открыта `from`. Ровно тот же проход, что делает `balanceFences`.
 */
function fenceOpenAfter(s: string, from: string | null): string | null {
  let open = from;
  for (const m of s.matchAll(FENCE_RE())) open = open === null ? openMarker(m[1]!) : null;
  return open;
}

/**
 * Часть в том виде, в котором её реально отправят: с открывашкой, перенесённой
 * с предыдущей части, и с закрывашкой, которую допишет `balanceFences`.
 *
 * Аудит 2026-08-21. Раньше запас под маркеры брался длиной: к кандидату
 * приклеивалось `reserve - 1` символов «x». Это компенсировало сами маркеры и
 * НЕ компенсировало главного — что закрывашка меняет МЕРКУ. Замер одной и той
 * же ссылки `[ai-agents#590](https://github.com/.../590)`:
 *
 *   вне блока          raw=67  plain=13   ← markdown, считается только якорь
 *   в закрытом блоке   raw=75  plain=67   ← <pre>, считается каждый символ URL
 *   после НЕзакрытого  raw=71  plain=17   ← снова markdown
 *
 * То есть решение «влезает» принималось на фрагменте с непарным ```, где ссылки
 * меряются по якорю, а в чат уезжал уже закрытый блок, где они меряются
 * целиком. Фаззинг подписи к медиа (лимит 1000, жёсткий предел Telegram 1024)
 * находил части в 2771 символ.
 *
 * Здесь решение и балансировка наконец меряют одно и то же. Запас под
 * открывашку следующей части больше не нужен отдельно: та часть измерится
 * вместе со своим `head`.
 */
function withFenceMarkers(part: string, carry: string | null): string {
  const head = carry === null ? "" : carry + "\n";
  // Последнюю часть balanceFences намеренно не закрывает, но на этапе резки
  // неизвестно, последняя ли она. Считаем, что закроет: ошибка в эту сторону
  // делает часть короче, а не длиннее лимита.
  const open = fenceOpenAfter(head + part, null);
  return head + part + (open !== null ? "\n```" : "");
}

/**
 * Дописать блокам кода недостающие маркеры на швах между частями.
 *
 * Аудит 2026-08-19: `splitForTelegram` режет СЫРОЙ markdown по пустым строкам,
 * а пустая строка внутри ```-блока — обычное дело (лог, диф, конфиг). Замер на
 * логе из 120 строк с одним пустым разделителем: пять частей, во второй остаётся
 * осиротевшая открывашка, в последней — осиротевшая закрывашка, а середина
 * уезжает вообще без маркеров. Дальше `mdToTelegramHtml` видит непарные ``` и
 * не делает `<pre>` НИ В ОДНОЙ части: моноширинность пропадает целиком, ```
 * показываются читателю буквально, `*b*` и `_c_` внутри кода становятся
 * курсивом, `# header` — жирным, а строка `---` молча удаляется правилом
 * горизонтальной линии. То есть код не просто теряет оформление, он МЕНЯЕТСЯ.
 *
 * Последнюю часть не закрываем намеренно: если блок не закрыт в самом исходнике,
 * форматтер показывает его буквально — и разрезанный текст обязан выглядеть так
 * же, как неразрезанный. Закрывашку дописываем только там, где есть следующая
 * часть, в которую можно перенести открывашку.
 */
function balanceFences(parts: string[]): string[] {
  if (parts.length < 2) return parts;
  const out: string[] = [];
  let carry: string | null = null; // открывашка блока, разорванного предыдущей частью
  for (let i = 0; i < parts.length; i++) {
    const part = parts[i]!;
    const isLast = i === parts.length - 1;
    let open = carry;
    for (const m of part.matchAll(FENCE_RE())) {
      open = open === null ? openMarker(m[1]!) : null;
    }
    const head = carry === null ? "" : carry + "\n";
    const cut = open !== null && !isLast;
    out.push(head + part + (cut ? "\n" + "```" : ""));
    carry = cut ? open : null;
  }
  return out;
}

/**
 * `fits` — необязательная мерка части. По умолчанию сырая длина (как было);
 * отправляющим с `parse_mode` нужен `htmlPartFits`, иначе решение и резка
 * меряют разное.
 */
export function splitForTelegram(
  text: string,
  limit = TG_LIMIT,
  fits: (part: string) => boolean = (s) => s.length <= limit,
): string[] {
  // Пустой части в Telegram нет: она 400 «message text is empty». Правило
  // держал только flush(), то есть ровно тот путь, что собирает буфер (см.
  // ниже про hardSlice). Здесь оно объявлено один раз для всей функции.
  if (!text.trim()) return [];
  if (fits(text)) return [text];
  // Часть меряется с маркерами блока кода — см. withFenceMarkers.
  const hasFence = FENCE_RE().test(text);
  const fitsRaw = fits;
  // Открывашка, разорванная предыдущей частью: её допишет balanceFences в
  // начало текущей, значит и мерить надо вместе с ней.
  let carry: string | null = null;
  if (hasFence) {
    // Аудит 2026-08-28: мерить ТОЛЬКО закрытый вариант нельзя. Комментарий у
    // withFenceMarkers обещал, что ошибка идёт в безопасную сторону («часть
    // короче, а не длиннее лимита»), но она идёт в обе: mdToTelegramHtml при
    // ЗАКРЫТОМ блоке съедает lang-токен после ```, а при незакрытом блок не
    // распознаётся и токен считается целиком как обычный текст. Последнюю
    // часть balanceFences намеренно не закрывает (а при parts.length < 2
    // выходит сразу), так что расхождение реализуется всегда. Замер: текст,
    // оканчивающийся на ``` плюс токен из 8400 символов — померено 702,
    // отправлено 9105 при жёстком пределе 4096.
    //
    // Требуем прохождения обоих вариантов: и того, что уйдёт, если часть
    // окажется последней, и того, что уйдёт, если balanceFences её закроет.
    fits = (part: string) => {
      const head = carry === null ? "" : carry + "\n";
      return fitsRaw(head + part) && fitsRaw(withFenceMarkers(part, carry));
    };
  }
  const out: string[] = [];
  let buf = "";
  const push = (part: string) => {
    out.push(part);
    if (hasFence) carry = fenceOpenAfter(part, carry);
  };
  const flush = () => {
    if (buf.trim()) push(buf.trimEnd());
    buf = "";
  };
  const pushChunk = (sep: string, piece: string): boolean => {
    if (buf && !fits(buf + sep + piece)) flush();
    /*
     * Аудит 2026-08-27: `fits` замыкает ИЗМЕНЯЕМЫЙ `carry`, а `flush()` двумя
     * строками выше толкает часть в out и тем самым его сдвигает. Значит
     * замер куска, сделанный вызывающим ДО сброса, считал чётность фенсов
     * прежней: кусок, влезавший при закрытом блоке кода, после сброса едет с
     * дописанной открывашкой `carry + "\n"` и закрывашкой `"\n```"` — плюс до
     * восьми символов сверх лимита. Замер на limit=60,
     * "```\n" + "a"*40 + "\n\n" + "b"*53 + "\n\n" + "c"*50: вторая часть
     * выходит 61. Поэтому после сброса кусок меряется заново, уже с новым
     * carry, и при отказе решение принимает вызывающий — режет мельче.
     *
     * Пока это, как и разделитель ниже, гасит запас (4000 против 4096, 1000
     * против 1024), но запас — единственное, что стоит между этим и 400 от
     * Telegram.
     */
    if (!buf && !fits(piece)) return false;
    /*
     * Разделитель приклеивается ПОСЛЕ решения о сбросе и только если буфер не
     * пуст. Раньше он приходил внутри chunk: длину проверяли вместе с ним, а
     * после сброса всё равно дописывали в начало пустого буфера — часть
     * выходила на 2 символа (или на 1 при резке по одиночному \n) длиннее
     * лимита.
     */
    buf += buf ? sep + piece : piece;
    return true;
  };
  /*
   * 1) попытка по двойному \n (абзацы).
   *
   * Разделитель захватывается группой и склеивается обратно тем же, каким был.
   * Аудит 2026-08-28: до правки текст резался по `/\n\n+/`, а собирался
   * жёстким `"\n\n"`, то есть ЛЮБОЙ пробел в три и более перевода строки
   * необратимо схлопывался в два — включая пустые строки внутри ```-блока,
   * где они часть кода (PEP 8 отделяет функции верхнего уровня ровно двумя
   * пустыми строками), и включая случаи, когда резать вообще не пришлось:
   * текст короче лимита проходил через split/join и всё равно менялся.
   * Отправитель не имеет права переписывать текст, который ему дали.
   */
  const parts = text.split(/(\n{2,})/);
  for (let i = 0; i < parts.length; i += 2) {
    const p = parts[i];
    // Разделитель ПЕРЕД этим абзацем. Для первого его нет, но и не нужен:
    // буфер там пуст, а pushChunk клеит sep только к непустому буферу.
    const sep = i === 0 ? "\n\n" : parts[i - 1];
    // Отказ pushChunk означает «буфер уже сброшен, кусок не положен»: своего
    // flush() перед резкой по \n больше не нужно.
    if (pushChunk(sep, p)) continue;
    // абзац длиннее лимита — режем по \n
    const lines = p.split("\n");
    for (const line of lines) {
      if (!pushChunk("\n", line)) {
        // длинная строка без переносов — режем жёстко по limit
        // Аудит 2026-08-14: hardSlice кладёт куски в out МИМО flush, а значит
        // мимо единственной проверки на пустоту. Строка из одних пробелов
        // длиннее лимита (абзац-разделитель, отбитая таблица, артефакт
        // модели) давала части, состоящие целиком из пробелов. Замер на
        // `"x\n\n" + " ".repeat(5000) + "\n\ny"`: 4 части, из них 2
        // пустые — первая уходит в чат, вторая ловит 400 «message text is
        // empty», и всё действие объявляется неудачным, хотя часть текста уже
        // доставлена. Ретрай после этого пришлёт «x» вторым экземпляром.
        // Аудит 2026-08-28: комментарий ниже описывал намерение, а не код.
        // hardSlice жадная — она возвращала ВЕСЬ массив кусков до того, как
        // цикл начнёт их обрабатывать, а `carry` двигает `push` уже после всех
        // замеров. Правильно померен был только ПЕРВЫЙ кусок; остальные
        // мерились с чужой чётностью фенсов — ровно то, что комментарий обещал
        // не допускать. Фикс stale-carry от 2026-08-27 закрыл `pushChunk`, эту
        // ветку он не трогал. Замер: одна строка из 164 markdown-ссылок с
        // одним непарным ``` даёт часть в 10264 видимых символа при пределе
        // 4096 → 400 «message is too long» → PartialSendError, повтор запрещён
        // (sideEffect), остаток ответа теряется. Триггер достижим из
        // недоверенного ввода, который агент цитирует дословно: вложение через
        // READ_FILE, выдача web_search, текст пользователя.
        //
        // Нарезаем инкрементально: берём один кусок, двигаем carry, меряем
        // следующий уже актуальной чётностью.
        let at = 0;
        while (at < line.length) {
          const end = sliceOneEnd(line, at, limit, fits);
          const piece = line.slice(at, end);
          if (piece.trim()) push(piece);
          at = end;
        }
      }
    }
  }
  flush();
  return balanceFences(out);
}

/**
 * Отказ на середине многочастной отправки: часть сообщений уже в чате.
 *
 * Аудит 2026-08-13: исключение со второй части улетало наружу как обычная
 * ошибка, и вызывающий репортил провал целиком — хотя часть (1/3) уже висела в
 * чате. Дальше повтор: Telegram транзакций не знает и идемпотентности здесь ни
 * на одном уровне нет, поэтому вторая попытка дописывает ВТОРОЙ экземпляр уже
 * доставленных частей. Форма та же, что у осиротевшего баннера в
 * PUBLISH_TO_CHANNEL: половина side-effect'а состоялась, и об этом надо
 * сказать словами, а не подать как «ничего не произошло».
 *
 * Причина реальна и не редкая: у юзербота на каждую часть висит FLOOD_WAIT-гвард
 * (по части, а не по отправке целиком — см. dispatch/telegram.ts), и длинный
 * ответ — это N отдельных вызовов от аккаунта владельца.
 */
export class PartialSendError extends Error {
  constructor(
    readonly cause: unknown,
    readonly partsSent: number,
    readonly partsTotal: number,
  ) {
    super(
      `частичная доставка: ушло ${partsSent} из ${partsTotal} частей, ` +
        `затем ${cause instanceof Error ? cause.message : String(cause)}`,
    );
    this.name = "PartialSendError";
  }
}

/**
 * Отправка одного логического ответа: 1+ Telegram-сообщений. Возвращает
 * последнее sent.
 *
 * `onPart` зовётся после КАЖДОЙ удавшейся части — до того, как следующая может
 * бросить. Иначе о доставленном знает только эта функция: она бросает на
 * первой неудаче, а вызывающий видит исключение и ни одной части, хотя
 * пользователю уже ушло k из N сообщений. В message-handler на этом терялась
 * запись ответа в короткую память — см. комментарий у вызова.
 *
 * Часть отдаётся без счётчика «(i/N) »: счётчик — оформление доставки, а
 * потребителю нужен текст.
 */
export async function sendChunked(
  send: (text: string) => Promise<any>,
  text: string,
  onPart?: (sent: any, part: string, index: number, total: number) => void,
  /**
   * Мерка части. По умолчанию сырая длина — она верна для отправителей БЕЗ
   * `parse_mode`. Шлющие HTML передают `HTML_MESSAGE_FITS`, иначе решение
   * «влезает» и то, что считает Telegram, — разные величины.
   */
  fits?: (part: string) => boolean,
): Promise<any> {
  const parts = splitForTelegram(text, TG_LIMIT, fits);
  // Пустой результат — это «отправлять нечего», и молчать об этом нельзя:
  // раньше функция возвращала undefined, и дальше расходились два разных
  // вранья. Путь юзербота (dispatch/telegram.ts) сразу читал
  // `last.message_id` и падал с TypeError, а путь Bot API отдавал
  // `{ok: true, result: undefined}` — успех в аудите за неотправленное
  // сообщение. Третий потребитель, handoff, писал ответ делегата в историю
  // чата (`sent?.message_id`), которого в чате никогда не было.
  if (parts.length === 0) {
    throw new Error("нечего отправлять: текст пуст после разбиения");
  }
  let last: any;
  for (let i = 0; i < parts.length; i++) {
    const prefix = parts.length > 1 ? `(${i + 1}/${parts.length}) ` : "";
    try {
      last = await send(prefix + parts[i]);
    } catch (e) {
      // Первая часть — ничего не доставлено, это обычный провал: пробрасываем
      // как есть, чтобы не ломать разбор ошибок у вызывающих (isCaptionTooLong,
      // isPhotoRejected и прочие смотрят на исходное исключение).
      if (i === 0) throw e;
      throw new PartialSendError(e, i, parts.length);
    }
    onPart?.(last, parts[i]!, i, parts.length);
  }
  return last;
}
