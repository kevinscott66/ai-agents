/**
 * Классификация запроса «обслуживается ли он ДО стены аутентификации».
 *
 * Зачем отдельный модуль. Аудит 2026-09-19 (AUD-030): в miniapp-server.ts
 * перемешаны маршрутизация, продуктовая логика и безопасность, и цена этого
 * видна именно здесь. Классификация жила выражением внутри `fetch()`, а
 * перечень входов выше стены — прозой в шапке файла; шапка при этом сама
 * признаёт, что список пересчитывали четыре раза и каждый раз мимо. Сторож
 * `audit-2026-09-11-miniapp-preauth-exceptions` сверяет шапку с маршрутами,
 * но третью сторону — по какому правилу тот же запрос попадает в анонимное
 * ведро — не видит ни один тест. То есть маршрут можно поставить выше стены,
 * честно вписать в шапку, пройти сторожа и остаться вовсе без рейт-лимита.
 *
 * Правило одно и по ФОРМЕ пути, а не по памяти о списке маршрутов:
 * не под /api/, либо /api/health, либо OPTIONS. Так оно и было написано в
 * сервере — ценность выноса не в другом правиле, а в том, что теперь у него
 * есть имя, единственное место и контрактный тест, который сверяет его с
 * настоящим набором маршрутов выше стены.
 *
 * Граница модуля намеренно узкая: здесь нет ни Request, ни Response, ни
 * ведра — только путь и метод. Рейт-лимит остаётся в сервере; сюда переезжает
 * ровно вопрос классификации, который и разъезжался.
 */

/**
 * Обслуживается ли запрос до стены `authOr401`.
 *
 * `true` означает «этот запрос не попадёт ни в одно пользовательское ведро»:
 * вызывающий обязан снять с него анонимный токен ДО того, как случится чтение
 * файла с диска или обращение к БД.
 *
 * Метод приводится к верхнему регистру здесь: `Request.method` в Bun уже
 * нормализован, но эта функция принимает и строку из теста или из будущего
 * вызывающего, а «options» строчными не должен незаметно менять ответ.
 */
export function isPreAuthRequest(pathname: string, method: string): boolean {
  return (
    !pathname.startsWith("/api/") ||
    pathname === "/api/health" ||
    method.toUpperCase() === "OPTIONS"
  );
}

/**
 * Маршруты под /api/, которые отвечают выше стены, но `isPreAuthRequest`
 * их НЕ относит к анонимным — потому что ограничивают себя сами.
 *
 * Это не исключение из правила, а честный список долгов: для каждого такого
 * маршрута кто-то однажды проверил, что токен снимается внутри обработчика.
 * `/api/events` снимает его из общего GET-ведра пользователя (билет к этому
 * моменту погашен, id проверен) — см. ветку `path === "/api/events"`.
 *
 * Контрактный тест требует, чтобы список сходился с кодом в обе стороны:
 * каждый непокрытый правилом маршрут выше стены обязан быть здесь, и каждая
 * запись отсюда обязана и вправду стоять выше стены со своим рейт-лимитом.
 * Новый маршрут выше стены без лимита не пройдёт ни одну из двух проверок.
 */
export const SELF_LIMITED_PRE_WALL: readonly string[] = ["/api/events"];
