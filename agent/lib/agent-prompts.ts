/**
 * Блок памяти для system-промпта: индексы + хвост общего лога, за фенсом.
 *
 * Единый источник для обоих путей запуска (message-handler и handoff) — раньше
 * строка собиралась в каждом отдельно и уже расходилась.
 */
export function buildMemorySystemText(a: {
  agentKey: string;
  teamIndex: string;
  privateIndex: string;
  teamLog: string;
}): string {
  return (
    `${WIKI_TRUST_BOUNDARY}\n\n` +
    `=== ОБЩИЙ ИНДЕКС КОМАНДЫ (_team/index.md) ===\n` +
    `${untrusted("wiki:_team/index.md", a.teamIndex)}\n\n` +
    `=== ЛИЧНЫЙ ИНДЕКС (${a.agentKey}/index.md) ===\n` +
    `${untrusted(`wiki:${a.agentKey}/index.md`, a.privateIndex)}\n\n` +
    `=== ПОСЛЕДНИЕ ЗАПИСИ В ОБЩЕМ ЛОГЕ ===\n` +
    `${untrusted("wiki:_team/log.md", a.teamLog)}`
  );
}

/** Найденные страницы вики — тот же фенс. Пустой список → пустая строка. */
export function buildWikiPagesSystemText(
  pages: { scope: string; slug: string; body: string }[],
): string {
  if (pages.length === 0) return "";
  return (
    "=== РЕЛЕВАНТНЫЕ СТРАНИЦЫ ВИКИ (та же граница доверия) ===\n" +
    pages
      .map((p) => untrusted(`wiki:${p.scope}/${p.slug}`, p.body.slice(0, 1200)))
      .join("\n\n")
  );
}

