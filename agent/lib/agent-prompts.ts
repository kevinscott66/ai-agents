/**
 * Блок «сейчас» — дата, время, день недели и часовой пояс на момент хода.
 *
 * Аудит 2026-09-11: в system-промпте не было ни одного признака текущего
 * момента, а SCHEDULE_POST требует `scheduledAt` в Unix-миллисекундах. «Пост
 * на завтра в 10» модели было не от чего посчитать: опору она брала из
 * обучения и промахивалась на месяцы. День недели печатаем вместе с датой —
 * «в понедельник» без него так же неисчислимо, как «завтра» без числа.
 *
 * ВАЖНО, где этот блок стоит: он должен идти ПОСЛЕДНИМ и БЕЗ `cache_control`.
 * Кэш промпта режется по последней точке `cache_control`, всё до неё
 * переиспользуется между ходами. Минута в хвосте после последней точки не
 * стоит ничего, а та же минута среди кэшируемых блоков обнуляла бы кэш
 * каждый ход. Предыдущий такой хвост — блок страниц вики в обоих сборщиках.
 * Проверки места и отсутствия `cache_control` —
 * tests/audit-2026-09-11-now-in-system.test.ts.
 */
export function nowSystemText(now: Date = new Date()): string {
  return (
    `Сейчас: ${ruDateTime(now)}, ${ruWeekday(now)}.\n` +
    "Относительные сроки («сегодня», «завтра в 10», «в понедельник») считай " +
    "от этого момента, а не от чего-либо ещё. Там, где инструмент просит " +
    "время в Unix-миллисекундах, переводи в них уже посчитанный момент."
  );
}
