/**
 * Когда демон объявляет соединение с мостом потерянным — и ровно один раз.
 *
 * Аудит 2026-09-11, круг 30. Watchdog в daemon.ts заведён против «полуоткрытого
 * зомби»: SSH-туннель умирает молча (сон, смена сети), кадры не идут, а события
 * `close` нет минутами. Сам watchdog при этом делал так:
 *
 *     stopWatchdog();
 *     try { ws.close(); } catch {}
 *
 * и на этом заканчивался. Дальше всё держалось на одном допущении — что за
 * `ws.close()` последует событие `close`, в обработчике которого и стоит
 * `scheduleReconnect()`. На живом сокете так и есть. Но `close()` — это НАЧАЛО
 * закрывающего рукопожатия: кадр уходит в тот самый мёртвый туннель, ответного
 * кадра нет, и событие не приходит по той же причине, по которой не приходили
 * ping'и. Watchdog к этому моменту уже остановлен, второй попытки нет ни у кого.
 *
 * То есть в точности тот случай, ради которого watchdog написан — тихо
 * умерший туннель, — оставлял демон висеть навсегда, и «мак в сети → сессия
 * подключается сама» не выполнялось. Обычный обрыв (RST, закрытие мостом) шёл
 * через `close` и лечился, поэтому дыра не попадалась на глаза.
 *
 * Отсюда два правила, и оба живут здесь, а не в обработчиках:
 *
 *  1. После принудительного закрытия взводится запасной срок. Не пришло
 *     событие `close` за `graceMs` — реконнектимся без него.
 *  2. Объявить соединение потерянным можно ровно один раз. Иначе запоздавшее
 *     событие `close` после сработавшего запасного срока даст ВТОРОЙ
 *     scheduleReconnect, то есть два параллельных сокета к мосту, из которых
 *     мост оставит активным последний, а первый будет тихо жрать backoff.
 *
 * Здесь нет ни таймеров, ни сокетов: и то и другое приходит параметрами,
 * поэтому весь порядок проверяется без сети и без ожидания в тестах.
 */

/** Почему соединение объявлено потерянным. Идёт только в лог. */
export type GiveUpReason = "close_event" | "close_timeout" | "connect_failed";

export type SocketLifecycleDeps = {
  /** Закрыть сокет (начало рукопожатия; может не завершиться никогда). */
  close: () => void;
  /** Позвать реконнект. Вызывается не более одного раза за жизнь объекта. */
  onGiveUp: (reason: GiveUpReason) => void;
  /** setTimeout в бою; в тестах — ручной. */
  setTimer: (fn: () => void, ms: number) => unknown;
  /** clearTimeout в бою. */
  clearTimer: (t: unknown) => void;
  /** Сколько ждать события `close` после принудительного закрытия. */
  graceMs: number;
};

export type SocketLifecycle = {
  /** Уже объявлено потерянным: кадры этого сокета больше не наши. */
  abandoned: () => boolean;
  /** Пришло событие `close`. */
  noticedClose: () => void;
  /** Watchdog: тишина дольше порога — закрыть и не ждать вечно. */
  forceClose: () => void;
  /** Сокет не открылся вовсе (ошибка конструктора). */
  connectFailed: () => void;
};

export function createSocketLifecycle(deps: SocketLifecycleDeps): SocketLifecycle {
  let done = false;
  let graceTimer: unknown = null;

  const giveUp = (reason: GiveUpReason): void => {
    if (done) return;
    done = true;
    if (graceTimer !== null) {
      deps.clearTimer(graceTimer);
      graceTimer = null;
    }
    deps.onGiveUp(reason);
  };

  return {
    abandoned: () => done,
    noticedClose: () => giveUp("close_event"),
    connectFailed: () => giveUp("connect_failed"),
    forceClose: () => {
      // Взведённый срок означает, что закрытие уже запрошено. Повторное
      // `close()` на закрывающемся сокете ничего не ускоряет, а по логам
      // читается как второй обрыв, которого не было.
      if (done || graceTimer !== null) return;
      // Закрытие может бросить на уже мёртвом сокете — это не повод не
      // реконнектиться, поэтому запасной срок взводится в любом случае.
      try {
        deps.close();
      } catch {
        /* мёртвый сокет — ровно тот случай, ради которого мы здесь */
      }
      graceTimer = deps.setTimer(() => giveUp("close_timeout"), deps.graceMs);
    },
  };
}
