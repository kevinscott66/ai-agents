/**
 * Гейт «мост подтвердил себя» для направления мост→демон.
 *
 * Аутентификация в этом протоколе односторонняя. Демон первым кадром шлёт
 * секрет, и мост до `auth_ok` не принимает от клиента ничего (`mac-bridge.ts`,
 * `state.authed`). Обратной проверки не было вовсе: `daemon.ts` разбирал кадр и
 * сразу уходил в switch по типу, так что `run` исполнялся у того, кто вообще не
 * знал секрета.
 *
 * Это не теоретическая симметрия. `bridge-url.ts` намеренно разрешает плейнтекст
 * на loopback, потому что боевая схема — SSH-туннель на 127.0.0.1:8788
 * (`DEFAULT_MAC_BRIDGE_PORT`; 8787 — это HTTP-порт Mini App, и перепутать их
 * здесь дороже всего). Процесс,
 * занявший порт моста раньше туннеля (туннель упал, гонка при загрузке), для
 * демона неотличим от моста: секрет ему не нужен, он его игнорирует и шлёт
 * `run` с `mode: "bypass"` — то есть `claude --permission-mode bypassPermissions`
 * в проекте владельца. Аллоулист проектов здесь не спасает: он ограничивает
 * КУДА, а не КТО.
 *
 * Гейт — объект на соединение, а не модульный флаг: реконнект обязан начинать
 * с нуля, иначе один удачный коннект к настоящему мосту открывал бы двери всем
 * последующим.
 */
import type { ParsedMsg } from "./protocol.ts";

/**
 * Что мост вправе прислать до `auth_ok`.
 *
 * `ping` здесь потому, что мост пингует сокет и считает мак мёртвым без `pong`;
 * молчать в ответ на пинг — значит ломать живое соединение ради проверки,
 * которая от пинга ничего не защищает (он ничего не исполняет). `auth_ok` и
 * `auth_fail` — сами кадры рукопожатия.
 *
 * Всё остальное исполняет или останавливает процессы на машине владельца и
 * ждёт своей очереди: `run`, `cancel`, `stop`, а также `bad_run` — ответ на
 * него подтверждает «демон здесь и слушает» тому, кто ещё никто.
 */
const PRE_AUTH_ALLOWED: ReadonlySet<string> = new Set([
  "ping",
  "auth_ok",
  "auth_fail",
]);

export interface BridgeAuthGate {
  /** Приходил ли `auth_ok` в этом соединении. */
  readonly authenticated: boolean;
  /** Отметить, что мост подтвердил себя. */
  markAuthenticated(): void;
  /** Можно ли исполнять этот кадр в текущем состоянии соединения. */
  accepts(msg: ParsedMsg): boolean;
}

/** Новый гейт для одного соединения. */
export function createAuthGate(): BridgeAuthGate {
  let authed = false;
  return {
    get authenticated(): boolean {
      return authed;
    },
    markAuthenticated(): void {
      authed = true;
    },
    accepts(msg: ParsedMsg): boolean {
      if (msg === null) return false;
      if (authed) return true;
      return PRE_AUTH_ALLOWED.has(msg.type);
    },
  };
}
