import { describe, expect, test } from "bun:test";
import { extractJson } from "../tools/daily-draft";

/**
 * Аудит 2026-09-30: черновик дня терялся из-за одного сырого перевода строки.
 *
 * Юнит `delabs-daily-draft` 29.09 в 08:03 UTC упал с
 *   [daily-draft] research failed: JSON Parse error: Unterminated string
 * и черновика в тот день не было вовсе. Сообщение уводит в сторону: «строка не
 * закрыта» звучит как обрыв ответа по лимиту или таймауту, и именно так это
 * читалось в журнале. На деле скобки были сбалансированы, кавычки закрыты, а
 * запрещён был один байт — НАСТОЯЩИЙ `\n` внутри JSON-строки. Промпт просит
 * `body` из нескольких абзацев; абзацы модель разделила переводом строки, а не
 * `\n`, — и весь дневной ресёрч уходил в отказ.
 *
 * Ждать идеального экранирования от модели нельзя, а сканер `extractJson` и так
 * знает про каждый символ, внутри строки он или нет. Теперь он по пути
 * экранирует управляющие символы. Тесты закрепляют обе стороны: сырой перевод
 * строки больше не отказ, а корректный JSON разбирается ровно как прежде.
 *
 * Отдельно проверяется, что настоящий обрыв ответа НЕ стал зелёным: у него
 * скобки не сходятся, и он падает с «unbalanced JSON braces» — с диагнозом, по
 * которому видно, что случилось.
 */
const ITEM = '"items":[{"text":"Источник","url":"https://example.dev/a"}]';

function wrap(body: string): string {
  return `Вот результат ресёрча:\n{"articles":[{"title":"A","date":"2026-09-30","summary":"s","body":${body},${ITEM}}]}`;
}

describe("разбор ответа ресёрча", () => {
  test("сырой перевод строки внутри строки — не отказ (прод 29.09)", () => {
    const raw = wrap('"Первый абзац.\nВторой абзац."');
    const got = extractJson(raw);
    expect(got.articles).toHaveLength(1);
    // Перевод строки сохраняется как перевод строки: текст абзацев доезжает до
    // сайта целиком, а не склеенным и не обрезанным по первому абзацу.
    expect(got.articles[0].body).toBe("Первый абзац.\nВторой абзац.");
  });

  test("возврат каретки и табуляция тоже не роняют разбор", () => {
    const got = extractJson(wrap('"строка\r\nдругая\tс табом"'));
    expect(got.articles[0].body).toBe("строка\r\nдругая\tс табом");
  });

  test("корректный JSON разбирается как прежде", () => {
    const got = extractJson(wrap('"Абзац.\\nВторой абзац."'));
    expect(got.articles[0].body).toBe("Абзац.\nВторой абзац.");
    expect(got.articles[0].items).toEqual([
      { text: "Источник", url: "https://example.dev/a" },
    ]);
  });

  test("экранированная кавычка внутри строки не закрывает её", () => {
    const got = extractJson(wrap('"он сказал \\"да\\" и ушёл"'));
    expect(got.articles[0].body).toBe('он сказал "да" и ушёл');
  });

  test("настоящий обрыв ответа по-прежнему отказ, и с внятным диагнозом", () => {
    // Скобки не сходятся — это и есть обрыв, в отличие от случая выше.
    expect(() => extractJson('{"articles":[{"title":"A","body":"текст')).toThrow(
      "unbalanced JSON braces",
    );
  });

  test("объект без articles[] — отказ, а не пустой черновик", () => {
    expect(() => extractJson('{"result":"ничего не нашёл"}')).toThrow("JSON has no articles[]");
  });

  test("текст без JSON вовсе — отказ", () => {
    expect(() => extractJson("не смог собрать статьи")).toThrow("no JSON object in model output");
  });
});
