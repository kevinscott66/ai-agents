/**
 * Аудит 2026-09-11, круг 29: счётное слово в шапке `lib/tools-schema.ts`
 * протухло на два, и протухло молча.
 *
 * Шапка написана как разбор чужой ошибки: прежний текст утверждал «все 12
 * инструментов идут через единый `gateOrDispatch`», и абзац объясняет, почему
 * это неверно дважды — инструментов в `TOOL_NAMES` не двенадцать, а двенадцать
 * это как раз `INLINE_TOOL_NAMES`, то есть набор, который через гейт НЕ идёт.
 * Объяснение держится на двух числах. К кругу 29 первое из них стало ложью:
 * написано «двадцать три», в наборе двадцать пять.
 *
 * Цена выше обычной опечатки. Абзац читают не ради арифметики, а чтобы понять
 * границу: что гейтуется, а что замыкается до гейта. Разъехавшееся число —
 * первый признак, что разъехалась и граница; читатель, сверившийся с ним,
 * решит, что знает состав, и не пойдёт смотреть, кто добавился последним. А
 * добавляются туда ровно те действия, у которых есть внешний эффект.
 *
 * Проза здесь нужна — это единственное место, где сказано, ПОЧЕМУ наборов два.
 * Убрать числа значит убрать и объяснение. Поэтому не «не писать чисел», а
 * «числа сверяются машиной»: набор растёт — падает этот тест, а не доверие к
 * абзацу. Та же развилка, что у tests/audit-2026-09-11-admin-read-routes.
 */
import { test, expect, describe } from "bun:test";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { TOOL_NAMES, INLINE_TOOL_NAMES } from "../lib/tools-schema.ts";

/**
 * Шапка одной строкой: маркеры комментария и переносы сняты.
 *
 * Без этого проверка ловила бы не ложь, а вёрстку: «двенадцать — это» и
 * «`INLINE_TOOL_NAMES`» стоят по разные стороны переноса, и дословное вхождение
 * не находится, хотя написано ровно то, что нужно. Ровно та же склейка, что в
 * tests/audit-2026-09-11-symbol-plus-coordinate, и заведена по той же причине.
 */
const HEADER = readFileSync(join(import.meta.dir, "..", "lib", "tools-schema.ts"), "utf8")
  .split("*/")[0]
  .replace(/^\s*(\/\*\*?|\*)\s?/gm, "")
  .replace(/\s+/g, " ");

/**
 * Числительные словами — так, как их пишут в этом файле.
 *
 * Список закрыт намеренно и покрывает обозримый рост: наборы прибавляют по
 * одному инструменту за релиз. Выход за границу роняет тест сам — `words[n]`
 * даст `undefined`, и `toContain(undefined)` не пройдёт молча.
 */
const WORDS: Record<number, string> = {
  10: "десять", 11: "одиннадцать", 12: "двенадцать", 13: "тринадцать",
  14: "четырнадцать", 15: "пятнадцать", 16: "шестнадцать", 17: "семнадцать",
  18: "восемнадцать", 19: "девятнадцать", 20: "двадцать",
  21: "двадцать один", 22: "двадцать два", 23: "двадцать три",
  24: "двадцать четыре", 25: "двадцать пять", 26: "двадцать шесть",
  27: "двадцать семь", 28: "двадцать восемь", 29: "двадцать девять",
  30: "тридцать",
};

describe("числа в шапке tools-schema сверены с наборами", () => {
  test("названный размер TOOL_NAMES совпадает с настоящим", () => {
    const word = WORDS[TOOL_NAMES.size];
    expect(word).toBeString();
    expect(HEADER).toContain(`Инструментов в \`TOOL_NAMES\` ${word}`);
  });

  test("названный размер INLINE_TOOL_NAMES совпадает с настоящим", () => {
    const word = WORDS[INLINE_TOOL_NAMES.size];
    expect(word).toBeString();
    expect(HEADER).toContain(`${word} — это \`INLINE_TOOL_NAMES\``);
  });

  test("наборы не пересекаются — иначе сумма в шапке считает дважды", () => {
    // Абзац противопоставляет их («тот набор, который через gateOrDispatch как
    // раз НЕ идёт»); общий элемент сделал бы противопоставление бессмысленным
    // раньше, чем разъехались бы числа.
    const both = [...INLINE_TOOL_NAMES].filter((n) => TOOL_NAMES.has(n));
    expect(both).toEqual([]);
  });
});
