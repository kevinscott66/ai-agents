/**
 * Аудит 2026-09-11, круг 20: координаты вида `модуль.ts:471` в комментариях
 * протухают молча.
 *
 * В этом репозитории комментарий — источник правды наравне с кодом: почти
 * каждая правка аудита начинается словами «докстрока утверждала X, а код
 * делает Y». Ссылка на номер строки ломается иначе, чем текст: её ломает не
 * правка того места, на которое она указывает, а ЛЮБАЯ вставка выше по файлу.
 * Автор ссылки при этом ничего не редактирует и ни о чём не узнаёт.
 *
 * Цена — не «неточность». Читатель (человек или роль) идёт по координате и
 * читает ТАМ ДРУГОЙ КОД, приняв его за названный. Два свежих примера, оба
 * найдены этим тестом: `lib/dispatch/media.ts` посылал за списком ролей
 * GENERATE_IMAGE по координате, где давно лежит абзац про
 * `mac_bridge_connected`; `lib/dispatch/build-payload.ts` посылал за
 * `ORDER BY priority DESC` туда, где стоит `vals.push(task.id)`. Ни одна
 * из двух координат не указывала на названное — оба комментария теперь
 * называют символ (`ROLE_EXPOSED_TOOLS`, `listTasksByAssignee`) и не тухнут.
 *
 * Проверить «координата указывает на то, что имел в виду автор» машина не
 * может. Проверить «координата указывает хоть на что-то» — может, и этого
 * достаточно: сдвиг файла вставкой почти всегда выносит ссылку на пустую
 * строку, закрывающую скобку или хвост комментария. Так найдены все 46
 * протухших ссылок круга 20.
 *
 * Что делать, когда тест упал: НЕ подгонять номер. Убрать номер и назвать
 * символ — `permissions.ts`, запись `GENERATE_IMAGE` — такая ссылка не тухнет
 * вовсе. Номер оставляют только там, где называть нечего.
 *
 * Круг 27: проверка смотрела в три корня и только на `.ts`, то есть не видела
 * ни одного файла Mini App — а это единственное место в репозитории, где
 * комментарий описывает то, что человек видит на экране. Расширение до `.tsx`
 * и до `tools`/`mac-daemon`/`miniapp/src` сразу нашло протухшее там.
 *
 * Круг 51 закрыл две дыры этого же рода, обе структурные.
 *
 * Первая: корни перечисляли подкаталоги `agent/`, а верхний уровень — восемь
 * файлов, включая боевую точку входа прода, — не смотрел ни один из четырёх
 * докблок-сторожей. Корни и обход переехали в общий хелпер, и верхний уровень
 * теперь входит в область; см. tests/helpers/docblock-gate-scope.ts.
 *
 * Вторая: `COORD` матчился построчно, поэтому координата, у которой путь
 * остался в конце одной строки комментария, а номер уехал в начало следующей,
 * была невидима — при том что соседний сторож связки «имя + номер» такой
 * перенос склеивал ещё с круга 29. Разбор шва — `wrappedCoords` ниже.
 */
import { test, expect, describe } from "bun:test";
import { readFileSync } from "node:fs";
import { join, dirname, normalize, basename } from "node:path";
// Корни и обход — одни на три докблок-сторожа, см. докблок хелпера.
import { gateFiles } from "./helpers/docblock-gate-scope.ts";
/** Куда ссылаются: там ищем цель, если путь ссылки не разрешился как есть. */
const LOOKUP_DIRS = [
  "lib",
  "lib/dispatch",
  "orchestrator",
  "tests",
  "tools",
  "mac-daemon",
  "miniapp/src",
  "miniapp/src/lib",
  "miniapp/src/pages",
  "miniapp/src/components",
];

/**
 * Ссылка на строку файла: `путь/модуль.ts:471` либо `Страница.tsx:471-480`.
 *
 * Круг 30: проверялся только `.ts`/`.tsx`, и это оказалось самой большой
 * дырой сторожа. Комментарии этого репозитория ссылаются номерами не только на
 * код: `.env.example` (какую переменную владелец обязан поставить; таких файлов
 * в дереве два — корневой и `agent/`, поэтому `resolveTarget` пробует cwd
 * раньше корня), `deploy/*.sh`
 * (какой шаг катит сайт), `*.service`, `docs/*.md`. Такие ссылки тухнут ЧАЩЕ
 * кодовых — `.env.example` растёт вставками в середину, — и не проверялись
 * ничем. Замер по дереву: 33 такие ссылки, 28 разрешились, 21 протухла.
 *
 * Улов был не косметическим, и примеры здесь описаны словами, без номеров:
 * своя же докстрока не должна заводить ту самую гниль, которую сторожит.
 * Три места подряд обещали строку с `NODE_ENV` в agent/.env.example, а
 * координата вела на строку с именем токена — читатель, идущий за настройкой
 * окружения, попадал на секрет. Другая пара обещала флаг ночного обслуживания
 * (`DB_MAINT_ENABLED`), а отдавала соседний выключатель веб-поиска, который
 * легко принять за нужный и выставить не тот.
 */
const COORD = /([A-Za-z0-9_./-]+\.(?:tsx?|sh|service|timer|md|example|ya?ml|sql)):(\d+)(?:-(\d+))?/g;

/**
 * Смотрим только комментарии.
 *
 * Дефект — врущий комментарий, а не врущая строка кода: в коде такая же
 * координата это обычно фикстура — строка стека, которую подают на вход
 * `isTelegrafNoise`. Она ни на что не ссылается и протухнуть не может.
 */
const COMMENT_LINE = /^\s*(\/\/|\*|\/\*)/;

/**
 * Строка «ни на что»: пустая либо только из закрывающей пунктуации.
 *
 * Список закрытый и намеренно узкий: тест обязан ловить протухшее, а не
 * спорить о стиле. Всё, где есть хоть какой-то идентификатор, считается
 * содержимым — даже если автор имел в виду соседнюю строку.
 */
const EMPTY_TARGET = new Set([
  "", "}", "};", "});", "),", ")", ");", "],", "]", "*/", "{", "//",
  // Круг 30, продолжение списка. TS-пунктуация: `},` закрывает элемент
  // объекта, `/**` открывает докблок — ссылаться на них нечем так же, как на
  // `}`. Замер: три формы, пять попаданий, все пять протухшие.
  "},", "/**",
  // Пунктуация shell и systemd: расширение COORD на `.sh`/`.service` завело
  // в проверку файлы, у которых своя закрывающая лексика. Без неё из 21
  // измеренного протухания машина ловила бы три.
  "esac", ";;", "fi", "done", "else", "EOF", "then", "do", "*/;",
]);

/**
 * `} catch (e) {` и родня — тоже «ни на что».
 *
 * Списком это не берётся: имя пойманной ошибки у каждого своё. А идентификатор
 * внутри `catch (…)` — не содержимое, на которое ссылаются, а служебное имя,
 * поэтому исключение из правила «есть идентификатор — значит содержимое» здесь
 * осознанное и узкое. Замер: четыре ссылки из четырёх протухшие.
 */
const EMPTY_CATCH = /^\}?\s*catch\s*(\([^)]*\))?\s*\{$/;


const cache = new Map<string, string[] | null>();
function fileLines(p: string): string[] | null {
  if (!cache.has(p)) {
    try {
      cache.set(p, readFileSync(p, "utf8").split("\n"));
    } catch {
      cache.set(p, null);
    }
  }
  return cache.get(p) ?? null;
}

/**
 * Путь ссылки → реальный файл, либо null (цель вне проверки: фикстуры, чужие деревья).
 *
 * Круг 29: добор по имени файла отбрасывал каталог из ссылки целиком, и
 * `dispatch/tasks.ts:43` сверялся с `lib/tasks.ts` — LOOKUP_DIRS перечисляет
 * `lib` раньше `lib/dispatch`, а имя там совпадает. Это хуже, чем пропуск:
 * сторож не молчал, он ОТВЕЧАЛ, только про другой файл. Обе ссылки на
 * `lib/dispatch/tasks.ts` протухли давно и держались зелёными ровно потому,
 * что в `lib/tasks.ts` на тех же номерах случайно лежал текст.
 *
 * Поэтому ссылка с каталогом принимается только как ХВОСТ настоящего пути:
 * `dispatch/tasks.ts` ← `lib/dispatch/tasks.ts` да, `lib/tasks.ts` нет. Голое
 * имя файла — давняя идиома репозитория (`commands.ts:N` из теста про
 * `lib/commands.ts`), её добор по имени и обслуживает.
 */
export function resolveTarget(from: string, ref: string): string | null {
  // Круг 30: к двум прежним кандидатам добавлены корень репозитория и снятие
  // префикса `agent/`. Первое нужно ссылкам на `deploy/*.sh` и `docs/*.md` —
  // они лежат ВЫШЕ cwd теста; второе — идиоме «пишу полный путь от корня
  // репозитория», которой пользуются тесты: `agent/lib/miniapp-server.ts` с
  // номером строки на конце. Номера здесь нет намеренно — пример ссылки,
  // который сам протухает, стоил бы этому сторожу красноты на каждой правке
  // цитируемого файла.
  //
  // Порядок кандидатов — это ответ на неоднозначность, а не мелочь. Файл
  // `.env.example` есть и в `agent/`, и в корне; ссылки на него идут из
  // `agent/**` и имеют в виду свой. Поэтому cwd проверяется РАНЬШЕ корня, и
  // добор наверх срабатывает только когда рядом ничего нет.
  const candidates = [
    normalize(join(dirname(from), ref)),
    normalize(ref),
    normalize(join("..", ref)),
  ];
  if (ref.startsWith("agent/")) candidates.push(normalize(ref.slice("agent/".length)));
  for (const c of candidates) {
    if (fileLines(c)) return c;
  }
  const suffix = normalize(ref);
  /**
   * Добор по голому имени файла.
   *
   * Круг 29 закрыл случай, когда ссылка С каталогом разрешалась в одноимённый
   * файл из ДРУГОГО каталога. Голое имя осталось играть в рулетку: кандидатов
   * может быть несколько, и выигрывал первый по `LOOKUP_DIRS`, то есть `lib`.
   * Замер круга 30: 96 ссылок разрешаются добором, у семи есть одноимённый
   * сосед (`permissions.ts` ×5, `tasks.ts` ×2). Сегодня выбор угадывает, но
   * держится он на порядке элементов массива — а не на факте.
   *
   * Поэтому при нескольких кандидатах возвращаем null: молчание сторожа
   * честнее уверенного ответа про чужой файл. Это тот же урок, что и в
   * круге 29, доведённый до второй половины функции.
   */
  const hits: string[] = [];
  for (const d of LOOKUP_DIRS) {
    const c = join(d, basename(ref));
    if (!fileLines(c)) continue;
    if (suffix.includes("/") && c !== suffix && !c.endsWith("/" + suffix)) continue;
    if (!hits.includes(c)) hits.push(c);
  }
  return hits.length === 1 ? hits[0] : null;
}

/** Тело строки комментария без открывашки: `* текст` → `текст`. */
function commentBody(line: string): string {
  return line.replace(/^\s*(\/\*\*?|\/\/|\*)\s?/, "").trimEnd();
}

/**
 * Координаты, разорванные переносом строки внутри одного комментария.
 *
 * Аудит 2026-09-11, круг 51. Сторож матчил `COORD` построчно, и ссылка,
 * у которой путь остался в конце одной строки, а номер уехал в начало
 * следующей, была для него невидима. Замер: так жила протухшая ссылка на
 * `dispatch/diagnostic-action.ts` в `lib/diagnostic.ts` — файл внутри корней,
 * координата внутри комментария, и всё равно ноль срабатываний.
 *
 * Склеиваем пару соседних строк комментария и берём ТОЛЬКО те совпадения,
 * которые пересекают шов. Всё, что уместилось в одну строку, уже посчитано
 * основным проходом, и второй раз его считать нельзя.
 */
export function wrappedCoords(lines: string[], i: number): RegExpMatchArray[] {
  const next = lines[i + 1];
  if (next === undefined || !COMMENT_LINE.test(next)) return [];
  const head = commentBody(lines[i]);
  const glued = head + commentBody(next);
  const out: RegExpMatchArray[] = [];
  for (const m of glued.matchAll(COORD)) {
    const start = m.index ?? 0;
    if (start < head.length && start + m[0].length > head.length) out.push(m);
  }
  return out;
}

/** Приговор одной координате: пусто — ссылка жива. */
function verdict(file: string, i: number, m: RegExpMatchArray): string[] {
  const target = resolveTarget(file, m[1]);
  if (!target) return []; // цель не из этого дерева — не наша ссылка
  const body = fileLines(target)!;
  const n = Number(m[2]);
  if (n < 1 || n > body.length) {
    return [`${file}:${i + 1} → ${m[0]} (в файле ${body.length} строк)`];
  }
  const at = body[n - 1].trim();
  if (EMPTY_TARGET.has(at) || EMPTY_CATCH.test(at)) {
    return [`${file}:${i + 1} → ${m[0]} указывает на ${JSON.stringify(at)}`];
  }
  return [];
}

describe("координаты строк в комментариях не протухли", () => {
  test("каждая ссылка `модуль.ts:N` указывает на строку с содержимым", () => {
    const stale: string[] = [];
    for (const file of gateFiles({ skipFixtures: true })) {
      const lines = fileLines(file);
      if (!lines) continue;
      lines.forEach((line, i) => {
        if (!COMMENT_LINE.test(line)) return;
        for (const m of line.matchAll(COORD)) stale.push(...verdict(file, i, m));
        // Круг 51: та же координата, разложенная на две строки комментария.
        for (const m of wrappedCoords(lines, i)) stale.push(...verdict(file, i, m));
      });
    }
    expect(stale).toEqual([]);
  });

  test("координата, разорванная переносом строки, видна сторожу", () => {
    // Та самая форма из круга 51: путь дописан до конца строки, номер уехал
    // в начало следующей. Проверяем сам разбор, а не живой файл: образец,
    // привязанный к чужим номерам, протухал бы вместе с ними.
    const lines = [
      " * Соседний вызывающий (dispatch/diagnostic-action.ts:",
      " * 205-218) устроен наоборот",
      "const x = 1;",
    ];
    expect(wrappedCoords(lines, 0).map((m) => m[0])).toEqual([
      "dispatch/diagnostic-action.ts:205-218",
    ]);
  });

  test("координата, целиком уместившаяся в строке, вторым проходом не считается", () => {
    // Иначе каждая живая ссылка попала бы в улов дважды.
    const lines = [" * см. lib/tasks.ts:10 — там", " * продолжение"];
    expect(wrappedCoords(lines, 0)).toEqual([]);
  });

  test("шов с некомментарной строкой не склеивается", () => {
    const lines = [" * хвост lib/tasks.ts:", "10;"];
    expect(wrappedCoords(lines, 0)).toEqual([]);
  });

  test("ссылка с каталогом разрешается в файл ИЗ ЭТОГО каталога", () => {
    // Оба файла существуют и называются одинаково; до круга 29 добор по имени
    // отдавал первый по списку LOOKUP_DIRS, то есть `lib/tasks.ts`.
    expect(fileLines("lib/tasks.ts")).not.toBeNull();
    expect(fileLines("lib/dispatch/tasks.ts")).not.toBeNull();
    expect(resolveTarget("tests/x.test.ts", "dispatch/tasks.ts")).toBe("lib/dispatch/tasks.ts");
  });

  test("голое имя файла по-прежнему добирается по каталогам", () => {
    // Идиома репозитория: из теста пишут `commands.ts:N` про `lib/commands.ts`.
    expect(resolveTarget("tests/x.test.ts", "commands.ts")).toBe("lib/commands.ts");
  });

  test("каталог, которого нет ни у одного настоящего пути, целью не считается", () => {
    // Иначе сторож снова начнёт отвечать про чужой файл.
    expect(resolveTarget("tests/x.test.ts", "нет-такого/tasks.ts")).toBeNull();
  });
});
