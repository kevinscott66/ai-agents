/**
 * Убрать комментарии из исходника — для тестов, которые утверждают что-то о
 * КОДЕ, а не о документации. Такие утверждения без этого ложны по построению:
 * докстрока правки почти всегда цитирует форму, которую правка убрала.
 *
 * Порядок обязателен: строчные комментарии первыми.
 *
 * Аудит 2026-09-11: помощник жил копией в каждом тесте, и во всех копиях
 * блочные комментарии вырезались ПЕРВЫМИ. На `orchestrator/message-handler.ts`
 * это съедало половину файла: в строчном комментарии там стоит `image/*`
 * (нормализация MIME вложений), нежадный `/\*[\s\S]*?\*\//` цеплялся за него и
 * закрывался на `*` следующей докстроки — шестнадцать килобайт кода исчезали
 * молча, а утверждения вида `not.toContain(...)` на исчезнувшем коде проходили
 * впустую. Строчные комментарии, снятые первыми, уносят `image/*` с собой.
 *
 * Обратный порядок безвреден для `//` внутри блочных комментариев: строка
 * обрезается, но её `*​/` (если он на той же строке) остался бы за бортом — в
 * этом репозитории докстроки закрываются на отдельной строке, и такого случая
 * нет. Строки и regex-литералы с `//` внутри (URL, `TEXT_DOC_EXT`) обрезаются
 * тоже, поэтому утверждать про такие строки через этот помощник нельзя —
 * смотрите на сырой исходник.
 */
export function stripComments(src: string): string {
  return src
    .replace(/^[ \t]*\/\/.*$/gm, "")
    .replace(/\/\*[\s\S]*?\*\//g, "");
}
