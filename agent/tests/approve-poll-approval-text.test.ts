/**
 * Аудит 2026-08-12: апрув черновика срабатывал на подстроку — отказ владельца
 * публиковал пост подписчикам и на сайт.
 *
 * Было:
 *   const s = (t || "").toLowerCase();
 *   return s.includes("+") || s.includes("✅") || s.includes("опубликов");
 *
 * Это не разбор ответа, а поиск подстроки. Любой reply на превью, где плюс
 * встречается где угодно («переделай второй пункт + добавь источник»,
 * «это не публикуем, +1 к правкам»), считался «публиковать». Хуже:
 * `includes("опубликов")` матчит и само отрицание — «не опубликовывай»,
 * «пока не опубликовано».
 *
 * Механизма отказа не было вообще: единственный способ НЕ опубликовать —
 * молчать 24 часа до MAX_AGE_MS. То есть ЕДИНСТВЕННЫЙ способ ответить на
 * превью текстом был опасен — почти любая правка содержит либо «+», либо
 * слово «опубликов».
 *
 * Цена ошибки максимальная и необратимая: следующий запуск
 * delabs-approve-poll.timer (каждые 30 мин) ингестит все статьи на
 * delabs.space (страницы + RSS) и постит дайджест подписчикам @delabsru через
 * юзербот. Ни отозвать RSS, ни «разотправить» пост нельзя.
 *
 * Инвариант: апрув — это короткий однозначный ответ целиком («+», «✅», «да»,
 * «публикуем»). Любой ответ с содержательным текстом — НЕ апрув; путь по
 * умолчанию — не публиковать. Реакция ✅ на превью остаётся вторым, отдельным
 * каналом апрува и этой функции не касается.
 */
import { describe, test, expect } from "bun:test";
import { isApprovalText } from "../tools/approve-poll.ts";

describe("апрув: короткий однозначный ответ", () => {
  test("канонические формы принимаются", () => {
    for (const yes of [
      "+",
      "++",
      "✅",
      " + ",
      "да",
      "Да!",
      "ок",
      "ОК",
      "ok",
      "го",
      "публикуем",
      "Публикуем.",
      "опубликовать",
      "+✅",
    ]) {
      expect(isApprovalText(yes)).toBe(true);
    }
  });
});

describe("апрув: правка с плюсом внутри — НЕ апрув", () => {
  test("«переделай ... + ...» не публикует", () => {
    expect(isApprovalText("переделай второй пункт + добавь источник")).toBe(false);
  });

  test("«не публикуем, +1 к правкам» не публикует", () => {
    expect(isApprovalText("это не публикуем, +1 к правкам")).toBe(false);
  });

  test("плюс внутри числа или ссылки не считается апрувом", () => {
    expect(isApprovalText("рост +12% за неделю, поправь цифру")).toBe(false);
    expect(isApprovalText("источник: https://x.com/a?b=1+2")).toBe(false);
  });
});

describe("апрув: отрицание не читается как согласие", () => {
  test("«не опубликовывай» не публикует", () => {
    expect(isApprovalText("не опубликовывай пока")).toBe(false);
  });

  test("«пока не опубликовано» не публикует", () => {
    expect(isApprovalText("пока не опубликовано — жду правок")).toBe(false);
  });

  test("прямой отказ не публикует", () => {
    for (const no of ["нет", "-", "стоп", "отмена", "❌", "не надо", "переделай"]) {
      expect(isApprovalText(no)).toBe(false);
    }
  });

  test("«да» внутри другого слова не срабатывает", () => {
    expect(isApprovalText("даже не думай")).toBe(false);
    expect(isApprovalText("добавь дату")).toBe(false);
  });
});

describe("апрув: пустое и мусор — не апрув", () => {
  test("пустая строка, пробелы, undefined", () => {
    expect(isApprovalText("")).toBe(false);
    expect(isApprovalText("   ")).toBe(false);
    expect(isApprovalText(undefined as unknown as string)).toBe(false);
  });

  test("длинный текст без явного согласия", () => {
    expect(
      isApprovalText(
        "в целом норм, но третий пункт слишком короткий, раскрой что делать читателю",
      ),
    ).toBe(false);
  });
});
