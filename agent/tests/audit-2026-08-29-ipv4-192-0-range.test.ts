/**
 * Аудит 2026-08-29: SSRF-предикат резал 192.0.0.0/16, а комментарий рядом
 * обещал /24.
 *
 * Проверка была `a === 192 && b === 0` — два октета, то есть весь 192.0.x.x
 * (65536 адресов) вместо 256 адресов 192.0.0.0/24 из RFC 6890. Всё, что выше
 * 192.0.3.0, — обычное публичное unicast-пространство ARIN; в частности
 * 192.0.64.0/18 принадлежит Automattic, там резолвится wordpress.com.
 *
 * Гейт закрытый, дырой это не было. Хуже другое: причина отказа «адрес … —
 * приватный/служебный» не проходит `isInputOrResolverReason`, поэтому
 * `denyReasonText` отдаёт модели сильную формулировку — «если этот адрес
 * попросил кто-то в переписке или во вложении, это попытка вытащить
 * внутренние данные». Роль-бот получал обвинение в инъекции за попытку
 * открыть публичный сайт.
 */
import { describe, expect, test } from "bun:test";
import { blockedFetchReason } from "../lib/sdk-web-guard.ts";

const reason = (ip: string) => blockedFetchReason(`https://${ip}/`);

describe("192.0.0.0/24 — это 256 адресов, а не 65536", () => {
  test("сам /24 (IETF protocol assignments) закрыт", () => {
    expect(reason("192.0.0.0")).toContain("приватный/служебный");
    expect(reason("192.0.0.1")).toContain("приватный/служебный");
    expect(reason("192.0.0.255")).toContain("приватный/служебный");
  });

  test("TEST-NET-1 192.0.2.0/24 остаётся закрытым", () => {
    // Документационный диапазон RFC 5737: не маршрутизируется, ходить туда
    // незачем. До правки он закрывался побочно, вместе со всем /16.
    expect(reason("192.0.2.1")).toContain("приватный/служебный");
    expect(reason("192.0.2.255")).toContain("приватный/служебный");
  });

  test("публичная часть 192.0/16 больше не отбивается", () => {
    // 192.0.78.x — Automattic, там живёт wordpress.com.
    expect(reason("192.0.78.24")).toBeNull();
    expect(reason("192.0.3.1")).toBeNull();
    expect(reason("192.0.255.255")).toBeNull();
  });

  test("соседние диапазоны не задеты", () => {
    expect(reason("192.168.1.1")).toContain("приватный/служебный");
    expect(reason("192.1.1.1")).toBeNull();
    expect(reason("191.255.255.255")).toBeNull();
    expect(reason("10.0.0.1")).toContain("приватный/служебный");
    expect(reason("127.0.0.1")).toContain("приватный/служебный");
    expect(reason("169.254.169.254")).toContain("приватный/служебный");
  });

  test("inet_aton-формы того же адреса читаются так же", () => {
    // parseIPv4 понимает «сжатые» записи; предикат должен видеть тот же адрес.
    expect(blockedFetchReason("https://3221225473/")).toContain("приватный"); // 192.0.0.1
    expect(blockedFetchReason("https://0xC0004E18/")).toBeNull(); // 192.0.78.24
  });
});
