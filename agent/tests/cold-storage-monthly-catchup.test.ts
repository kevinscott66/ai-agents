/**
 * Аудит 2026-08-12: месячная выгрузка в холодное хранилище пропускала месяц целиком.
 *
 * Суточный прогон обслуживания стоит на маркере в БД (`maint_state.daily_ymd`,
 * миграция 039) — именно затем, чтобы «пропуск одних суток догонялся
 * следующими»: так написано в комментарии к runDaily. Все шаги внутри и правда
 * инкрементальны — кроме одного:
 *
 *   if (nowProvider().getUTCDate() === 1) { exportColdStorage() … }
 *
 * Это не маркер, а календарная проверка: шаг выполняется, только если суточный
 * прогон случился ИМЕННО первого числа. Замер (probe, шедулер с подменённым
 * nowProvider, 30 августа → 1 октября, процесс лежал ровно сутки 1 сентября):
 *
 *   суточных прогонов: 32 из 33 (1 сентября процесс лежал)
 *   месячная выгрузка запускалась: 2026-10-01
 *
 * То есть один пропущенный день стоил месяца: *_archive рос ещё 30 суток, а в
 * логе — ни строки, потому что шаг просто не вызывался. Ровно тот же дефект и
 * ровно на этом же шедулере чинили 2026-08-04 для суточного прогона: состояние
 * жило в памяти процесса, рестарт его терял. Здесь состояние не хранится вовсе.
 *
 * Второе: соседние шаги (archive, compact) при исключении зовут emitAlert, а
 * этот — только log.warn. Тихо упавшая выгрузка означает БД, которая растёт
 * без ограничения, и узнать об этом было неоткуда.
 *
 * Инвариант: выгрузка происходит один раз в календарный месяц — в первый
 * суточный прогон этого месяца, какого бы числа он ни случился.
 */
import { describe, test, expect, beforeEach } from "bun:test";
import { startMaintScheduler } from "../lib/db-maint.ts";
import { db } from "../lib/db.ts";

const MARKER = "cold_storage_ym";

function wipeMarkers() {
  db.prepare("DELETE FROM maint_state WHERE key IN ('daily_ymd', ?)").run(MARKER);
}

beforeEach(wipeMarkers);

/**
 * Прогоняет шедулер по списку дат и возвращает те, в которые выгрузка
 * состоялась. Даты — это дни, когда процесс был жив в суточное окно.
 */
function runDays(days: string[], opts: { fail?: boolean } = {}): string[] {
  const fired: string[] = [];
  let now = new Date();
  const h = startMaintScheduler({
    nowProvider: () => now,
    // Таймеры в тесте не нужны: суточный прогон дёргаем руками.
    dailyPollMs: 10_000_000,
    gcIntervalMs: 10_000_000,
    exportColdStorageImpl: () => {
      fired.push(now.toISOString().slice(0, 10));
      if (opts.fail) throw new Error("диск кончился");
      return [];
    },
  });
  try {
    for (const d of days) {
      now = new Date(`${d}T05:00:00.000Z`);
      h._runDailyNow();
    }
  } finally {
    h.stop();
  }
  return fired;
}

describe("месячная выгрузка держится за календарь, а не за первое число", () => {
  test("пропущенное первое число догоняется вторым, а не следующим месяцем", () => {
    // Сцена из шапки: 1 сентября процесс лежал.
    const fired = runDays(["2026-08-30", "2026-08-31", "2026-09-02", "2026-09-03"]);
    expect(fired).toEqual(["2026-08-30", "2026-09-02"]);
  });

  test("в течение месяца — ровно один раз", () => {
    const fired = runDays([
      "2026-09-01",
      "2026-09-02",
      "2026-09-15",
      "2026-09-30",
    ]);
    expect(fired).toEqual(["2026-09-01"]);
  });

  test("новый месяц — новый прогон", () => {
    const fired = runDays(["2026-09-20", "2026-10-01", "2026-10-02", "2026-11-04"]);
    expect(fired).toEqual(["2026-09-20", "2026-10-01", "2026-11-04"]);
  });

  test("маркер переживает рестарт процесса", () => {
    expect(runDays(["2026-09-05"])).toEqual(["2026-09-05"]);
    // Второй шедулер — это и есть рестарт: замыкание новое, БД та же.
    expect(runDays(["2026-09-06"])).toEqual([]);
  });

  test("упавшая выгрузка не роняет суточный прогон и не крутится каждый день", () => {
    const fired = runDays(["2026-09-10", "2026-09-11"], { fail: true });
    expect(fired).toEqual(["2026-09-10"]);
    // Маркер ставится до работы — как у суточного: повторять ежедневно то, что
    // пишет и удаляет файлы на диске, дороже, чем подождать следующего месяца.
    // Зато о падении теперь говорит алерт, а не одна строка log.warn.
    expect(
      db.prepare("SELECT value FROM maint_state WHERE key = ?").get(MARKER),
    ).toMatchObject({ value: "2026-09" });
  });
});
