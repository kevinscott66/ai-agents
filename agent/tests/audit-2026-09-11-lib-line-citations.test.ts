import { describe, expect, test } from "bun:test";
import { readFileSync, readdirSync, statSync } from "node:fs";
import { join } from "node:path";

const LIB = join(import.meta.dir, "..", "lib");

function walk(root: string, out: string[] = []): string[] {
  for (const name of readdirSync(root)) {
    const p = join(root, name);
    if (statSync(p).isDirectory()) walk(p, out);
    else if (/\.tsx?$/.test(p)) out.push(p);
  }
  return out;
}

const FILES = walk(LIB);

describe("комментарии в lib/ не ссылаются на номера строк", () => {
  test("есть что проверять", () => {
    // Если обход сломается и вернёт пусто, оба теста ниже пройдут вхолостую.
    expect(FILES.length).toBeGreaterThan(40);
  });

  test("ни одной ссылки вида file.ts:<строка> в lib/**", () => {
    const bad: string[] = [];
    for (const f of FILES) {
      const lines = readFileSync(f, "utf8").split("\n");
      for (let i = 0; i < lines.length; i++) {
        if (/[A-Za-z0-9_./-]+\.tsx?:\d/.test(lines[i]!)) {
          bad.push(`${f.slice(LIB.length + 1)}:${i + 1}: ${lines[i]!.trim()}`);
        }
      }
    }
    expect(bad).toEqual([]);
  });

  test("ни одной голой координаты вида (:173) или , :428 в lib/**", () => {
    const bad: string[] = [];
    for (const f of FILES) {
      const lines = readFileSync(f, "utf8").split("\n");
      for (let i = 0; i < lines.length; i++) {
        if (/\(:\d|, :\d/.test(lines[i]!)) {
          bad.push(`${f.slice(LIB.length + 1)}:${i + 1}: ${lines[i]!.trim()}`);
        }
      }
    }
    expect(bad).toEqual([]);
  });
});
