/**
 * Инцидент 2026-08-14: сайт стоял с 08-13 по 08-19, семь дней.
 *
 * Часть причин была внешней (недельный лимит подписки на VPS), но одна —
 * своя: TTL неодобренного черновика был равен периоду таймера, ровно 24ч.
 * Черновик от 08-13 08:05 на прогоне 08-14 08:00 считался живым ещё пять
 * минут, и `pendingAwaitingApproval()` останавливал выпуск:
 *
 *   Aug 14 08:00:08 [daily-draft] черновик от 2026-08-13T08:05:31.241Z
 *                   ещё ждёт апрува (msg 41544) — второй не шлём
 *
 * То есть один невнимательный день владельца стоил ДВУХ дней выпуска, и так
 * при любом дрейфе старта: systemd стартует не секунда в секунду, а черновик
 * пишется на несколько минут позже начала прогона (ресёрч + баннер + отправка).
 *
 * Инвариант: TTL строго меньше периода таймера, с запасом на этот дрейф.
 */
import { describe, test, expect } from "bun:test";
import { PENDING_MAX_AGE_MS } from "../tools/daily-draft.ts";
import { MAX_AGE_MS as APPROVE_POLL_MAX_AGE_MS } from "../tools/approve-poll.ts";

/** delabs-daily-draft.timer — OnCalendar=*-*-* 08:00:00 UTC. */
const DRAFT_PERIOD_MS = 24 * 60 * 60 * 1000;

/**
 * Запас на дрейф: ресёрч через SDK до 600с по TimeoutStartSec, плюс рендер
 * баннера и две отправки в Telegram. Час покрывает это с головой.
 */
const DRIFT_MARGIN_MS = 60 * 60 * 1000;

describe("TTL неодобренного черновика", () => {
  test("протухает раньше следующего прогона таймера", () => {
    expect(PENDING_MAX_AGE_MS).toBeLessThanOrEqual(
      DRAFT_PERIOD_MS - DRIFT_MARGIN_MS,
    );
  });

  test("живёт достаточно долго, чтобы владелец успел ответить за рабочий день", () => {
    expect(PENDING_MAX_AGE_MS).toBeGreaterThanOrEqual(12 * 60 * 60 * 1000);
  });

  // Если poll держит апрув дольше, чем draft считает слот занятым, между двумя
  // порогами появляется окно, в котором новый черновик затирает pending, на
  // который владелец вот-вот поставит ✅ — апрув уходит в никуда (ровно та
  // болезнь, которую лечил аудит 2026-08-12).
  test("совпадает с порогом approve-poll", () => {
    expect(APPROVE_POLL_MAX_AGE_MS).toBe(PENDING_MAX_AGE_MS);
  });
});
