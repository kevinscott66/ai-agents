/**
 * Аудит 2026-08-28: однострочный забор съедал первое слово кода, а то и весь код.
 *
 * Регулярка шага 1 была `/```[a-zA-Z0-9_+-]*\n?([\s\S]*?)```/`: метка языка
 * жадная и НЕ привязана к концу строки. Когда открывающий и закрывающий заборы
 * стоят на одной строке, `[a-zA-Z0-9_+-]*` забирает первый латинский токен
 * кода как «язык», а ленивая группа — остаток. Если код — одно латинское
 * слово, группа пустеет целиком: `"```code```"` давало `<pre></pre>`.
 *
 * Молча: HTML валиден, 400 от Telegram нет, плейн-фолбэк не срабатывает —
 * сообщение уходит успешно с вырезанным куском. Путь общий и для чата, и для
 * канала: mdToUserbotHtml зовёт тот же конвертер.
 *
 * Правка: метка языка засчитывается, только если за ней (с точностью до
 * пробелов) идёт перевод строки — как того и требует CommonMark, где info
 * string живёт на строке открывающего забора.
 */
import { describe, expect, test } from "bun:test";
import { mdToTelegramHtml } from "../lib/telegram-format.ts";

describe("однострочный забор", () => {
  test("код из одного слова не исчезает", () => {
    expect(mdToTelegramHtml("```code```")).toBe("<pre>code</pre>");
  });

  test("первое слово команды остаётся на месте", () => {
    expect(mdToTelegramHtml("Запусти ```npm install``` и всё")).toBe(
      "Запусти <pre>npm install</pre> и всё",
    );
  });

  test("два забора в строке не обкусываются каждый", () => {
    expect(mdToTelegramHtml("a ```x``` b ```y``` c")).toBe(
      "a <pre>x</pre> b <pre>y</pre> c",
    );
  });

  test("слово, совпадающее с именем языка, остаётся кодом", () => {
    // Раньше `ts` списывалось в метку языка и блок выходил пустым.
    expect(mdToTelegramHtml("```ts```")).toBe("<pre>ts</pre>");
  });
});

describe("многострочный забор разбирается как прежде", () => {
  test("метка языка по-прежнему съедается", () => {
    expect(mdToTelegramHtml("```js\nlet a=1;\n```")).toBe("<pre>let a=1;</pre>");
  });

  test("забор без метки языка", () => {
    expect(mdToTelegramHtml("```\nnpm install\n```")).toBe("<pre>npm install</pre>");
  });

  test("метка с хвостовыми пробелами тоже съедается", () => {
    // `[ \t]*` перед переводом строки: info string по CommonMark может иметь
    // хвостовой пробел, и до правки он ломал разбор в другую сторону —
    // в <pre> уезжал сам перевод строки.
    expect(mdToTelegramHtml("```js \ncode```")).toBe("<pre>code</pre>");
  });

  test("закрывающий забор без перевода строки перед ним", () => {
    expect(mdToTelegramHtml("```python\nprint(1)```")).toBe("<pre>print(1)</pre>");
  });

  test("содержимое по-прежнему экранируется", () => {
    expect(mdToTelegramHtml("```sh\ncd agent && bun test\n```")).toBe(
      "<pre>cd agent &amp;&amp; bun test</pre>",
    );
  });

  test("пустой забор остаётся пустым", () => {
    expect(mdToTelegramHtml("``````")).toBe("<pre></pre>");
  });
});
