/**
 * Аудит 2026-09-11, круг 51: обоснование, державшееся на ссылке, которую в
 * этом дереве проверить нечем.
 *
 * Шапка lib/test-run-marker.ts объясняет, зачем у детектора тест-прогона ТРИ
 * признака, а не два, и обоснование сводилось к фразе «обе половины описаны в
 * репозитории как обычная практика: CLAUDE.md §3.8.1». Две беды сразу:
 *   • подраздела §3.8.1 нет. В CLAUDE.md есть §3.8 («Pre-push gate»), а
 *     «3.8.1» встречается там только двумя обратными ссылками на него же;
 *   • CLAUDE.md вообще не входит в репозиторий. Значит, сторож протухших
 *     координат (`audit-2026-09-11-stale-line-coordinates.test.ts`) этой
 *     ссылки не видит по построению — `resolveTarget` ищет цель В ДЕРЕВЕ.
 *
 * Второе тут дороже первого. Ссылка наружу — это обещание, которое никто не
 * проверяет, и живёт оно ровно до тех пор, пока кто-нибудь не пойдёт по ней
 * проверять, не избыточен ли третий признак. Не найдя раздела, он с равной
 * вероятностью снесёт признак или потратит час. Поэтому факт, ради которого
 * ссылались, записан на месте, а сторож ниже следит, чтобы он там остался.
 *
 * ЧЕГО СТОРОЖ НЕ ДЕЛАЕТ. Он не запрещает ссылаться на CLAUDE.md вообще: в
 * дереве есть честные ссылки (§3.4 в lib/figma.ts, §6 в
 * lib/agent-sdk-runtime.ts), и они несут смысл. Он держит ровно один случай —
 * тот, где внешняя ссылка была ЕДИНСТВЕННЫМ обоснованием защитного признака.
 */
import { describe, test, expect } from "bun:test";
import { execFileSync } from "node:child_process";
import { readFileSync } from "node:fs";
import { join } from "node:path";
import { isTestRun } from "../lib/test-run-marker.ts";

const SRC = readFileSync(join(import.meta.dir, "..", "lib", "test-run-marker.ts"), "utf8");
/** Докблоки несут ` * ` в каждой строке — сплющиваем, иначе не найти фразу. */
const FLAT = SRC.replace(/^\s*\*/gm, "").replace(/\s+/g, " ");
/** Действующая часть шапки: разбор ниже цитирует прежнюю неправду нарочно. */
const ACTIVE = FLAT.slice(0, FLAT.indexOf("Аудит 2026-09-11, круг 51:"));
const POSTMORTEM = FLAT.slice(FLAT.indexOf("Аудит 2026-09-11, круг 51:"));

describe("обоснование третьего признака стоит на своих ногах", () => {
  test("CLAUDE.md в репозитории нет — сторожу координат ссылка не видна", () => {
    // Замер, а не предположение: именно из-за этого ссылка и уцелела.
    let inRepo = true;
    try {
      execFileSync("git", ["cat-file", "-e", "HEAD:CLAUDE.md"], {
        cwd: join(import.meta.dir, "..", ".."),
        stdio: "ignore",
      });
    } catch {
      inRepo = false;
    }
    expect(inRepo).toBe(false);
  });

  test("действующая часть шапки на номер раздела не ссылается", () => {
    // Правило круга 20: протухший номер убирают, а не подгоняют.
    expect(ACTIVE).not.toContain("§3.8.1");
    expect(ACTIVE).not.toMatch(/CLAUDE\.md\s*§/);
    // А разбор — цитирует, иначе следующий читатель не поймёт, чего не стало.
    expect(POSTMORTEM).toContain("CLAUDE.md §3.8.1");
  });

  test("оба факта, ради которых ссылались, названы на месте", () => {
    expect(ACTIVE).toContain("из корня репозитория");
    expect(ACTIVE).toContain("NODE_ENV=production");
    expect(ACTIVE).toContain("set -a; . /opt/agent-team/.env; set +a");
  });

  test("сам третий признак на месте, а не только проза о нём", () => {
    // Иначе сторож охранял бы объяснение механизма, которого нет.
    expect(SRC).toContain("Bun.main");
    // Под тест-раннером детектор обязан быть поднят — мы внутри него.
    expect(isTestRun()).toBe(true);
  });
});
