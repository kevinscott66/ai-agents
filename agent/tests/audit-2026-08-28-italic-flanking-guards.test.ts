/**
 * Аудит 2026-08-28: курсив открывался и закрывался на пробеле.
 *
 * Правило шага 9 было `/(^|[^*\p{L}\p{N}_])\*([^\n*]+?)\*(?!\*)/gu`: символ
 * ПЕРЕД открывающей звёздочкой проверялся, а вокруг самой пары — нет. У
 * жирного такая охрана появилась ещё 2026-08-27 (`(?=[^\s*])`, чтобы не
 * схлопывать `** **`), у курсива её не было ни с одной стороны.
 *
 * CommonMark обе стороны и запрещает: звёздочка, за которой идёт пробел, не
 * открывает эмфазу, а звёздочка, перед которой пробел, — не закрывает.
 *
 * Молча: HTML валиден, 400 от Telegram нет, отката нет — читатель просто
 * получает текст, из которого убрали звёздочки и добавили курсив.
 */
import { describe, expect, test } from "bun:test";
import { mdToTelegramHtml } from "../lib/telegram-format.ts";

describe("звёздочка на пробеле не размечает", () => {
  test("умножение остаётся умножением", () => {
    expect(mdToTelegramHtml("Цена 5 * 3 рублей и ещё 2 * 8")).toBe(
      "Цена 5 * 3 рублей и ещё 2 * 8",
    );
  });

  test("глоб-маски не теряют звёздочку", () => {
    expect(mdToTelegramHtml("Путь C:\\temp\\*.log и *.txt")).toBe(
      "Путь C:\\temp\\*.log и *.txt",
    );
  });

  test("три звёздочки подряд в арифметике", () => {
    expect(mdToTelegramHtml("5 * 3 * 7")).toBe("5 * 3 * 7");
  });

  test("закрывающая звёздочка после пробела не закрывает", () => {
    expect(mdToTelegramHtml("*a b *c")).toBe("*a b *c");
  });

  test("открывающая звёздочка перед пробелом не открывает", () => {
    expect(mdToTelegramHtml("текст * ещё* хвост")).toBe("текст * ещё* хвост");
  });
});

describe("настоящий курсив по-прежнему курсив", () => {
  test("одиночное слово", () => {
    expect(mdToTelegramHtml("*курсив*")).toBe("<i>курсив</i>");
  });

  test("две пары в строке не слипаются", () => {
    expect(mdToTelegramHtml("*a* и *b*")).toBe("<i>a</i> и <i>b</i>");
  });

  test("курсив внутри предложения", () => {
    expect(mdToTelegramHtml("начало *к* конец")).toBe("начало <i>к</i> конец");
  });

  test("курсив в скобках", () => {
    expect(mdToTelegramHtml("(*x*)")).toBe("(<i>x</i>)");
  });

  test("курсив из одной кириллической буквы", () => {
    expect(mdToTelegramHtml("*ы*")).toBe("<i>ы</i>");
  });

  test("курсив с пробелами внутри", () => {
    expect(mdToTelegramHtml("*два слова*")).toBe("<i>два слова</i>");
  });

  test("жирный не задет", () => {
    expect(mdToTelegramHtml("**жирный**")).toBe("<b>жирный</b>");
  });

  test("маркер списка не превращается в курсив", () => {
    expect(mdToTelegramHtml("* пункт списка")).toBe("• пункт списка");
  });

  test("внутрисловная звёздочка по-прежнему не размечает", () => {
    expect(mdToTelegramHtml("a*b*c")).toBe("a*b*c");
  });
});
