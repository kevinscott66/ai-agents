/**
 * Можно ли этому пользователю нажимать то, что закрыто админом на сервере.
 *
 * Аудит 2026-08-20: страница «Задачи» рисовала «+ Новая задача», быстрые
 * действия и кнопки переходов всем одинаково, хотя сервер закрывает и создание
 * (lib/miniapp-server.ts:1008), и смену статуса (:1068) админом. Не-админ
 * заполнял форму, жал «Создать» и получал тост «admin only» — сырой английской
 * строкой на полторы секунды.
 *
 * Признак берём там же, где его берёт Dashboard: `GET /api/autonomy` отдаёт
 * `admin` любому allowlisted пользователю. Инвариант общий для Mini App
 * (tests/miniapp-admin-flag.test.ts): про свои права клиенту говорит сервер, а
 * не коды ошибок ручки, которая этих кодов заранее не отдаёт.
 *
 * Живёт в lib, а не рядом с одной страницей: с аудита 2026-08-28 по нему же
 * закрыта кнопка «Остановить всё» на вкладке Mac.
 */
export function adminFromAutonomy(res: { admin?: boolean } | null): boolean {
  // Отказ читается как «не знаем». Показать кнопку, которая гарантированно
  // вернёт 403, хуже, чем не показать её.
  if (!res) return false;
  // Поля нет — бэкенд старее клиента; отбирать кнопки у настоящего админа
  // из-за рассинхрона версий было бы хуже, чем показать лишнюю.
  return res.admin ?? true;
}
