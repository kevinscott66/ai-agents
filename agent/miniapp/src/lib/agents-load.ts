/**
 * Справочник агентов для выпадающих списков.
 *
 * Аудит 2026-08-28: Logs и Tasks обе делали
 * `api.agents().then((r) => setAgents(r.agents)).catch(() => {})`.
 *
 * Не ронять страницу из-за справочного запроса — верно: список действий и
 * список задач приходят своими вызовами и от этого не зависят. Но отказ не
 * оставлял вообще никакого следа: список молча оставался пустым, и пустой
 * `<select>` выглядит ровно как «агентов нет», а не как «спросить не удалось».
 *
 * Хуже всего в модалке новой задачи (Tasks): там из этого же списка выбирают
 * исполнителя, и молчаливый отказ превращается в «задачу не на кого назначить»
 * без единого слова о причине.
 *
 * Поэтому отказ здесь по-прежнему не бросает, но запоминается — а страницы
 * подписывают им сам список.
 */
import type { AgentInfo } from "./types";

export interface AgentsState {
  agents: AgentInfo[];
  /** Запрос ответил отказом. Пустой список без отказа — это просто пусто. */
  failed: boolean;
}

export const AGENTS_EMPTY: AgentsState = { agents: [], failed: false };

/** Никогда не бросает: вызывающий рисует список, а не обрабатывает ошибку. */
export async function loadAgents(
  fetchAgents: () => Promise<{ agents: AgentInfo[] }>,
): Promise<AgentsState> {
  try {
    const r = await fetchAgents();
    // Ответ без массива — тот же отказ по сути: выбирать не из чего, а причина
    // на стороне сервера. Молчать о нём так же нельзя.
    return Array.isArray(r?.agents)
      ? { agents: r.agents, failed: false }
      : { agents: [], failed: true };
  } catch {
    return { agents: [], failed: true };
  }
}

/**
 * Подпись внутри списка — отдельным disabled-пунктом, а не строкой рядом:
 * так она попадает ровно туда, куда смотрит пользователь, и не трогает вёрстку
 * фильтров (в Tasks они лежат в одном flex-ряду).
 *
 * Молчим, если что-то всё же приехало: неполный список лучше, чем пугающая
 * надпись поверх работающего фильтра.
 */
export function agentsHint(state: AgentsState): string | null {
  return state.failed && state.agents.length === 0
    ? "список не загрузился — обнови страницу"
    : null;
}
