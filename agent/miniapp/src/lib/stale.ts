import { useRef } from "react";

/**
 * Защита от «ответ на устаревший запрос перезаписал свежие данные».
 *
 * Аудит 2026-08-11. Страницы Mini App грузятся так: `load()` ставит
 * `setLoading(true)`, ждёт ответа и кладёт результат в состояние. Кто пришёл
 * последним — тот и записал. Порядок ответов сети не гарантирован, а `load()`
 * вызывается не только руками:
 *
 *  • Tasks: на каждое изменение фильтра И на каждое событие task.created /
 *    task.updated от любого из 12 агентов в любом чате. Быстрая смена фильтра
 *    → ответ на старый фильтр приезжает вторым и показывает не тот список,
 *    какой выбран в UI. Само по себе это не чинится: следующий рендер данные
 *    не перезапросит.
 *
 *  • Approvals: `decideMany` оптимистично убирает строки, зовёт API и делает
 *    `load()`. Параллельно то же решение прилетает событием approval.decided —
 *    ещё один `load()`. Если запрос, ушедший ДО записи в БД, вернётся позже,
 *    только что одобренный апрув воскреснет в списке — и его предложат
 *    одобрить второй раз.
 *
 * Приём стандартный: у каждого запуска свой номер, применяем результат, только
 * если наш номер всё ещё последний. Отдельная функция, а не «просто ref в
 * компоненте», чтобы у всех страниц это было одинаково и проверялось тестом.
 */
export function createLatestRun(): () => () => boolean {
  let seq = 0;
  return () => {
    const mine = ++seq;
    return () => mine === seq;
  };
}

/**
 * Хук-обёртка. Возвращает функцию «начать заход»: зови её в начале загрузки
 * и получишь `isCurrent()` — предикат «мой запрос всё ещё актуален».
 *
 * ```ts
 * const beginLoad = useLatestRun();
 * async function load() {
 *   const isCurrent = beginLoad();
 *   const r = await api.tasks(...);
 *   if (!isCurrent()) return;
 *   setTasks(r.tasks);
 * }
 * ```
 *
 * `setLoading(false)` тоже под предикатом: устаревший запрос не должен гасить
 * индикатор, пока актуальный ещё в пути.
 */
export function useLatestRun(): () => () => boolean {
  const ref = useRef<(() => () => boolean) | null>(null);
  if (ref.current === null) ref.current = createLatestRun();
  return ref.current;
}
