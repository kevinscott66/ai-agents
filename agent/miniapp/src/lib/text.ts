/**
 * Обрезка длинного текста для превью.
 *
 * Аудит 2026-08-21: в четырёх местах Mini App текст резали по-разному, и три
 * идиомы из четырёх врали пользователю:
 *
 *   • `Agents.tsx` — `{action.error.slice(0, 100)}...` без всякого условия.
 *     Ошибки агентов почти все короче ста символов («timeout», «HTTP 429»), и
 *     каждая показывалась как «timeout...» — то есть как обрезанная. Читатель
 *     ищет продолжение, которого нет, и не верит уже ни одной строке: понять,
 *     где многоточие настоящее, а где приписано, по экрану нельзя.
 *   • `Logs.tsx` — `` ` · ${a.error.slice(0, 80)}` `` вообще без метки. Ошибка
 *     на 300 символов выглядела законченной фразой, оборванной на полуслове.
 *     Это хуже лишнего многоточия: там видно, что чего-то не хватает, здесь —
 *     нет.
 *   • `Mac.tsx` — условие правильное, но метка из трёх точек ASCII, а не «…».
 *
 * Правильной была одна `InterAgentCard.tsx`. Теперь правило одно на всех и
 * проверяется тестом: метка ставится, только если что-то действительно
 * отрезано, метка — «…», и длина результата не превышает лимит (сама метка
 * входит в бюджет, иначе «обрезано до 100» на деле давало 101).
 */

/** Символ обрезки. Один код-поинт, а не три точки: так его видно в поиске. */
export const ELLIPSIS = "…";

export function ellipsize(text: string, max: number): string {
  const s = text ?? "";
  if (max <= 0) return "";
  if (s.length <= max) return s;
  // trimEnd, чтобы не получить «слово …»: пробел перед меткой читается как
  // конец предложения.
  return s.slice(0, max - 1).trimEnd() + ELLIPSIS;
}
